#!/usr/bin/env node
/* eslint-disable no-await-in-loop -- Compare/write generated outputs sequentially with exact provenance. */
import { format, resolveConfig } from 'prettier'
import { readFile, writeFile } from 'node:fs/promises'
import { createHash } from 'node:crypto'
import { extractClaudeRootRegistrations, registrationNames } from './lib/claudeRootRegistry.mjs'

const check = process.argv.includes('--check')
const path = process.argv.slice(2).find(arg => arg !== '--check')
if (!path) {
  throw new Error(
    'Provide the installed Claude Code 2.1.322 executable path; this command only reads it.',
  )
}
const bytes = await readFile(path)
const source = bytes.toString('utf8')
if (!source.includes('// Version: 2.1.322')) {
  throw new Error('The installed Claude Code version is not the pinned 2.1.322.')
}
const registrations = extractClaudeRootRegistrations(source)
const commands = [
  ...new Set(registrations.flatMap(row => registrationNames(row.expression))),
].sort()
const table = `// Generated by scripts/generate-claude-command-registry.mjs from Claude Code 2.1.322.\n// Do not edit by hand. The source audit is pinned in tests/fixtures/provider-argv/claudeRegistrySource.json.\nexport const CLAUDE_ROOT_COMMANDS: readonly string[] = ${JSON.stringify(commands, null, 2)}\n`
const audit =
  JSON.stringify(
    { version: '2.1.322', sha256: createHash('sha256').update(bytes).digest('hex'), registrations },
    null,
    2,
  ) + '\n'
for (const [target, value] of [
  ['src/contexts/agent/domain/claudeRootCommands.generated.ts', table],
  ['tests/fixtures/provider-argv/claudeRegistrySource.json', audit],
  ['tests/fixtures/provider-argv/claudeRegistry.json', JSON.stringify(commands, null, 2) + '\n'],
]) {
  const formatted = await format(value, {
    ...(await resolveConfig(target)),
    parser: target.endsWith('.ts') ? 'typescript' : 'json',
  })
  if (check) {
    if ((await readFile(target, 'utf8')) !== formatted) {
      throw new Error(
        `Registry differs from installed source: ${target}; regenerate then format generated files.`,
      )
    }
  } else {
    await writeFile(target, formatted)
  }
}
process.stdout.write(
  `Verified ${commands.length} root command names/aliases from ${registrations.length} registrations (including plugins).\n`,
)
