import { attachClearReadinessFailure } from './claude-clear-diagnostics.helpers'
import type { ChildProcessWithoutNullStreams } from 'node:child_process'
import { rm, readFile, access } from 'node:fs/promises'
import { expect, test, type ElectronApplication } from '@playwright/test'
import type { AgentRunSnapshot } from '../../src/shared/contracts/dto/agentRunState'
import type { CreateNodeResult } from '../../src/shared/contracts/dto/nodeControl'
import { clearConversation } from './agent.resident-context.helpers'
import {
  createClearHarness,
  captureWorkerOutput,
  waitForReply,
  readRecords,
  promptA,
  promptB,
  attachScreen,
  preserveFailureEvidence,
  type Hook,
} from './recovery.claude-clear.helpers'
import { launchApp, seedWorkspaceState, removePathWithRetry } from './workspace-canvas.helpers'
import { startWorker, stopWorker } from './worker-client.helpers'
import { getBinding, cliCommand } from './recovery.managed-claude-launch-lifecycle.helpers'
import { terminalCommand, jsonOutput } from './cli.terminal.helpers'
import { readRuntimeSessionId } from './workspace-canvas.terminal-agent-overlay.helpers'

test.describe('first CLI prompt after real Claude clear', () => {
  test.skip(
    process.env.OPENCOVE_TEST_USE_REAL_AGENTS !== '1',
    'Requires isolated Claude Code 2.1.321 or 2.1.322',
  )
  test.skip(process.platform === 'win32', 'POSIX CLI instrumentation')
  for (const slowHook of [false, true]) {
    test(`submits first B through the CLI with ${slowHook ? 'a slow background hook' : 'normal hooks'}`, async ({
      browserName: _browserName,
    }, testInfo) => {
      test.setTimeout(180_000)
      const h = await createClearHarness(testInfo)
      const env = { ...h.env, ...(slowHook ? { OPENCOVE_TEST_CLEAR_HOOK_DELAY_MS: '8000' } : {}) }
      let worker: ChildProcessWithoutNullStreams | null = null,
        app: ElectronApplication | null = null
      const hold = h.env.OPENCOVE_TEST_CLAUDE_CLEAR_PROOF_HOLD
      try {
        worker = (await startWorker({ userDataDir: h.userDataDir, env })).child
        captureWorkerOutput(worker, testInfo)
        const launched = await launchApp({
          userDataDir: h.userDataDir,
          cleanupUserDataDir: false,
          env,
        })
        app = launched.electronApp
        const page = launched.window
        await seedWorkspaceState(page, {
          activeWorkspaceId: 'prompt-clear-project',
          settings: {
            defaultProvider: 'claude-code',
            agentResidentContext: 'off',
            agentFullAccess: false,
          },
          workspaces: [
            {
              id: 'prompt-clear-project',
              name: 'Clear prompt',
              path: h.workspace,
              activeSpaceId: 'prompt-clear-space',
              spaces: [
                {
                  id: 'prompt-clear-space',
                  name: 'Main',
                  directoryPath: h.workspace,
                  nodeIds: ['prompt-clear-task'],
                  rect: { x: 0, y: 0, width: 5000, height: 3000 },
                },
              ],
              nodes: [
                {
                  id: 'prompt-clear-task',
                  kind: 'task',
                  title: 'Clear prompt',
                  position: { x: 100, y: 80 },
                  width: 460,
                  height: 280,
                  task: {
                    requirement: promptA,
                    status: 'todo',
                    linkedAgentNodeId: null,
                    lastRunAt: null,
                    autoGeneratedTitle: false,
                  },
                },
              ],
            },
          ],
        })
        await page.getByTestId('task-node-run-agent').click()
        await expect(page.locator('.terminal-node')).toHaveCount(1)
        const nodeId = await page
          .locator('.terminal-node')
          .evaluate(el => el.closest('.react-flow__node')!.getAttribute('data-id')!)
        await waitForReply(h.hookLog, 'REPLY_A')
        const snapshot = () =>
          page.evaluate(
            id =>
              window.opencoveApi.controlSurface.invoke<AgentRunSnapshot>({
                kind: 'query',
                id: 'agent.get',
                payload: { nodeId: id },
              }),
            nodeId,
          )
        await expect.poll(async () => (await snapshot()).state).toBe('idle')
        const aTurn = (await snapshot()).lastEndedTurn!.id
        const a = (await getBinding(page, nodeId)).tuple.resumeSessionId
        const terminal = await page.evaluate(() =>
          window.opencoveApi.controlSurface.invoke<CreateNodeResult>({
            kind: 'command',
            id: 'node.create',
            payload: {
              kind: 'terminal',
              space: { kind: 'spaceId', spaceId: 'prompt-clear-space' },
              data: { shell: '/bin/sh' },
            },
          }),
        )
        const caller = { nodeId: terminal.node.id, sessionId: terminal.node.sessionId! }
        const requestsBefore = h.api.main().length
        await clearConversation(page, (await readRuntimeSessionId(page, nodeId))!)
        const clears = async () =>
          (await readRecords<Hook>(h.hookLog)).filter(
            r => r.input.hook_event_name === 'SessionStart' && r.input.source === 'clear',
          )
        await expect.poll(async () => (await clears()).length).toBe(1)
        const b = (await clears())[0].input.session_id
        expect(b).not.toBe(a)
        const before = await readRecords<Hook>(h.hookLog)
        expect(
          before.filter(
            r =>
              r.input.session_id === b && ['Stop', 'StopFailure'].includes(r.input.hook_event_name),
          ),
        ).toHaveLength(0)
        try {
          await expect.poll(async () => (await snapshot()).state).toBe('idle')
        } catch (error) {
          await attachClearReadinessFailure(testInfo, {
            root: h.root,
            config: String(h.env.CLAUDE_CONFIG_DIR),
            hookLog: h.hookLog,
            successor: b,
            snapshot,
          }).catch(() => undefined)
          throw error
        }
        expect((await snapshot()).turn).toBeNull()
        await attachScreen(testInfo, page, 'empty-B-before-first-CLI-prompt')
        if (slowHook) {
          await expect(access(`${h.hookLog}.clear-hook-complete`)).rejects.toThrow()
        }
        const rawDelivery = await terminalCommand(
          page,
          caller,
          cliCommand(
            'agent',
            'prompt',
            '--node',
            nodeId,
            '--text',
            promptB,
            '--timeout',
            '15s',
            '-o',
            'json',
          ),
          'PROMPT_B',
        )
        if (slowHook && rawDelivery.includes('agent.prompt_stalled')) {
          expect(rawDelivery.replaceAll('\n', '')).toMatch(/"pasteDispatchAttempted"\s*:\s*true/)
          expect(rawDelivery.replaceAll('\n', '')).toMatch(/"submitDispatchAttempted"\s*:\s*true/)
          // An uncertain outcome permits no automatic second submission.
          await page.waitForTimeout(9000)
          expect(h.api.main().length - requestsBefore).toBeLessThanOrEqual(1)
          return
        }
        const delivered = jsonOutput(rawDelivery)
        expect(delivered).toMatchObject({ phase: 'submission_observed', textComparison: 'matched' })
        const bTurn = delivered.turnId as string
        expect(bTurn).not.toBe(aTurn)
        const waited = jsonOutput(
          await terminalCommand(
            page,
            caller,
            cliCommand('agent', 'wait', '--node', nodeId, '--turn', bTurn, '--timeout', '10s'),
            'WAIT_B',
          ),
        )
        expect(waited).toMatchObject({ turnId: bTurn, outcome: 'completed' })
        const read = async (turnId: string, label: string) =>
          jsonOutput(
            await terminalCommand(
              page,
              caller,
              cliCommand('agent', 'read', '--node', nodeId, '--turn', turnId, '-o', 'json'),
              label,
            ),
          )
        expect(await read(bTurn, 'READ_B')).toMatchObject({ turnId: bTurn, message: 'REPLY_B' })
        expect(await read(aTurn, 'READ_A')).toMatchObject({ turnId: aTurn, message: 'REPLY_A' })
        expect(h.api.main().slice(requestsBefore)).toEqual([expect.arrayContaining([promptB])])
        const hooks = (await readRecords<Hook>(h.hookLog)).filter(r => r.input.session_id === b)
        const submit = hooks.filter(r => r.input.hook_event_name === 'UserPromptSubmit')
        expect(submit).toHaveLength(1)
        expect(submit[0].input).toMatchObject({ prompt: promptB, prompt_id: delivered.promptId })
        expect(hooks.find(r => r.input.hook_event_name === 'Stop')?.input).toMatchObject({
          prompt_id: delivered.promptId,
          last_assistant_message: 'REPLY_B',
        })
        const transcript = (await readFile(submit[0].input.transcript_path!, 'utf8'))
          .split('\n')
          .filter(Boolean)
          .map(line => JSON.parse(line) as { type: string; sessionId?: string; promptId?: string })
        expect(transcript).toContainEqual(
          expect.objectContaining({ type: 'user', sessionId: b, promptId: delivered.promptId }),
        )
        await expect
          .poll(() => getBinding(page, nodeId))
          .toMatchObject({ tuple: { resumeSessionId: b, resumeSessionIdVerified: true } })
      } finally {
        await rm(hold, { force: true })
        await app?.close()
        await stopWorker(worker)
        await new Promise<void>(resolve => h.api.server.close(() => resolve()))
        await preserveFailureEvidence(h, testInfo)
        await removePathWithRetry(h.root)
      }
    })
  }
})
