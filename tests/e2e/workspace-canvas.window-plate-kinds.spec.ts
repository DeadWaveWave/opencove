/* eslint-disable no-await-in-loop -- Themes are read in turn in one Electron window. */
import { expect, test, type Locator, type Page } from '@playwright/test'
import { clearAndSeedWorkspace, launchApp, testWorkspacePath } from './workspace-canvas.helpers'
import { PIXEL_EFFECTS_DISABLED } from './workspace-canvas.pixel-effects.helpers'

/** Which kind's plate each window reads on (windowKindFamily.ts). */
const WINDOWS = [
  { selector: '.terminal-node:not(.terminal-node--agent)', family: 'shell', terminal: true },
  { selector: '.terminal-node--agent', family: 'ai', terminal: true },
  { selector: '.task-node', family: 'plan', terminal: false },
  { selector: '.note-node', family: 'knowledge', terminal: false },
] as const

/** A root token as the computed `rgb()` the plate paints. */
async function rootColour(window: Page, token: string): Promise<string> {
  return await window.evaluate(name => {
    const probe = document.body.appendChild(document.createElement('div'))
    probe.style.color = getComputedStyle(document.documentElement).getPropertyValue(name)
    const colour = getComputedStyle(probe).color
    probe.remove()
    return colour
  }, token)
}

/** What the window's plate paints, and for a terminal what fills behind xterm. */
async function readWindow(node: Locator, terminal: boolean) {
  return await node.evaluate((element, isTerminal) => {
    const plate = element.querySelector('[data-cove-part="window-plate"]')
    const fill = isTerminal ? element.querySelector('.terminal-node__terminal') : null
    return {
      plate: plate ? getComputedStyle(plate).backgroundColor : null,
      terminal: fill ? getComputedStyle(fill).backgroundColor : null,
    }
  }, terminal)
}

test.describe('Workspace Canvas - Window plate per kind', () => {
  test('each kind of window reads on its own plate, and on the theme plate with kind colours off', async () => {
    const { electronApp, window } = await launchApp()

    try {
      for (const uiTheme of ['dark', 'light'] as const) {
        await clearAndSeedWorkspace(
          window,
          [
            {
              id: 'kind-plate-terminal',
              title: 'shell',
              position: { x: 40, y: 80 },
              width: 420,
              height: 260,
            },
            {
              id: 'kind-plate-agent',
              title: 'codex · gpt-5.2-codex',
              position: { x: 500, y: 80 },
              width: 520,
              height: 300,
              kind: 'agent',
              status: 'running',
              startedAt: '2026-02-09T00:05:00.000Z',
              endedAt: null,
              exitCode: null,
              lastError: null,
              agent: {
                provider: 'codex',
                prompt: 'Read on the AI plate.',
                model: 'gpt-5.2-codex',
                effectiveModel: 'gpt-5.2-codex',
                launchMode: 'resume',
                resumeSessionId: '019c3e32-52ff-7b00-94ac-e6c5a56b4aa4',
                resumeSessionIdVerified: true,
                executionDirectory: testWorkspacePath,
                directoryMode: 'workspace',
                customDirectory: null,
                shouldCreateDirectory: false,
              },
            },
            {
              id: 'kind-plate-task',
              title: 'plan',
              position: { x: 40, y: 380 },
              width: 380,
              height: 300,
              kind: 'task',
              task: {
                requirement: 'Read on the plan plate.',
                status: 'todo',
                priority: 'medium',
                tags: [],
                linkedAgentNodeId: null,
                lastRunAt: null,
                autoGeneratedTitle: false,
              },
            },
            {
              id: 'kind-plate-note',
              title: 'knowledge',
              position: { x: 500, y: 420 },
              width: 320,
              height: 220,
              kind: 'note',
              task: { text: 'Read on the knowledge plate.' },
            },
          ],
          // Opaque terminals fill behind xterm with the terminal colour, so it can be read.
          { settings: { uiTheme, terminalBackground: 'opaque', ...PIXEL_EFFECTS_DISABLED } },
        )
        await expect
          .poll(() => window.evaluate(() => document.documentElement.dataset.coveTheme ?? null))
          .toBe(uiTheme)

        for (const kindColours of ['on', 'off'] as const) {
          await window.evaluate(state => {
            document.documentElement.dataset.coveKindColors = state
          }, kindColours)
          for (const { selector, family, terminal } of WINDOWS) {
            const node = window.locator(selector).first()
            await expect(node).toBeVisible()
            const expected = await rootColour(
              window,
              `--cove-kind-${kindColours === 'on' ? family : 'neutral'}-plate`,
            )
            const label = `${uiTheme} kind colours ${kindColours} ${family}`
            // A terminal's colour follows the switch without a theme change.
            await expect
              .poll(() => readWindow(node, terminal), { message: label })
              .toEqual({ plate: expected, terminal: terminal ? expected : null })
          }
        }
        // The kinds are told apart: no two kinds share a plate.
        const plates = await Promise.all(
          ['shell', 'ai', 'plan', 'knowledge', 'media'].map(id =>
            rootColour(window, `--cove-kind-${id}-plate`),
          ),
        )
        expect(new Set(plates).size, uiTheme).toBe(plates.length)
        await window.evaluate(() => {
          document.documentElement.dataset.coveKindColors = 'on'
        })
      }
    } finally {
      await electronApp.close()
    }
  })
})
