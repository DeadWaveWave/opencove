async function exists(path: string) {
  try {
    await access(path)
    return true
  } catch {
    return false
  }
}
/** A graceful acceptance failure must fail, never silently switch to SIGKILL. */
async function stopGracefully(child: ChildProcessWithoutNullStreams | null) {
  if (!child || child.exitCode !== null || child.signalCode !== null) {
    return
  }
  const exited = new Promise<void>((resolve, reject) => {
    const timer = setTimeout(
      () => reject(new Error('Worker did not stop gracefully within 10 seconds')),
      10_000,
    )
    child.once('exit', (code, signal) => {
      clearTimeout(timer)
      if (signal === 'SIGKILL' || (code !== 0 && signal !== 'SIGTERM')) {
        reject(new Error(`Worker shutdown failed: ${code}/${signal}`))
      } else {
        resolve()
      }
    })
  })
  child.kill('SIGTERM')
  await exited
}

test.describe('Claude clear restart binding', () => {
  test.skip(process.env.OPENCOVE_TEST_USE_REAL_AGENTS !== '1', 'Requires Claude Code 2.1.321')
  test.skip(process.platform === 'win32', 'POSIX CLI instrumentation')
  for (const scenario of [
    'completed B',
    'empty B',
    'completed C',
    'empty C',
    'quit during proof',
    'renderer offline',
  ] as const) {
    test(scenario, async ({ browserName: _browserName }, testInfo) => {
      test.setTimeout(300_000)
      const h = await createClearHarness(testInfo)
      let worker: ChildProcessWithoutNullStreams | null = null,
        app: ElectronApplication | null = null,
        page: Page | null = null
      const hold = h.env.OPENCOVE_TEST_CLAUDE_CLEAR_PROOF_HOLD
      try {
        worker = (await startWorker({ userDataDir: h.userDataDir, env: h.env })).child
        captureWorkerOutput(worker, testInfo)
        ;({ electronApp: app, window: page } = await launchApp({
          userDataDir: h.userDataDir,
          cleanupUserDataDir: false,
          env: h.env,
        }))
        await seedWorkspaceState(page, {
          activeWorkspaceId: 'clear-project',
          settings: {
            defaultProvider: 'claude-code',
            agentResidentContext: 'off',
            agentFullAccess: false,
          },
          workspaces: [
            {
              id: 'clear-project',
              name: 'Claude restart',
              path: h.workspace,
              nodes: [
                {
                  id: 'clear-task',
                  kind: 'task',
                  title: 'Claude restart',
                  position: { x: 100, y: 80 },
                  width: 460,
                  height: 280,
                  task: {
                    requirement: promptA,
                    status: 'todo',
                    linkedAgentNodeId: null,
                    lastRunAt: null,
                    autoGeneratedTitle: false,
                  },
                },
              ],
            },
          ],
        })
        await page.getByTestId('task-node-run-agent').click()
        await expect(page.locator('.terminal-node')).toHaveCount(1)
        const nodeId = await page
          .locator('.terminal-node')
          .evaluate(element => element.closest('.react-flow__node')!.getAttribute('data-id')!)
        await waitForReply(h.hookLog, 'REPLY_A')
        const initial = await getBinding(page, nodeId)
        const a = initial.tuple.resumeSessionId!
        const runtime = (await readRuntimeSessionId(page, nodeId))!
        await clearConversation(page, runtime)
        await expect
          .poll(
            async () =>
              (await readRecords<Hook>(h.hookLog)).filter(
                record =>
                  record.input.hook_event_name === 'SessionStart' &&
                  record.input.source === 'clear',
              ).length,
          )
          .toBe(1)
        const b = (await readRecords<Hook>(h.hookLog)).find(
          record =>
            record.input.hook_event_name === 'SessionStart' && record.input.source === 'clear',
        )!.input.session_id
        expect(b).not.toBe(a)
        const held = scenario === 'quit during proof' || scenario === 'renderer offline'
        if (held) {
          await writeFile(hold, '')
        }
        let expectedId = a,
          expectedReply = 'REPLY_A'
        if (scenario !== 'empty B') {
          await typeTurn(page, nodeId, promptB)
          await waitForReply(h.hookLog, 'REPLY_B')
          expectedId = b
          expectedReply = 'REPLY_B'
          if (held) {
            await expect.poll(() => exists(`${hold}.admitted`)).toBe(true)
          } else {
            await expect
              .poll(() => getBinding(page!, nodeId))
              .toMatchObject({ tuple: { resumeSessionId: b } })
          }
        }
        if (scenario === 'completed C' || scenario === 'empty C') {
          await clearConversation(page, runtime)
          await expect
            .poll(
              async () =>
                (await readRecords<Hook>(h.hookLog)).filter(
                  record =>
                    record.input.hook_event_name === 'SessionStart' &&
                    record.input.source === 'clear',
                ).length,
            )
            .toBe(2)
          if (scenario === 'completed C') {
            const c = (await readRecords<Hook>(h.hookLog))
              .filter(
                record =>
                  record.input.hook_event_name === 'SessionStart' &&
                  record.input.source === 'clear',
              )
              .at(-1)!.input.session_id
            await typeTurn(page, nodeId, promptC)
            await waitForReply(h.hookLog, 'REPLY_C')
            expectedId = c
            expectedReply = 'REPLY_C'
            await expect
              .poll(() => getBinding(page!, nodeId))
              .toMatchObject({ tuple: { resumeSessionId: c } })
          }
        }
        const initialLaunch = launches(await readRecords<Invocation>(h.invocationLog))[0]
        expect(initialLaunch).toBeTruthy()
        // Close the renderer while the Worker retains the admitted read.
        await app.close()
        app = null
        page = null
        if (scenario === 'renderer offline') {
          await rm(hold)
          // Independent renderer reconnect proves committed convergence before cold restart.
          ;({ electronApp: app, window: page } = await launchApp({
            userDataDir: h.userDataDir,
            cleanupUserDataDir: false,
            env: h.env,
          }))
          await expect
            .poll(() => getBinding(page!, nodeId))
            .toMatchObject({ tuple: { resumeSessionId: b } })
          await expect.poll(() => binding(page!, nodeId)).toMatchObject({ resumeSessionId: b })
          await app.close()
          app = null
          page = null
        }
        // Desktop may have its own shutdown surface. Only a marker written after the
        // executing Worker's SIGTERM proves release happened during its drain.
        if (scenario === 'quit during proof') {
          await rm(`${hold}.draining`, { force: true })
        }
        const stopped = stopGracefully(worker)
        if (scenario === 'quit during proof') {
          await expect.poll(() => exists(`${hold}.draining`)).toBe(true)
          await rm(hold)
        }
        await stopped
        worker = null
        await expect
          .poll(
            () => {
              try {
                process.kill(initialLaunch.pid, 0)
                return false
              } catch (error) {
                return (error as NodeJS.ErrnoException).code === 'ESRCH'
              }
            },
            { timeout: 15_000 },
          )
          .toBe(true)
        const launchCount = launches(await readRecords<Invocation>(h.invocationLog)).length
        const hookCount = (await readRecords<Hook>(h.hookLog)).length
        worker = (await startWorker({ userDataDir: h.userDataDir, env: h.env })).child
        captureWorkerOutput(worker, testInfo)
        ;({ electronApp: app, window: page } = await launchApp({
          userDataDir: h.userDataDir,
          cleanupUserDataDir: false,
          env: h.env,
        }))
        await expect
          .poll(async () => launches(await readRecords<Invocation>(h.invocationLog)).length)
          .toBeGreaterThan(launchCount)
        const restarted = launches(await readRecords<Invocation>(h.invocationLog)).slice(
          launchCount,
        )
        expect(restarted.map(launchIdentity)).toContainEqual(
          expect.objectContaining({ mode: 'resume', resumeSessionId: expectedId }),
        )
        await expect
          .poll(
            async () =>
              (await readRecords<Hook>(h.hookLog))
                .slice(hookCount)
                .some(
                  record =>
                    record.input.hook_event_name === 'SessionStart' &&
                    record.input.session_id === expectedId,
                ),
            { timeout: 30_000 },
          )
          .toBe(true)
        await expect
          .poll(() => getBinding(page!, nodeId))
          .toMatchObject({ tuple: { resumeSessionId: expectedId, resumeSessionIdVerified: true } })
        await expect
          .poll(() => binding(page!, nodeId))
          .toMatchObject({ resumeSessionId: expectedId, resumeSessionIdVerified: true })
        const requestCount = h.api.requests().length
        await typeTurn(page, nodeId, promptAfterRestart)
        await expect
          .poll(
            () =>
              h.api
                .requests()
                .slice(requestCount)
                .some(body => lastUserBlocks(body).includes(promptAfterRestart)),
            { timeout: 60_000 },
          )
          .toBe(true)
        const request = h.api
          .requests()
          .slice(requestCount)
          .find(body => lastUserBlocks(body).includes(promptAfterRestart))!
        const history = (request.messages ?? [])
          .filter(message => message.role === 'assistant')
          .map(message =>
            typeof message.content === 'string'
              ? message.content
              : message.content.map(block => block.text ?? '').join('\n'),
          )
          .join('\n')
        expect(history).toContain(expectedReply)
        for (const reply of ['REPLY_A', 'REPLY_B', 'REPLY_C'].filter(
          candidateReply => candidateReply !== expectedReply,
        )) {
          expect(history).not.toContain(reply)
        }
        await testInfo.attach('restart-evidence', {
          body: JSON.stringify({ expectedId, restarted, request }, null, 2),
          contentType: 'application/json',
        })
      } finally {
        await rm(hold, { force: true })
        await app?.close()
        await stopGracefully(worker)
        await new Promise<void>((resolve, reject) =>
          h.api.server.close(error => (error ? reject(error) : resolve())),
        )
        await preserveFailureEvidence(h, testInfo)
        await removePathWithRetry(h.root)
      }
    })
  }
})
