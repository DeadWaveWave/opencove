const claudeSettings = {
  defaultProvider: 'claude-code',
  customModelEnabledByProvider: { 'claude-code': false },
  customModelByProvider: { 'claude-code': '' },
  customModelOptionsByProvider: { 'claude-code': [] },
}

/** Drags the empty canvas, which pans the view in the default mouse mode. */
async function dragCanvas(window: Page, dx: number, dy: number) {
  // Start on a spot where the pane itself is hit, never a window or a control.
  const start = await window.evaluate(() => {
    const pane = document.querySelector('.workspace-canvas .react-flow__pane')!
    const rect = pane.getBoundingClientRect()
    for (let y = rect.bottom - 60; y > rect.top + 60; y -= 40) {
      for (let x = rect.left + rect.width / 2; x < rect.right - 120; x += 40) {
        if (document.elementFromPoint(x, y) === pane) {
          return { x, y }
        }
      }
    }
    return null
  })
  if (!start) {
    throw new Error('No empty canvas spot to drag from')
  }
  await window.mouse.move(start.x, start.y)
  await window.mouse.down()
  await window.mouse.move(start.x + dx, start.y + dy, { steps: 12 })
  await window.mouse.up()
}

async function isInView(window: Page, selector: string) {
  return await window.evaluate(target => {
    const element = document.querySelector(target)
    const pane = document.querySelector('.workspace-canvas .react-flow__pane')
    if (!element || !pane) {
      return false
    }
    const rect = element.getBoundingClientRect()
    const view = pane.getBoundingClientRect()
    return (
      rect.right > view.left &&
      rect.left < view.right &&
      rect.bottom > view.top &&
      rect.top < view.bottom
    )
  }, selector)
}

test('an edge beacon points at an out-of-view agent waiting for you and flies to it', async () => {
  const { electronApp, window } = await launchApp({
    windowMode: 'inactive',
    env: {
      OPENCOVE_TEST_ENABLE_SESSION_STATE_WATCHER: '1',
      OPENCOVE_TEST_AGENT_SESSION_SCENARIO: 'claude-hook-lifecycle',
      OPENCOVE_TEST_CLAUDE_HOOK_INSTALL_FAILURE: '0',
    },
  })
  try {
    await setFrameMotion(window, false)
    await seedWorkspaceState(window, {
      activeWorkspaceId: 'beacon-project',
      workspaces: [
        {
          id: 'beacon-project',
          name: 'Beacons',
          path: testWorkspacePath,
          nodes: [
            {
              id: 'beacon-task',
              title: 'Fix the flaky E2E',
              position: { x: 180, y: 140 },
              width: 460,
              height: 280,
              kind: 'task',
              status: null,
              task: {
                requirement: 'Fix the flaky E2E',
                status: 'todo',
                priority: 'medium',
                tags: [],
                linkedAgentNodeId: null,
                lastRunAt: null,
                autoGeneratedTitle: false,
                createdAt: '2026-11-05T10:00:00.000Z',
                updatedAt: '2026-11-05T10:00:00.000Z',
              },
            },
          ],
          spaces: [],
        },
      ],
      settings: { ...claudeSettings, language: 'en' },
    })
    await installPtySessionCapture(window)
    await window.locator('.task-node [data-testid="task-node-run-agent"]').click()
    await expect(window.locator('.terminal-node').first()).toContainText(
      '[opencove-test-hook] ready',
    )
    await expect.poll(async () => await resolveFirstAgentSessionId(window)).not.toBeNull()
    const sessionId = (await resolveFirstAgentSessionId(window))!
    const agentId = (await window
      .locator('.react-flow__node:has(.terminal-node)')
      .first()
      .getAttribute('data-id'))!
    const agent = `.react-flow__node[data-id="${agentId}"]`
    const beacon = window.getByTestId(`workspace-edge-beacon-${agentId}`)

    await writeToPty(window, { sessionId, data: '<test-hook-waiting>\r' })
    // In view, the waiting agent needs no beacon.
    await expect.poll(() => isInView(window, agent)).toBe(true)
    await expect(beacon).toHaveCount(0)

    // Pan the agent out of view, up and to the left.
    await dragCanvas(window, -1100, -650)
    await dragCanvas(window, -1100, -650)
    await expect.poll(() => isInView(window, agent)).toBe(false)
    await expect(beacon).toBeVisible()
    await expect(beacon).toHaveAccessibleName(/Needs approval/)
    await expect(beacon.locator('.workspace-edge-beacon__status')).toHaveText('· Needs approval')
    const dot = beacon.locator('.workspace-edge-beacon__dot')
    await expect(beacon).toHaveCSS('animation-name', 'none')
    await expect(dot).toHaveCSS('animation-name', 'workspace-edge-beacon-pulse')
    await expect(dot).toHaveCSS('animation-duration', '1.3s')
    await expect(dot).toHaveCSS('width', '8px')
    const ring = await beacon.evaluate(el => getComputedStyle(el).boxShadow)
    expect(ring).toContain('0px 0px 0px 4px')
    await setFrameMotion(window, true)
    await expect(dot).toHaveCSS('animation-name', 'none')
    await expect(beacon).toHaveCSS('box-shadow', ring)
    await setFrameMotion(window, false)
    await setMotionSignals(window, false)
    await expect(dot).toHaveCSS('animation-name', 'none')
    await expect(beacon).toHaveCSS('box-shadow', ring)
    // The beacon sits on the edge facing the agent.
    const expectedSide = await window.evaluate(target => {
      const rect = document.querySelector(target)!.getBoundingClientRect()
      const view = document
        .querySelector('.workspace-canvas .react-flow__pane')!
        .getBoundingClientRect()
      const dx = rect.left + rect.width / 2 - (view.left + view.width / 2)
      const dy = rect.top + rect.height / 2 - (view.top + view.height / 2)
      return Math.abs(dx) / (view.width / 2 - 132) >= Math.abs(dy) / (view.height / 2 - 28)
        ? dx > 0
          ? 'right'
          : 'left'
        : dy > 0
          ? 'bottom'
          : 'top'
    }, agent)
    await expect(beacon).toHaveAttribute('data-side', expectedSide)

    await beacon.click()
    await expect.poll(() => isInView(window, agent)).toBe(true)
    await expect(window.locator(agent)).toHaveAttribute('data-cove-navigation-focus', 'true')
    await expect(window.locator(`${agent} .cove-window-focus-brackets`)).toHaveCount(1)
    await expect(beacon).toHaveCount(0)
  } finally {
    await electronApp.close()
  }
})
