import { execFileSync } from 'node:child_process'
import { mkdir, mkdtemp, readFile, realpath, rm, writeFile } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { isZombieProcess } from '../support/processLiveness'
import { expect, test } from '@playwright/test'
import type { AgentRunSnapshot } from '../../src/shared/contracts/dto/agentRunState'
import {
  readPosixProcessTable,
  snapshotProcessTree,
  type ProcessIdentity,
} from '../../src/platform/process/ptyHost/posixProcessTable'
import { startResponsesApi } from './agent.prompt.real-codex.helpers'
import { resolveFirstAgentSessionId } from './workspace-canvas.agent-status-watcher.helpers'
import { launchApp, seedWorkspaceState } from './workspace-canvas.helpers'

test.describe('managed Agent tool process reaping with real Codex', () => {
  test.skip(process.env.OPENCOVE_TEST_USE_REAL_AGENTS !== '1', 'Requires installed real Codex CLI')
  test.skip(
    process.platform !== 'darwin' && process.platform !== 'linux',
    'POSIX lifecycle regression',
  )

  for (const action of ['close', 'delete'] as const) {
    test(`${action} reaps a running tool across process groups`, async ({
      browserName: _,
    }, testInfo) => {
      test.setTimeout(120_000)
      await testInfo.attach('codex-version', {
        body: Buffer.from(
          execFileSync('codex', ['--version'], { encoding: 'utf8', timeout: 10_000 }),
        ),
        contentType: 'text/plain',
      })
      const root = await realpath(await mkdtemp(join(tmpdir(), 'opencove-codex-reap-')))
      const workspace = join(root, 'workspace')
      const codexHome = join(root, 'codex-home')
      const marker = join(root, 'tool-pids')
      await mkdir(workspace)
      await mkdir(codexHome)
      // The shell records its identity, then exec preserves that PID as the detached sleep.
      const api = await startResponsesApi(
        `printf '%s %s\\n' "$$" "$PPID" > '${marker}'; exec sleep 30`,
      )
      await writeFile(
        join(codexHome, 'config.toml'),
        [
          'model = "test-model"',
          'model_provider = "mock"',
          'check_for_update_on_startup = false',
          '[model_providers.mock]',
          'name = "mock"',
          `base_url = "${api.url}"`,
          'wire_api = "responses"',
          'env_key = "OPENCOVE_TEST_MOCK_API_KEY"',
          `[projects."${workspace}"]`,
          'trust_level = "trusted"',
          '',
        ].join('\n'),
      )
      const { electronApp, window } = await launchApp({
        userDataDir: join(root, 'user-data'),
        cleanupUserDataDir: false,
        env: {
          OPENCOVE_TEST_USE_REAL_AGENTS: '1',
          OPENCOVE_TEST_CODEX_HOOK_INSTALL_FAILURE: '0',
          OPENCOVE_TEST_MOCK_API_KEY: 'opencove-local-diagnostic-not-a-real-key',
          CODEX_HOME: codexHome,
        },
      })
      let captured: ProcessIdentity[] = []
      try {
        await seedWorkspaceState(window, {
          activeWorkspaceId: 'reap',
          settings: {
            defaultProvider: 'codex',
            agentFullAccess: true,
            customModelEnabledByProvider: { codex: false },
          },
          workspaces: [
            {
              id: 'reap',
              name: 'Reap',
              path: workspace,
              nodes: [
                {
                  id: 'task',
                  title: 'Reap task',
                  kind: 'task',
                  status: null,
                  position: { x: 100, y: 80 },
                  width: 460,
                  height: 280,
                  task: {
                    requirement: 'Reply with ACK.',
                    status: 'todo',
                    linkedAgentNodeId: null,
                    lastRunAt: null,
                    autoGeneratedTitle: false,
                  },
                },
              ],
            },
          ],
        })
        await window.getByTestId('task-node-run-agent').click()
        await expect
          .poll(() => resolveFirstAgentSessionId(window), { timeout: 30_000 })
          .not.toBeNull()
        const sessionId = (await resolveFirstAgentSessionId(window))!
        const snapshot = () =>
          window.evaluate(
            id =>
              window.opencoveApi.controlSurface.invoke<AgentRunSnapshot>({
                kind: 'query',
                id: 'agent.get',
                payload: { sessionId: id },
              }),
            sessionId,
          )
        await expect.poll(async () => (await snapshot()).state, { timeout: 60_000 }).toBe('idle')
        const nodeId = (await snapshot()).nodeId!
        const agent = window.locator(`[data-id="${nodeId}"]`)
        await agent.locator('.xterm-helper-textarea').focus()
        // Fast bursts are bracketed paste in Codex 0.166, so Enter would insert a newline.
        await window.keyboard.type(`SLOW_TOOL ${action} lifecycle probe`, { delay: 30 })
        await window.keyboard.press('Enter')
        await expect
          .poll(
            async () => {
              try {
                return await readFile(marker, 'utf8')
              } catch {
                return ''
              }
            },
            { timeout: 15_000 },
          )
          .not.toBe('')
        const [toolPid, cliPid] = (await readFile(marker, 'utf8')).trim().split(/\s+/u).map(Number)
        const rows = await readPosixProcessTable()
        captured = snapshotProcessTree(rows, cliPid!)
        expect(captured.find(row => row.pid === toolPid)).toMatchObject({ pgid: toolPid })
        expect(captured.length).toBeGreaterThanOrEqual(2)
        await testInfo.attach('termination-snapshot', {
          body: Buffer.from(JSON.stringify(captured, null, 2)),
          contentType: 'application/json',
        })
        if (action === 'close') {
          await agent.locator('.terminal-node__close').click()
        } else {
          await window.evaluate(async id => {
            await window.opencoveApi.controlSurface.invoke({
              kind: 'command',
              id: 'node.delete',
              payload: { nodeId: id },
            })
          }, nodeId)
        }
        await expect(agent).toHaveCount(0)
        await expect
          .poll(
            async () => {
              const current = new Map(
                (await readPosixProcessTable()).map(row => [row.pid, row.startTime]),
              )
              return captured
                .filter(row => current.get(row.pid) === row.startTime && !isZombieProcess(row.pid))
                .map(row => row.pid)
            },
            { timeout: 5_000, intervals: [50, 100, 200] },
          )
          .toEqual([])
      } finally {
        await electronApp.close()
        const cleanupRows = new Map(
          (await readPosixProcessTable()).map(row => [row.pid, row.startTime]),
        )
        for (const row of captured) {
          if (cleanupRows.get(row.pid) === row.startTime) {
            process.kill(row.pid, 'SIGKILL')
          }
        }
        api.server.closeAllConnections()
        api.server.close()
        await rm(root, { recursive: true, force: true })
      }
    })
  }
})
