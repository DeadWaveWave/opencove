import { expect, test, type Locator } from '@playwright/test'
import { clearAndSeedWorkspace, launchApp, testWorkspacePath } from './workspace-canvas.helpers'

// A task window opens two grid columns wide: 252px at the regular size.
const DEFAULT_SIZE = { width: 252, height: 356 }
const WIDE_SIZE = { width: 420, height: 300 }

function sessionRecord(index: number) {
  return {
    id: `session-${index}`,
    provider: 'codex',
    resumeSessionId: `resume-${index}`,
    resumeSessionIdVerified: true,
    prompt: 'Write the release notes',
    model: 'gpt-5.2-codex',
    effectiveModel: 'gpt-5.2-codex',
    boundDirectory: testWorkspacePath,
    lastDirectory: testWorkspacePath,
    createdAt: `2026-11-08T10:0${index}:00.000Z`,
    lastRunAt: `2026-11-08T10:0${index}:00.000Z`,
    endedAt: `2026-11-08T10:0${index}:30.000Z`,
    exitCode: 0,
    status: 'exited',
  }
}

function taskNode(
  id: string,
  position: { x: number; y: number },
  size: { width: number; height: number },
  agentSessions: ReturnType<typeof sessionRecord>[] = [],
) {
  return {
    id,
    title: 'Release notes',
    position,
    ...size,
    kind: 'task' as const,
    task: {
      requirement: 'Write the round 4 release notes.',
      status: 'doing',
      priority: 'medium',
      tags: ['release', 'docs', 'round-4'],
      linkedAgentNodeId: null,
      agentSessions,
      lastRunAt: null,
      autoGeneratedTitle: false,
      createdAt: null,
      updatedAt: null,
    },
  }
}

async function box(locator: Locator) {
  const value = await locator.boundingBox()
  expect(value).not.toBeNull()
  return value!
}

test.describe('Workspace Canvas - Tasks (Card)', () => {
  test('fits the card into a default-width window, every control in reach', async () => {
    const { electronApp, window } = await launchApp()

    try {
      await clearAndSeedWorkspace(window, [
        taskNode('task-default', { x: 120, y: 120 }, DEFAULT_SIZE, [
          sessionRecord(1),
          sessionRecord(2),
        ]),
        taskNode('task-wide', { x: 420, y: 120 }, WIDE_SIZE),
      ])

      const card = window.locator('.react-flow__node[data-id="task-default"] .task-node')
      await expect(card).toBeVisible()
      const plate = await box(card.locator('.task-node__plate'))
      const progress = await box(card.locator('.task-node__progress'))
      const labels = await box(card.locator('.task-node__labels'))

      // Too narrow for one row: the labels take the line under the progress.
      expect(labels.y).toBeGreaterThanOrEqual(progress.y + progress.height - 1)
      // Nothing in the meta row runs past the plate.
      for (const part of [progress, labels]) {
        expect(part.x + part.width).toBeLessThanOrEqual(plate.x + plate.width)
      }
      const edit = await box(card.getByTestId('task-node-edit-meta'))
      expect(edit.x + edit.width).toBeLessThanOrEqual(plate.x + plate.width)
      // Tags that do not fit leave the line rather than squeeze to a letter each.
      const tags = await box(card.getByTestId('task-node-tags'))
      expect(tags.height).toBeLessThanOrEqual(20)
      await expect(card.locator('.task-node__tag').first()).toHaveText('#release')

      // Both sessions show as avatars; nothing folds.
      await expect(card.locator('.task-node__session--record')).toHaveCount(2)
      await expect(card.getByTestId('task-node-agent-session-more')).toHaveCount(0)

      // Every control is at least 24px square.
      const targets = [
        ...(await card.locator('.cove-segmented__option').all()),
        card.getByTestId('task-node-status-select-trigger'),
        card.getByTestId('task-node-edit-meta'),
        ...(await card.locator('.task-node__session').all()),
        card.getByTestId('task-node-run-agent'),
      ]
      for (const targetBox of await Promise.all(targets.map(box))) {
        expect(targetBox.width).toBeGreaterThanOrEqual(24)
        expect(targetBox.height).toBeGreaterThanOrEqual(24)
      }

      // A wide window keeps the meta on one row.
      const wide = window.locator('.react-flow__node[data-id="task-wide"] .task-node')
      const wideProgress = await box(wide.locator('.task-node__progress'))
      const wideLabels = await box(wide.locator('.task-node__labels'))
      expect(
        Math.abs(wideLabels.y + wideLabels.height / 2 - (wideProgress.y + wideProgress.height / 2)),
      ).toBeLessThanOrEqual(2)
    } finally {
      await electronApp.close()
    }
  })

  test('moves the task along its steps by click and by arrow key', async () => {
    const { electronApp, window } = await launchApp()

    try {
      await clearAndSeedWorkspace(window, [
        taskNode('task-default', { x: 120, y: 120 }, DEFAULT_SIZE),
      ])

      const card = window.locator('.react-flow__node[data-id="task-default"] .task-node')
      const status = card.getByTestId('task-node-status-select')
      await expect(status).toHaveValue('doing')

      // From the keyboard, on a window that is not selected: the steps keep focus, so the next
      // arrow moves the status again rather than nudging the selected window.
      const windowBefore = await box(card)
      await card.getByTestId('task-node-status-step-doing').focus()
      await window.keyboard.press('ArrowRight')
      await expect(status).toHaveValue('ai_done')
      await expect(card.getByTestId('task-node-status-step-ai_done')).toBeFocused()
      await window.keyboard.press('ArrowRight')
      await expect(status).toHaveValue('done')
      await expect(card.getByTestId('task-node-status-step-done')).toBeFocused()
      const windowAfter = await box(card)
      expect([windowAfter.x, windowAfter.y]).toEqual([windowBefore.x, windowBefore.y])
      await window.keyboard.press('ArrowLeft')
      await expect(status).toHaveValue('ai_done')

      // By pointer.
      await card.locator('.cove-segmented__option').nth(3).click()
      await expect(status).toHaveValue('done')
      await expect(card).toHaveAttribute('data-task-status', 'done')
      await expect(card.locator('.task-node__step[data-filled="true"]')).toHaveCount(4)
    } finally {
      await electronApp.close()
    }
  })

  test('renames from a click on the title bar, and moves the window from a hold or a drag', async () => {
    const { electronApp, window } = await launchApp()

    try {
      await clearAndSeedWorkspace(window, [
        taskNode('task-default', { x: 120, y: 120 }, DEFAULT_SIZE),
      ])

      const node = window.locator('.react-flow__node[data-id="task-default"]')
      const card = node.locator('.task-node')
      const title = card.getByTestId('task-node-title-display')
      const input = card.getByTestId('task-node-inline-title-input')

      // The title is the bar between the tile and the controls; no drag space sits beside it.
      await expect(card.locator('.task-node__header .cove-window-header__drag')).toHaveCount(0)
      const titleBox = await box(title)
      const actions = await box(card.locator('.task-node__header-actions'))
      expect(actions.x - (titleBox.x + titleBox.width)).toBeLessThanOrEqual(12)
      expect(
        await title
          .locator('.node-title-editor__display-text')
          .evaluate(text => text.scrollWidth <= text.clientWidth),
      ).toBe(true)

      // A click renames.
      await title.click()
      await expect(input).toBeFocused()
      await window.keyboard.press('Escape')
      await expect(input).toHaveCount(0)

      const press = async (offset: { x: number; y: number }, hold: boolean) => {
        const from = await box(title)
        const start = { x: from.x + 24, y: from.y + from.height / 2 }
        await window.mouse.move(start.x, start.y)
        await window.mouse.down()
        if (hold) {
          await expect(title).toHaveAttribute('data-cove-title-held', 'true')
        }
        await window.mouse.move(start.x + offset.x, start.y + offset.y, { steps: 8 })
        await window.mouse.up()
      }

      // A drag moves the window and renames nothing.
      const before = await box(node)
      await press({ x: 60, y: 40 }, false)
      await expect.poll(async () => (await box(node)).x - before.x).toBeGreaterThan(40)
      await expect(input).toHaveCount(0)

      // A hold let go in place renames nothing; a hold then a drag moves the window.
      await press({ x: 0, y: 0 }, true)
      await expect(title).not.toHaveAttribute('data-cove-title-held')
      await expect(input).toHaveCount(0)
      const held = await box(node)
      await press({ x: 0, y: 50 }, true)
      await expect.poll(async () => (await box(node)).y - held.y).toBeGreaterThan(30)
      await expect(input).toHaveCount(0)
    } finally {
      await electronApp.close()
    }
  })

  test('lights the running session, and stills the light in reduced motion', async () => {
    const { electronApp, window } = await launchApp()

    try {
      await clearAndSeedWorkspace(window, [
        taskNode('task-default', { x: 120, y: 120 }, DEFAULT_SIZE),
      ])

      const card = window.locator('.react-flow__node[data-id="task-default"] .task-node')
      await card.getByTestId('task-node-run-agent').click()

      const light = card.locator('.task-node__session--linked .task-node__session-light--working')
      await expect(light).toHaveCount(1)
      await expect(card.getByTestId('task-node-agent-sessions')).toContainText('1 running')
      await expect(light).toHaveCSS('animation-name', 'cove-pixel-blink')

      await window.emulateMedia({ reducedMotion: 'reduce' })
      await expect(light).toHaveCSS('animation-name', 'none')
    } finally {
      await electronApp.close()
    }
  })
})
