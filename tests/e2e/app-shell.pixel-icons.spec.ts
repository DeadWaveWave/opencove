import { expect, test, type Page } from '@playwright/test'
import { clearAndSeedWorkspace, launchApp } from './workspace-canvas.helpers'

const SETTINGS_SECTIONS = [
  'general',
  'appearance',
  'canvas',
  'terminal',
  'agent',
  'shortcuts',
  'plugins',
  'worker',
  'experimental',
]

/**
 * Every pixel icon on screen that is not drawn on its grid: a pixel icon is square and sized at a
 * whole multiple of half its 12 cells (ui-icons.css), or its cells smear across device pixels.
 * Sizes are layout sizes, so a zoomed canvas does not count against them.
 */
async function readOffGridIcons(window: Page): Promise<string[]> {
  return await window.evaluate(() => {
    const sizes = new Set([12, 18, 24, 36])
    const where = (element: Element | null): string => {
      const owner = element?.closest('[class]')
      return owner ? `${owner.tagName.toLowerCase()}.${owner.classList[0]}` : 'document'
    }
    const offGrid: string[] = []
    for (const icon of document.querySelectorAll<SVGSVGElement>('svg[data-cove-pixel-icon]')) {
      if (!icon.checkVisibility()) {
        continue
      }
      const style = getComputedStyle(icon)
      const width = Number.parseFloat(style.width)
      const height = Number.parseFloat(style.height)
      if (width !== height || !sizes.has(width)) {
        offGrid.push(
          `${icon.dataset.covePixelIcon} ${width}×${height} in ${where(icon.parentElement)}`,
        )
      }
    }
    for (const icon of document.querySelectorAll('svg.lucide')) {
      offGrid.push(`a lucide icon in ${where(icon.parentElement)}`)
    }
    return offGrid
  })
}

async function rightClickEmptyCanvas(window: Page): Promise<void> {
  const point = await window.evaluate(() => {
    const pane = document.querySelector('.react-flow__pane')!
    const box = pane.getBoundingClientRect()
    for (let y = box.top + 40; y < Math.min(box.bottom, window.innerHeight) - 40; y += 24) {
      for (let x = box.left + 40; x < Math.min(box.right, window.innerWidth) - 40; x += 24) {
        if (document.elementFromPoint(x, y) === pane) {
          return { x, y }
        }
      }
    }
    return null
  })
  expect(point, 'an empty spot on the canvas').not.toBeNull()
  await window.mouse.click(point!.x, point!.y, { button: 'right' })
}

test.describe('App shell - Pixel icons', () => {
  test('every icon is pixel art drawn on its grid', async () => {
    const { electronApp, window } = await launchApp()

    try {
      await clearAndSeedWorkspace(window, [
        {
          id: 'icons-note',
          title: 'icons note',
          position: { x: 120, y: 120 },
          width: 320,
          height: 220,
          kind: 'note',
          task: { text: 'Pixel icons only.' },
        },
        {
          id: 'icons-task',
          title: 'icons task',
          position: { x: 500, y: 120 },
          width: 360,
          height: 300,
          kind: 'task',
          task: {
            requirement: 'Draw every icon on its grid.',
            status: 'doing',
            priority: 'medium',
            tags: ['ui'],
            linkedAgentNodeId: null,
            lastRunAt: null,
            autoGeneratedTitle: false,
          },
        },
      ])
      await expect(window.locator('.note-node')).toBeVisible()
      await expect(window.locator('.task-node')).toBeVisible()
      await expect(window.locator('svg[data-cove-pixel-icon]').first()).toBeVisible()
      expect(await readOffGridIcons(window), 'the workspace').toEqual([])

      await rightClickEmptyCanvas(window)
      const menu = window.locator('[role="menu"]').first()
      await expect(menu).toBeVisible()
      await expect(menu.locator('svg[data-cove-pixel-icon]').first()).toBeVisible()
      expect(await readOffGridIcons(window), 'the canvas menu').toEqual([])
      await window.keyboard.press('Escape')
      await expect(menu).toBeHidden()

      await window.getByTestId('app-header-settings').click({ noWaitAfter: true })
      await expect(window.locator('.settings-panel')).toBeVisible()
      for (const section of SETTINGS_SECTIONS) {
        await window.getByTestId(`settings-section-nav-${section}`).click()
        await window.waitForTimeout(150)
        expect(await readOffGridIcons(window), `settings: ${section}`).toEqual([])
      }
    } finally {
      await electronApp.close()
    }
  })
})
