import { execFileSync } from 'node:child_process'
import { mkdir, mkdtemp, realpath, rm } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { startResponsesApi, writeCodexConfig } from './agent.prompt.real-codex.helpers'
import { expect, type TestInfo } from '@playwright/test'
import type { AgentRunSnapshot } from '../../src/shared/contracts/dto/agentRunState'
import { launchApp, seedWorkspaceState } from './workspace-canvas.helpers'
import { resolveFirstAgentSessionId } from './workspace-canvas.agent-status-watcher.helpers'

export async function launchResidentCodex(testInfo: TestInfo, mode: 'suggest' | 'off') {
  const version = execFileSync('codex', ['--version'], { encoding: 'utf8', timeout: 10_000 })
  await testInfo.attach('real-cli-version', {
    body: Buffer.from(version),
    contentType: 'text/plain',
  })
  const root = await realpath(await mkdtemp(join(tmpdir(), 'opencove-real-codex-')))
  const workspace = join(root, 'workspace')
  const codexHome = join(root, 'codex-home')
  const userDataDir = join(root, 'user-data')
  await mkdir(workspace, { recursive: true })
  await mkdir(codexHome, { recursive: true })
  const api = await startResponsesApi()
  await writeCodexConfig(codexHome, workspace, api.url)
  const { electronApp, window: page } = await launchApp({
    userDataDir,
    cleanupUserDataDir: false,
    env: {
      OPENCOVE_TEST_USE_REAL_AGENTS: '1',
      OPENCOVE_TEST_CODEX_HOOK_INSTALL_FAILURE: '0',
      OPENCOVE_TEST_MOCK_API_KEY: 'opencove-local-diagnostic-not-a-real-key',
      CODEX_HOME: codexHome,
    },
  })

  try {
    await seedWorkspaceState(page, {
      activeWorkspaceId: 'real-codex',
      settings: {
        defaultProvider: 'codex',
        agentResidentContext: mode,
        agentFullAccess: false,
        customModelEnabledByProvider: { codex: false },
      },
      workspaces: [
        {
          id: 'real-codex',
          name: 'Real Codex',
          path: workspace,
          nodes: [
            {
              id: 'real-codex-task',
              title: 'Codex task',
              kind: 'task',
              status: null,
              position: { x: 100, y: 80 },
              width: 460,
              height: 280,
              task: {
                requirement: 'Reply with ACK.',
                status: 'todo',
                linkedAgentNodeId: null,
                lastRunAt: null,
                autoGeneratedTitle: false,
              },
            },
          ],
        },
      ],
    })
    await page.locator('[data-testid="task-node-run-agent"]').click()
    await expect.poll(() => resolveFirstAgentSessionId(page), { timeout: 30_000 }).not.toBeNull()
    const sessionId = (await resolveFirstAgentSessionId(page))!
    const snapshot = () =>
      page.evaluate(
        id =>
          window.opencoveApi.controlSurface.invoke<AgentRunSnapshot>({
            kind: 'query',
            id: 'agent.get',
            payload: { sessionId: id },
          }),
        sessionId,
      )
    // The launch prompt completes one real turn; its Stop hook establishes readiness.
    await expect
      .poll(
        async () => {
          const value = await snapshot()
          return `${value.state}:${value.source}`
        },
        { timeout: 60_000 },
      )
      .toBe('idle:codex_hook')

    return {
      page,
      api,
      sessionId,
      snapshot,
      userDataDir,
      nodeId: (await snapshot()).nodeId!,
      async close() {
        await electronApp.close()
        api.server.close()
        await rm(root, { recursive: true, force: true })
      },
    }
  } catch (error) {
    await electronApp.close()
    api.server.close()
    await rm(root, { recursive: true, force: true })
    throw error
  }
}
