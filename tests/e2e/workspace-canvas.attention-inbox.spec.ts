import { expect, test } from '@playwright/test'
import { launchApp, seedWorkspaceState, testWorkspacePath } from './workspace-canvas.helpers'
import {
  installPtySessionCapture,
  resolveFirstAgentSessionId,
  writeToPty,
} from './workspace-canvas.agent-status-watcher.helpers'

const claudeSettings = {
  defaultProvider: 'claude-code',
  customModelEnabledByProvider: { 'claude-code': false },
  customModelByProvider: { 'claude-code': '' },
  customModelOptionsByProvider: { 'claude-code': [] },
}

test('the needs-you inbox reaches a waiting agent in another project', async () => {
  const { electronApp, window } = await launchApp({
    windowMode: 'inactive',
    env: {
      OPENCOVE_TEST_ENABLE_SESSION_STATE_WATCHER: '1',
      OPENCOVE_TEST_AGENT_SESSION_SCENARIO: 'claude-hook-lifecycle',
      OPENCOVE_TEST_CLAUDE_HOOK_INSTALL_FAILURE: '0',
    },
  })
  try {
    await seedWorkspaceState(window, {
      activeWorkspaceId: 'inbox-site',
      workspaces: [
        { id: 'inbox-core', name: 'Core', path: testWorkspacePath, nodes: [], spaces: [] },
        {
          id: 'inbox-site',
          name: 'Site',
          path: testWorkspacePath,
          nodes: [
            {
              id: 'inbox-task',
              title: 'Draft the changelog',
              position: { x: 180, y: 140 },
              width: 460,
              height: 280,
              kind: 'task',
              status: null,
              task: {
                requirement: 'Draft the changelog',
                status: 'todo',
                priority: 'medium',
                tags: [],
                linkedAgentNodeId: null,
                lastRunAt: null,
                autoGeneratedTitle: false,
                createdAt: '2026-10-17T10:00:00.000Z',
                updatedAt: '2026-10-17T10:00:00.000Z',
              },
            },
          ],
          spaces: [],
        },
      ],
      settings: claudeSettings,
    })
    await installPtySessionCapture(window)
    await window.locator('.task-node [data-testid="task-node-run-agent"]').click()
    const agentNode = window.locator('.terminal-node').first()
    await expect(agentNode).toContainText('[opencove-test-hook] ready')
    await expect.poll(async () => await resolveFirstAgentSessionId(window)).not.toBeNull()
    const sessionId = (await resolveFirstAgentSessionId(window))!
    const agentId = await window
      .locator('.react-flow__node:has(.terminal-node)')
      .first()
      .getAttribute('data-id')
    await writeToPty(window, { sessionId, data: '<test-hook-initial-working>\r' })
    await expect(window.getByTestId('workspace-project-working-inbox-site')).toBeVisible()
    const inbox = window.getByTestId('workspace-attention-inbox')
    await expect(inbox).toHaveCount(0)

    await window.getByTestId('workspace-item-inbox-core').click()
    await expect(window.getByTestId('workspace-item-inbox-core')).toHaveAttribute(
      'aria-current',
      'page',
    )
    // Record the animation frame in which the rail badge and the inbox row first exist.
    await window.evaluate(() => {
      const seen: Record<string, number> = {}
      let frame = 0
      const tick = () => {
        frame += 1
        requestAnimationFrame(tick)
      }
      requestAnimationFrame(tick)
      new MutationObserver(() => {
        for (const id of ['workspace-project-attention-inbox-site', 'workspace-attention-inbox']) {
          if (seen[id] === undefined && document.querySelector(`[data-testid="${id}"]`)) {
            seen[id] = frame
          }
        }
      }).observe(document.body, { childList: true, subtree: true })
      ;(window as unknown as { __inboxFrames: Record<string, number> }).__inboxFrames = seen
    })
    await writeToPty(window, { sessionId, data: '<test-hook-waiting>\r' })

    const item = window.getByTestId(`workspace-attention-item-inbox-site-${agentId}`)
    await expect(item).toContainText('Site · Project canvas')
    await expect(item).toContainText('Just now')
    const frames = await window.evaluate(
      () => (window as unknown as { __inboxFrames: Record<string, number> }).__inboxFrames,
    )
    expect(frames['workspace-attention-inbox']).toEqual(expect.any(Number))
    expect(frames['workspace-attention-inbox']).toBe(
      frames['workspace-project-attention-inbox-site'],
    )

    await item.click()
    await expect(window.getByTestId('workspace-item-inbox-site')).toHaveAttribute(
      'aria-current',
      'page',
    )
    await expect(agentNode.locator('.xterm-helper-textarea')).toBeFocused()

    await writeToPty(window, { sessionId, data: '<test-hook-done>\r' })
    await expect(inbox).toHaveCount(0)
  } finally {
    await electronApp.close()
  }
})
