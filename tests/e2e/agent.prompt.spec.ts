import { mkdtemp, readFile, rm, writeFile } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { join, resolve } from 'node:path'
import { expect, test } from '@playwright/test'
import { clearAndSeedWorkspace, launchApp, seededWorkspaceId } from './workspace-canvas.helpers'
import {
  installPtySessionCapture,
  resolveFirstAgentSessionId,
  writeToPty,
} from './workspace-canvas.agent-status-watcher.helpers'
import type { AgentRunSnapshot } from '../../src/shared/contracts/dto/agentRunState'

test.describe('agent.prompt from a canvas terminal', () => {
  for (const blocked of [false, true]) {
    test(
      blocked
        ? 'refuses a permission dialog with zero target bytes'
        : 'delivers one multiline paste and one submit through the real hook relay',
      async () => {
        const root = await mkdtemp(join(tmpdir(), 'opencove-prompt-'))
        const record = join(root, 'records.jsonl'),
          dialog = join(root, 'dialog'),
          prompt = join(root, 'prompt.txt')
        await writeFile(prompt, 'first line\nsecond line\nthird line\n')
        const { electronApp, window } = await launchApp({
          windowMode: 'inactive',
          env: {
            CLAUDE_CONFIG_DIR: join(root, 'claude'),
            CODEX_HOME: join(root, 'codex'),
            OPENCOVE_TEST_AGENT_SESSION_SCENARIO: 'claude-prompt-strict',
            OPENCOVE_TEST_CLAUDE_HOOK_INSTALL_FAILURE: '0',
            OPENCOVE_TEST_PROMPT_RECORD: record,
            OPENCOVE_TEST_PROMPT_DIALOG: dialog,
          },
        })
        try {
          await clearAndSeedWorkspace(
            window,
            [
              {
                id: 'prompt-task',
                title: 'Prompt fixture',
                kind: 'task',
                status: null,
                position: { x: 100, y: 100 },
                width: 460,
                height: 280,
                task: {
                  requirement: 'One manual turn',
                  status: 'todo',
                  linkedAgentNodeId: null,
                  lastRunAt: null,
                  autoGeneratedTitle: false,
                },
              },
            ],
            {
              settings: {
                defaultProvider: 'claude-code',
                customModelEnabledByProvider: { 'claude-code': false },
              },
            },
          )
          await installPtySessionCapture(window)
          await window.locator('[data-testid="task-node-run-agent"]').click()
          const agent = window.locator('.terminal-node').first()
          await expect(agent).toContainText('STRICT_READY')
          await expect.poll(() => resolveFirstAgentSessionId(window)).not.toBeNull()
          const sessionId = (await resolveFirstAgentSessionId(window))!
          // Establish readiness with an actual turn. No startup-idle shortcut.
          await writeToPty(window, { sessionId, data: 'manual baseline\r' })
          await expect(agent).toContainText('STRICT_TURN_1')
          const snapshot = () =>
            window.evaluate(
              id =>
                window.opencoveApi.controlSurface.invoke<AgentRunSnapshot>({
                  kind: 'query',
                  id: 'agent.get',
                  payload: { sessionId: id },
                }),
              sessionId,
            )
          await expect.poll(async () => (await snapshot()).state).toBe('idle')
          const nodeId = (await snapshot()).nodeId!
          if (blocked) {
            await writeFile(dialog, 'permission')
            await expect(agent).toContainText('STRICT_DIALOG')
            await expect.poll(async () => (await snapshot()).state).toBe('waiting')
          }
          const before = (await readFile(record, 'utf8'))
            .trim()
            .split('\n')
            .map(line => JSON.parse(line))
          // node.create launches the command inside a canvas terminal with its session grant.
          const quote = (value: string) =>
            process.platform === 'win32'
              ? `"${value.replaceAll('"', '\\"')}"`
              : `'${value.replaceAll("'", `'"'"'`)}'`
          const cliCommand = `node ${quote(resolve('out/cli/opencove.mjs'))} agent prompt --node ${quote(nodeId)} --text-file ${quote(prompt)} --timeout 10s`
          const terminal = await window.evaluate(
            async ({ projectId, command }) =>
              window.opencoveApi.controlSurface.invoke<{ node: { id: string } }>({
                kind: 'command',
                id: 'node.create',
                payload: {
                  projectId,
                  kind: 'terminal',
                  title: 'Prompt CLI',
                  frame: { x: 700, y: 100 },
                  data: { command },
                },
              }),
            { projectId: seededWorkspaceId, command: cliCommand },
          )
          const canvasTerminal = window.locator(`[data-id="${terminal.node.id}"] .terminal-node`)
          await expect(canvasTerminal).toContainText(
            blocked ? 'agent.blocked' : 'submission_observed',
          )
          const after = (await readFile(record, 'utf8'))
            .trim()
            .split('\n')
            .map(line => JSON.parse(line))
          const added = after.slice(before.length)
          if (blocked) {
            expect(added).toEqual([])
            expect(after.some(entry => entry.kind === 'dialog_bytes')).toBe(false)
            expect((await snapshot()).blockedReason).toBe('permission')
          } else {
            expect(added.filter(entry => entry.kind === 'paste')).toEqual([
              { kind: 'paste', text: 'first line\rsecond line\rthird line' },
            ])
            expect(added.filter(entry => entry.kind === 'submit')).toHaveLength(1)
            await expect(agent).toContainText('STRICT_TURN_2')
          }
        } finally {
          await electronApp.close()
          await rm(root, { recursive: true, force: true })
        }
      },
    )
  }
})
