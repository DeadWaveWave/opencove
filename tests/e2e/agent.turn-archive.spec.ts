import { execFile } from 'node:child_process'
import { mkdtemp, readFile, rm } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { join, resolve } from 'node:path'
import { expect, test, type ElectronApplication } from '@playwright/test'
import { clearAndSeedWorkspace, launchApp } from './workspace-canvas.helpers'
import {
  installPtySessionCapture,
  resolveFirstAgentSessionId,
  writeToPty,
} from './workspace-canvas.agent-status-watcher.helpers'
import type { AgentRunSnapshot } from '../../src/shared/contracts/dto/agentRunState'

// Deliberately independent of all real-provider helpers. This scenario uses only the strict stub.
test('exact turn read and wait survive a complete Worker restart, then disappear on node deletion', async () => {
  test.setTimeout(120_000)
  const root = await mkdtemp(join(tmpdir(), 'opencove-archive-e2e-'))
  const userDataDir = join(root, 'profile')
  const env = {
    OPENCOVE_WORKER_CLIENT: '1',
    OPENCOVE_TEST_USE_REAL_AGENTS: '0',
    OPENCOVE_TEST_AGENT_SESSION_SCENARIO: 'claude-prompt-strict',
    OPENCOVE_TEST_CLAUDE_HOOK_INSTALL_FAILURE: '0',
    CLAUDE_CONFIG_DIR: join(root, 'claude'),
    OPENCOVE_TEST_PROMPT_RECORD: join(root, 'submissions.jsonl'),
  }
  let app: ElectronApplication | undefined
  const connection = async () =>
    JSON.parse(await readFile(join(userDataDir, 'worker-control-surface.json'), 'utf8')) as {
      hostname: string
      port: number
      token: string
      pid: number
    }
  const cli = async (args: string[]) => {
    const info = await connection()
    return await new Promise<{ code: number; stdout: string; stderr: string }>(done => {
      execFile(
        process.execPath,
        [
          resolve('out/cli/opencove.mjs'),
          ...args,
          '--endpoint',
          `http://${info.hostname}:${info.port}`,
          '--token',
          info.token,
          '-o',
          'json',
        ],
        {
          env: { ...process.env, OPENCOVE_USER_DATA_DIR: userDataDir },
          timeout: 20_000,
        },
        (error, stdout, stderr) =>
          done({ code: error ? Number(error.code ?? 1) : 0, stdout, stderr }),
      )
    })
  }
  try {
    const first = await launchApp({
      userDataDir,
      cleanupUserDataDir: false,
      windowMode: 'inactive',
      env,
    })
    app = first.electronApp
    await clearAndSeedWorkspace(
      first.window,
      [
        {
          id: 'archive-task',
          title: 'Archive fixture',
          kind: 'task',
          status: null,
          position: { x: 100, y: 100 },
          width: 460,
          height: 280,
          task: {
            requirement: 'Archive one strict turn',
            status: 'todo',
            linkedAgentNodeId: null,
            lastRunAt: null,
            autoGeneratedTitle: false,
          },
        },
      ],
      {
        settings: {
          defaultProvider: 'claude-code',
          customModelEnabledByProvider: { 'claude-code': false },
        },
      },
    )
    await installPtySessionCapture(first.window)
    await first.window.locator('[data-testid="task-node-run-agent"]').click()
    await expect(first.window.locator('.terminal-node').first()).toContainText('STRICT_READY')
    await expect.poll(() => resolveFirstAgentSessionId(first.window)).not.toBeNull()
    const sessionId = (await resolveFirstAgentSessionId(first.window))!
    await writeToPty(first.window, { sessionId, data: 'manual baseline\r' })
    const snapshot = () =>
      first.window.evaluate(
        id =>
          window.opencoveApi.controlSurface.invoke<AgentRunSnapshot>({
            kind: 'query',
            id: 'agent.get',
            payload: { sessionId: id },
          }),
        sessionId,
      )
    await expect.poll(async () => (await snapshot()).state).toBe('idle')
    const nodeId = (await snapshot()).nodeId!
    const prompted = await cli([
      'agent',
      'prompt',
      '--node',
      nodeId,
      '--text',
      'Archived strict prompt',
      '--timeout',
      '10s',
    ])
    expect(prompted.code, prompted.stderr).toBe(0)
    const { turnId } = JSON.parse(prompted.stdout) as { turnId: string }
    const ended = await cli([
      'agent',
      'wait',
      '--node',
      nodeId,
      '--turn',
      turnId,
      '--timeout',
      '10s',
    ])
    expect(ended.code, ended.stderr).toBe(0)
    expect(JSON.parse(ended.stdout)).toMatchObject({
      turnId,
      persisted: true,
      outcome: 'completed',
    })
    const before = await cli(['agent', 'read', '--node', nodeId, '--turn', turnId])
    expect(before.code, before.stderr).toBe(0)
    const reply = JSON.parse(before.stdout)
    expect(reply).toMatchObject({ turnId, sessionId, persisted: true, message: 'Strict reply 2' })
    const oldEpoch = JSON.parse((await cli(['agent', 'list'])).stdout).epoch
    const oldPid = (await connection()).pid
    await app.close()
    app = undefined
    // Closing the Desktop must close its owned Worker, rather than merely replacing a renderer.
    await expect
      .poll(
        () => {
          try {
            process.kill(oldPid, 0)
            return false
          } catch {
            return true
          }
        },
        { timeout: 15_000 },
      )
      .toBe(true)
    const second = await launchApp({
      userDataDir,
      cleanupUserDataDir: false,
      windowMode: 'inactive',
      env,
    })
    app = second.electronApp
    expect(JSON.parse((await cli(['agent', 'list'])).stdout).epoch).not.toBe(oldEpoch)
    // No second prompt or provider relaunch is needed to read the historical original session.
    const after = await cli(['agent', 'read', '--node', nodeId, '--turn', turnId])
    expect(after.code, after.stderr).toBe(0)
    // Delivery records are volatile: the restarted Worker cannot correlate earlier deliveries.
    const { deliveryIds: _deliveriesBeforeRestart, ...durableReply } = reply
    expect(JSON.parse(after.stdout)).toMatchObject({
      ...durableReply,
      persisted: true,
      deliveryIds: [],
    })
    const waited = await cli([
      'agent',
      'wait',
      '--node',
      nodeId,
      '--turn',
      turnId,
      '--timeout',
      '5s',
    ])
    expect(waited.code, waited.stderr).toBe(0)
    expect(JSON.parse(waited.stdout)).toMatchObject({
      turnId,
      sessionId,
      outcome: 'completed',
      persisted: true,
    })
    const deleted = await cli(['node', 'delete', '--node', nodeId])
    expect(deleted.code, deleted.stderr).toBe(0)
    // Query by original session bypasses selector resolution and proves content was revoked too.
    const info = await connection()
    const revoked = await Promise.all(
      [
        { sessionId, turnId },
        { nodeId, turnId },
      ].map(async payload => {
        const response = await fetch(`http://${info.hostname}:${info.port}/invoke`, {
          method: 'POST',
          headers: { authorization: `Bearer ${info.token}`, 'content-type': 'application/json' },
          body: JSON.stringify({ kind: 'query', id: 'agent.finalMessage', payload }),
        })
        return await response.json()
      }),
    )
    for (const result of revoked) {
      expect(result).toMatchObject({
        ok: false,
        error: { code: 'agent.final_message_unavailable', details: { reason: 'turn_not_found' } },
      })
    }
    const gone = await cli(['agent', 'read', '--node', nodeId, '--turn', turnId])
    expect(gone.code).toBe(1)
    expect(gone.stdout).toBe('')
  } finally {
    await app?.close()
    await rm(root, { recursive: true, force: true })
  }
})
