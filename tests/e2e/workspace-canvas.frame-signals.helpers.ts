import { expect, type Page } from '@playwright/test'
import { mkdtemp, writeFile } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import path from 'node:path'
import {
  launchApp,
  removePathWithRetry,
  seedWorkspaceState,
  testWorkspacePath,
} from './workspace-canvas.helpers'
import {
  installPtySessionCapture,
  resolveFirstAgentSessionId,
  writeToPty,
} from './workspace-canvas.agent-status-watcher.helpers'

export async function setFrameMotion(window: Page, reduced: boolean) {
  const cdp = await window.context().newCDPSession(window)
  await cdp.send('Emulation.setEmulatedMedia', {
    features: [
      { name: 'prefers-reduced-motion', value: reduced ? 'reduce' : 'no-preference' },
      { name: 'prefers-reduced-transparency', value: 'no-preference' },
    ],
  })
}

export async function launchFrameSignals() {
  const fixture = await mkdtemp(path.join(tmpdir(), 'opencove-frames-'))
  const stub = path.join(fixture, 'agent.mjs')
  await writeFile(
    stub,
    `void import(${JSON.stringify(path.join(testWorkspacePath, 'scripts/test-agent-session-stub.mjs'))}); let input=''; process.stdin.on('data', data => { input+=data; if(input.includes('<test-frame-fail>')) process.exit(1) });`,
  )
  const app = await launchApp({
    windowMode: 'inactive',
    env: {
      OPENCOVE_TEST_ENABLE_SESSION_STATE_WATCHER: '1',
      OPENCOVE_TEST_AGENT_SESSION_SCENARIO: 'claude-hook-lifecycle',
      OPENCOVE_TEST_CLAUDE_HOOK_INSTALL_FAILURE: '0',
      OPENCOVE_TEST_AGENT_STUB_SCRIPT: stub,
    },
  })
  const { window } = app
  const close = async () => {
    await app.electronApp.close()
    await removePathWithRetry(fixture)
  }
  try {
    await seedWorkspaceState(window, {
      activeWorkspaceId: 'frame-signals',
      workspaces: [
        {
          id: 'frame-signals',
          name: 'Frame signals',
          path: testWorkspacePath,
          nodes: [
            {
              id: 'frame-task',
              title: 'Review frame signals',
              position: { x: 180, y: 140 },
              width: 460,
              height: 280,
              kind: 'task',
              status: null,
              task: {
                requirement: 'Review frame signals',
                status: 'todo',
                linkedAgentNodeId: null,
                lastRunAt: null,
                autoGeneratedTitle: false,
              },
            },
          ],
        },
      ],
      settings: {
        language: 'en',
        defaultProvider: 'claude-code',
        customModelEnabledByProvider: { 'claude-code': false },
        customModelByProvider: { 'claude-code': '' },
        customModelOptionsByProvider: { 'claude-code': [] },
      },
    })
    await setFrameMotion(window, false)
    await installPtySessionCapture(window)
    await window.getByTestId('task-node-run-agent').click()
    await expect(window.locator('.terminal-node')).toContainText('[opencove-test-hook] ready')
    const sessionId = (await resolveFirstAgentSessionId(window))!
    const node = window.locator('.react-flow__node:has(.terminal-node)').first()
    const id = (await node.getAttribute('data-id'))!
    return {
      ...app,
      node,
      id,
      close,
      send: (data: string) => writeToPty(window, { sessionId, data: `${data}\r` }),
    }
  } catch (error) {
    await close()
    throw error
  }
}
