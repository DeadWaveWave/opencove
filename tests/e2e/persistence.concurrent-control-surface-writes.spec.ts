/* eslint-disable no-await-in-loop -- CAS retries and timed race rounds require sequential execution. */
// Regression for external writes racing renderer publication.
import { expect, test } from '@playwright/test'
import { mkdir, mkdtemp, readFile } from 'node:fs/promises'
import { join } from 'node:path'
import { launchApp } from './workspace-canvas.app'
import { seedWorkspaceState } from './workspace-canvas.helpers'

const projectId = 'repro-project'

type Connection = { hostname: string; port: number; token: string }

async function invoke(
  connection: Connection,
  kind: 'query' | 'command',
  id: string,
  payload: unknown,
) {
  const response = await fetch(`http://${connection.hostname}:${connection.port}/invoke`, {
    method: 'POST',
    headers: { authorization: `Bearer ${connection.token}`, 'content-type': 'application/json' },
    body: JSON.stringify({ kind, id, payload }),
  })
  const parsed = (await response.json()) as { ok: boolean; value?: unknown; error?: unknown }
  if (!parsed.ok) {
    throw new Error(`${id} failed: ${JSON.stringify(parsed.error)}`)
  }
  return parsed.value as Record<string, unknown>
}

for (const scenario of ['task', 'note', 'echo'] as const) {
  test(`control surface ${scenario} writes survive renderer publication`, async () => {
    test.setTimeout(240_000)
    await mkdir('.codex-out/tmp', { recursive: true })
    const userDataDir = await mkdtemp(join(process.cwd(), '.codex-out/tmp/sync-'))
    const { electronApp, window } = await launchApp({ userDataDir, cleanupUserDataDir: true })
    try {
      await seedWorkspaceState(window, {
        activeWorkspaceId: projectId,
        workspaces: [
          {
            id: projectId,
            name: 'Repro',
            path: userDataDir,
            nodes: [
              {
                id: 'note-1',
                title: 'Original note',
                kind: 'note',
                position: { x: 700, y: 200 },
                width: 300,
                height: 250,
                task: { text: 'Note content' },
              },
              {
                id: 'task-1',
                title: 'Fix flaky login test',
                position: { x: 200, y: 200 },
                width: 276,
                height: 388,
                kind: 'task',
                status: null,
                task: {
                  requirement: 'Fix flaky login test',
                  status: 'todo',
                  priority: 'high',
                  tags: ['login', 'flaky-test'],
                  linkedAgentNodeId: null,
                  lastRunAt: null,
                  autoGeneratedTitle: false,
                },
              },
            ],
            spaces: [
              {
                id: 'space-main',
                name: 'Main',
                directoryPath: userDataDir,
                nodeIds: ['task-1'],
                rect: { x: 0, y: 0, width: 2400, height: 1400 },
              },
            ],
            activeSpaceId: 'space-main',
          },
        ],
      })

      let connection: Connection | null = null
      for (let attempt = 0; attempt < 60 && !connection; attempt += 1) {
        try {
          connection = JSON.parse(
            await readFile(join(userDataDir, 'worker-control-surface.json'), 'utf8'),
          ) as Connection
        } catch {
          await new Promise(resolve => setTimeout(resolve, 500))
        }
      }
      expect(connection).not.toBeNull()
      const conn = connection as Connection

      await new Promise(resolve => setTimeout(resolve, 3000))
      if (scenario === 'echo') {
        const written = await invoke(conn, 'command', 'node.update', {
          nodeId: 'task-1',
          kind: 'task',
          data: { tags: ['echo-probe'] },
        })
        await new Promise(resolve => setTimeout(resolve, 1500))
        const after = await invoke(conn, 'query', 'sync.state', null)
        expect(after.revision).toBe(written.revision)
        return
      }
      const tagSets = [['probe-tag'], ['login', 'flaky-test'], ['a', 'b', 'c'], ['solo']]
      const gapsMs = [80, 150]
      const log: string[] = []
      let lost = 0
      for (let round = 0; round < 8; round += 1) {
        const first = tagSets[round % tagSets.length]
        const second = tagSets[(round + 1) % tagSets.length]
        const gap = gapsMs[round % gapsMs.length]
        const a = await invoke(conn, 'command', 'node.update', {
          nodeId: scenario === 'task' ? 'task-1' : 'note-1',
          kind: scenario,
          ...(scenario === 'task' ? { data: { tags: first } } : { title: `first-${round}` }),
        })
        await new Promise(resolve => setTimeout(resolve, gap))
        const b = await invoke(conn, 'command', 'node.update', {
          nodeId: scenario === 'task' ? 'task-1' : 'note-1',
          kind: scenario,
          ...(scenario === 'task' ? { data: { tags: second } } : { title: `second-${round}` }),
        })
        await new Promise(resolve => setTimeout(resolve, 1500))
        const state = await invoke(conn, 'query', 'sync.state', null)
        const read = await invoke(conn, 'query', 'node.get', {
          nodeId: scenario === 'task' ? 'task-1' : 'note-1',
        })
        const tags = ((read.node as { data?: { tags?: string[] } }).data?.tags ?? []).join(',')
        const ok =
          scenario === 'task'
            ? tags === second.join(',')
            : (read.node as { title: string }).title === `second-${round}`
        if (!ok) {
          lost += 1
        }
        log.push(
          `round=${round} gap=${gap} revA=${String(a.revision)} revB=${String(b.revision)} now=${String(state.revision)} expected=${second.join(',')} got=${tags} ${ok ? 'OK' : 'LOST'}`,
        )
      }
      expect(lost, log.join('\n')).toBe(0)
    } finally {
      await electronApp.close()
    }
  })
}
