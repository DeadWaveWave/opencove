import { expect, test } from '@playwright/test'
import {
  launchApp,
  seedWorkspaceState,
  seededWorkspaceId,
  testWorkspacePath,
} from './workspace-canvas.helpers'

const commandCenterModifier = process.platform === 'darwin' ? 'Meta' : 'Control'

const archivedSpace = {
  id: 'archive-release',
  archivedAt: '2026-11-08T12:00:00.000Z',
  space: {
    id: 'space-release',
    name: 'Release',
    directoryPath: testWorkspacePath,
    labelColor: null,
    rect: { x: 0, y: 0, width: 900, height: 480 },
  },
  nodes: [
    {
      kind: 'task',
      id: 'task-archived',
      title: 'Release notes',
      frame: { position: { x: 40, y: 60 }, size: { width: 252, height: 356 } },
      requirement: 'Write the round 4 release notes.',
      status: 'ai_done',
      priority: 'high',
      tags: ['release', 'docs'],
      linkedAgentNodeId: 'agent-archived',
      lastRunAt: '2026-11-08T11:00:00.000Z',
      autoGeneratedTitle: false,
      createdAt: '2026-11-08T10:00:00.000Z',
      updatedAt: '2026-11-08T11:30:00.000Z',
    },
    {
      kind: 'agent',
      id: 'agent-archived',
      title: 'codex · gpt-5.2-codex',
      frame: { position: { x: 340, y: 60 }, size: { width: 480, height: 356 } },
      status: 'exited',
      provider: 'codex',
      prompt: 'Write the round 4 release notes.',
      model: 'gpt-5.2-codex',
      effectiveModel: 'gpt-5.2-codex',
      taskId: 'task-archived',
      startedAt: '2026-11-08T11:00:00.000Z',
      endedAt: '2026-11-08T11:30:00.000Z',
      exitCode: 0,
    },
  ],
}

test.describe('Space Archives - Task card', () => {
  test('replays an archived task as the task card, to read only', async () => {
    const { electronApp, window } = await launchApp()

    try {
      await seedWorkspaceState(window, {
        activeWorkspaceId: seededWorkspaceId,
        workspaces: [
          {
            id: seededWorkspaceId,
            name: 'workspace-seeded',
            path: testWorkspacePath,
            nodes: [],
            spaceArchiveRecords: [archivedSpace],
          },
        ],
        settings: { standardWindowSizeBucket: 'regular' },
      })

      await window.keyboard.press(`${commandCenterModifier}+P`)
      await window.locator('[data-testid="command-center-item-command:space-archives"]').click()
      const archivesWindow = window.locator('[data-testid="space-archives-window"]')
      await expect(archivesWindow).toBeVisible()
      await archivesWindow.locator('[data-testid="space-archives-window-record"]').first().click()
      await expect(
        archivesWindow.locator('[data-testid="space-archives-window-replay-canvas"]'),
      ).toBeVisible()

      const card = archivesWindow.locator(
        '[data-testid="space-archives-window-replay-node"][data-node-kind="task"]',
      )
      await expect(card).toBeVisible()
      await expect(card).toHaveAttribute('data-cove-part', 'window')
      await expect(card).toHaveAttribute('data-task-status', 'ai_done')
      await expect(card.locator('[data-cove-part="window-plate"]')).toHaveAttribute(
        'data-cove-kind',
        'plan',
      )

      // How far it had come, its labels, its requirement and its session; nothing to act on.
      await expect(card.locator('.task-node__step[data-filled="true"]')).toHaveCount(3)
      await expect(card.locator('.task-node__status-name')).toHaveText('AI_DONE')
      await expect(card.locator('.task-node__priority')).toHaveText('HIGH')
      await expect(card.locator('.task-node__tag')).toHaveText(['#release', '#docs'])
      const requirement = card.getByRole('textbox', { name: 'Task Requirement' })
      await expect(requirement).toHaveValue('Write the round 4 release notes.')
      await expect(requirement).not.toBeEditable()
      await expect(card.locator('.task-node__session--readout')).toHaveCount(1)
      await expect(card.locator('.task-node__sessions')).toContainText('1 session')
      await expect(card.getByRole('button')).toHaveCount(0)
      await expect(card.getByRole('radio')).toHaveCount(0)

      // The requirement stays on its plate.
      const plate = await card.locator('.task-node__plate').boundingBox()
      const text = await requirement.boundingBox()
      expect(plate).not.toBeNull()
      expect(text).not.toBeNull()
      expect(text!.x).toBeGreaterThanOrEqual(plate!.x)
      expect(text!.x + text!.width).toBeLessThanOrEqual(plate!.x + plate!.width)
    } finally {
      await electronApp.close()
    }
  })
})
