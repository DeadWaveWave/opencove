async function clickInlineTitleDisplay(display: Locator): Promise<void> {
  await expect(display).toBeVisible()
  await display.evaluate(element => {
    ;(element as HTMLElement).click()
  })
}

async function readInlineTitleMetrics(display: Locator): Promise<{
  text: string
  width: number
  textWidth: number
  textClientWidth: number
  textScrollWidth: number
}> {
  await expect(display).toBeVisible()

  return await display.evaluate(element => {
    const rect = element.getBoundingClientRect()
    const textElement = element.querySelector('.node-title-editor__display-text')
    const textRect = textElement?.getBoundingClientRect() ?? null

    return {
      text: element.textContent?.trim() ?? '',
      width: rect.width,
      textWidth: textRect?.width ?? 0,
      textClientWidth: textElement instanceof HTMLElement ? textElement.clientWidth : 0,
      textScrollWidth: textElement instanceof HTMLElement ? textElement.scrollWidth : 0,
    }
  })
}

async function readRestingBorderAlpha(button: Locator): Promise<number> {
  return await button.evaluate(element => {
    const style = getComputedStyle(element)
    if (style.borderTopWidth === '0px') {
      return 0
    }
    const probe = document.createElement('canvas').getContext('2d')
    if (!probe) {
      throw new Error('2d canvas unavailable')
    }
    probe.fillStyle = style.borderTopColor
    probe.fillRect(0, 0, 1, 1)
    return probe.getImageData(0, 0, 1, 1).data[3]
  })
}

test.describe('Workspace Canvas - Unified Node Chrome', () => {
  test('uses the same compact header height and button chrome across terminal, task, and note nodes', async () => {
    const { electronApp, window } = await launchApp()

    try {
      await clearAndSeedWorkspace(window, [
        {
          id: 'terminal-chrome',
          title: 'terminal-chrome',
          position: { x: 360, y: 120 },
          width: 460,
          height: 300,
        },
        {
          id: 'task-chrome',
          title: 'task chrome',
          position: { x: 900, y: 120 },
          width: 460,
          height: 280,
          kind: 'task',
          task: {
            requirement: 'Keep task chrome aligned with terminal and note nodes.',
            status: 'doing',
            priority: 'medium',
            tags: ['ui'],
            linkedAgentNodeId: null,
            lastRunAt: null,
            autoGeneratedTitle: false,
          },
        },
      ])

      const pane = window.locator('.workspace-canvas .react-flow__pane')
      await expect(pane).toBeVisible()
      await pane.dblclick({ position: { x: 380, y: 460 } })

      const terminalNode = window.locator('.terminal-node').first()
      const taskNode = window.locator('.task-node').first()
      const noteNode = window.locator('.note-node').first()

      await expect(terminalNode).toBeVisible()
      await expect(taskNode).toBeVisible()
      await expect(noteNode).toBeVisible()

      await expect(terminalNode.locator('.terminal-node__header')).toHaveCSS('height', '34px')
      await expect(taskNode.locator('.task-node__header')).toHaveCSS('height', '34px')
      await expect(noteNode.locator('.note-node__header')).toHaveCSS('height', '34px')

      const terminalClose = terminalNode.locator('.terminal-node__close')
      const taskMore = taskNode.locator('.task-node__icon-button--more')
      const taskClose = taskNode.locator('.task-node__icon-button--close')
      const noteClose = noteNode.locator('.note-node__close')
      const collapseButtons = window.locator('[data-testid="node-collapse"]')
      await expect(collapseButtons).toHaveCount(3)

      // Resting header buttons draw no box; the window controls are 24px squares everywhere.
      const windowControls = [terminalClose, taskClose, noteClose, ...(await collapseButtons.all())]
      await Promise.all(
        [taskMore, ...windowControls].map(async button => {
          await expect(button).toHaveCSS('background-color', 'rgba(0, 0, 0, 0)')
          expect(await readRestingBorderAlpha(button)).toBe(0)
        }),
      )
      await Promise.all(
        windowControls.map(async control => {
          await expect(control).toHaveCSS('height', '24px')
          const rect = await readLocatorClientRect(control)
          expect(Math.round(rect.width / rect.height)).toBe(1)
        }),
      )

      // Content is inset 6px from the frame's sides and bottom, and reads on the window's one
      // reading plate, a layer under the whole window that fades into the frame.
      await Promise.all(
        [terminalNode, taskNode, noteNode].map(async node => {
          const body = node.locator('[data-cove-part="window-body"]')
          await expect(body).toHaveCSS('margin-left', '6px')
          await expect(body).toHaveCSS('margin-right', '6px')
          await expect(body).toHaveCSS('margin-bottom', '6px')
          await expect(body).toHaveCSS('background-image', 'none')
          const plate = node.locator(':scope > [data-cove-part="window-plate"]')
          await expect(plate).toHaveCSS('position', 'absolute')
          expect(await plate.evaluate(element => getComputedStyle(element).maskImage)).toContain(
            'linear-gradient',
          )
        }),
      )
    } finally {
      await electronApp.close()
    }
  })

  test('edits titles only from the title hit area, which fills each title bar', async () => {
    const { electronApp, window } = await launchApp()

    try {
      await clearAndSeedWorkspace(window, [
        {
          id: 'terminal-rename',
          title: 'terminal-rename',
          position: { x: 360, y: 120 },
          width: 460,
          height: 300,
          kind: 'terminal',
        },
        {
          id: 'task-rename',
          title: 'task rename',
          position: { x: 900, y: 120 },
          width: 460,
          height: 280,
          kind: 'task',
          task: {
            requirement: 'Rename from header double click.',
            status: 'doing',
            priority: 'medium',
            tags: ['rename'],
            linkedAgentNodeId: null,
            lastRunAt: null,
            autoGeneratedTitle: false,
          },
        },
        {
          id: 'task-agent-linked',
          title: 'agent linked task',
          position: { x: 900, y: 460 },
          width: 460,
          height: 280,
          kind: 'task',
          task: {
            requirement: 'Rename linked agent from header double click.',
            status: 'doing',
            priority: 'medium',
            tags: ['rename'],
            linkedAgentNodeId: 'agent-rename',
            lastRunAt: null,
            autoGeneratedTitle: false,
          },
        },
        {
          id: 'agent-rename',
          title: 'codex · agent linked task',
          position: { x: 360, y: 460 },
          width: 460,
          height: 300,
          kind: 'agent',
          status: 'running',
          startedAt: '2026-04-29T10:00:00.000Z',
          endedAt: null,
          exitCode: null,
          lastError: null,
          agent: {
            provider: 'codex',
            prompt: 'Rename the linked agent',
            model: 'gpt-5.4',
            effectiveModel: 'gpt-5.4',
            launchMode: 'new',
            resumeSessionId: null,
            executionDirectory: '/tmp',
            expectedDirectory: null,
            directoryMode: 'workspace',
            customDirectory: null,
            shouldCreateDirectory: false,
            taskId: 'task-agent-linked',
          },
        },
      ])

      const sidebarToggle = window.locator('[data-testid="app-header-sidebar-toggle"]')
      await expect(sidebarToggle).toBeVisible()
      await sidebarToggle.click()
      await expect(window.locator('.app-shell--sidebar-collapsed')).toHaveCount(1)
      // The collapsed class is set before the grid transition finishes. Sample hit targets
      // only once the sidebar column has reached its destination, including in inactive windows.
      await expect
        .poll(() =>
          window
            .locator('.app-shell')
            .evaluate(element => Number.parseFloat(getComputedStyle(element).gridTemplateColumns)),
        )
        .toBe(0)

      const terminalNode = window.locator('.terminal-node').first()
      const agentNode = window
        .locator('.terminal-node')
        .filter({ has: window.locator('.terminal-node__status') })
        .first()
      const taskNode = window.locator('.task-node').first()

      const terminalHeader = terminalNode.locator('.terminal-node__header')
      const agentHeader = agentNode.locator('.terminal-node__header')
      const taskHeader = taskNode.locator('.task-node__header')
      const terminalTitleDisplay = terminalNode.locator(
        '[data-testid="terminal-node-title-display"]',
      )
      const agentTitleDisplay = agentNode.locator('[data-testid="terminal-node-title-display"]')
      const taskTitleDisplay = taskNode.locator('[data-testid="task-node-title-display"]')
      const terminalTitleInput = terminalNode.locator(
        '[data-testid="terminal-node-inline-title-input"]',
      )
      const agentTitleInput = agentNode.locator('[data-testid="terminal-node-inline-title-input"]')
      const taskTitleInput = taskNode.locator('[data-testid="task-node-inline-title-input"]')

      await expect(terminalHeader).toBeVisible()
      await expect(agentHeader).toBeVisible()
      await expect(taskHeader).toBeVisible()
      await expect(terminalTitleDisplay).toBeVisible()
      await expect(agentTitleDisplay).toBeVisible()
      await expect(taskTitleDisplay).toBeVisible()

      // Every renaming title is its window's drag surface and runs up to the controls; only the
      // kind tile beside it grabs without renaming. The whole bar shows the grab cursor, the
      // title included, so that it reads as the place to move the window from.
      const headers = [terminalHeader, agentHeader, taskHeader]
      const probes = await Promise.all(
        [terminalTitleDisplay, agentTitleDisplay, taskTitleDisplay].map(title =>
          title.evaluate(element => {
            const header = element.closest('[data-cove-part="window-header"]')!
            const tile = header.querySelector('[data-cove-part="kind-tile"]')!
            const controls = element.closest('[data-cove-part="window-title"]')!.nextElementSibling!
            const titleBox = element.getBoundingClientRect()
            const tileBox = tile.getBoundingClientRect()
            const points = [
              {
                x: titleBox.left + Math.min(titleBox.width - 2, 8),
                y: titleBox.top + titleBox.height / 2,
              },
              { x: titleBox.right - 8, y: titleBox.top + titleBox.height / 2 },
              { x: tileBox.left + tileBox.width / 2, y: tileBox.top + tileBox.height / 2 },
            ]

            // Rects and hit tests share one renderer task: no layout frame can invalidate the
            // coordinates between them. Keep hit identities and geometry in assertion failures.
            return {
              title: element.textContent,
              titleBox: titleBox.toJSON(),
              tileBox: tileBox.toJSON(),
              gapToControls: controls.getBoundingClientRect().left - titleBox.right,
              hits: points.map((point, index) => {
                const hit = document.elementFromPoint(point.x, point.y)
                const target = index === 2 ? tile : element
                return {
                  point,
                  cursor: hit ? getComputedStyle(hit).cursor : null,
                  onTarget: hit !== null && target.contains(hit),
                  hit: hit?.outerHTML,
                  control: hit?.closest('button')?.outerHTML,
                }
              }),
            }
          }),
        ),
      )

      for (const probe of probes) {
        const diagnostic = JSON.stringify(probe, null, 2)
        expect(probe.gapToControls, diagnostic).toBeLessThanOrEqual(12)
        expect(
          probe.hits.map(hit => hit.onTarget),
          diagnostic,
        ).toEqual([true, true, true])
        expect(
          probe.hits.map(hit => hit.cursor),
          diagnostic,
        ).toEqual(['grab', 'grab', 'grab'])
      }
      for (const header of headers) {
        await header.locator('[data-cove-part="kind-tile"]').click()
      }
      await expect(terminalTitleInput).toHaveCount(0)
      await expect(agentTitleInput).toHaveCount(0)
      await expect(taskTitleInput).toHaveCount(0)

      await clickInlineTitleDisplay(terminalTitleDisplay)
      await expect(terminalTitleInput).toBeVisible({ timeout: 30_000 })
      await terminalTitleInput.fill('terminal renamed')
      await terminalTitleInput.press('Enter')
      await expect(terminalTitleInput).toHaveCount(0)
      await expect(terminalHeader).toContainText('terminal renamed')

      await clickInlineTitleDisplay(agentTitleDisplay)
      await expect(agentTitleInput).toBeVisible({ timeout: 30_000 })
      await expect(agentTitleInput).toHaveValue('agent linked task')
      await agentTitleInput.fill('agent renamed')
      await agentTitleInput.press('Enter')
      await expect(agentTitleInput).toHaveCount(0)
      await expect(agentTitleDisplay).toHaveText('agent renamed')

      await clickInlineTitleDisplay(taskTitleDisplay)
      await expect(taskTitleInput).toBeVisible({ timeout: 30_000 })
      await taskTitleInput.fill('task renamed')
      await taskTitleInput.press('Enter')
      await expect(taskTitleInput).toHaveCount(0)
      await expect(taskHeader).toContainText('task renamed')
    } finally {
      await electronApp.close()
    }
  })

  test('keeps long inline titles visible after blur save', async () => {
    const { electronApp, window } = await launchApp()

    try {
      await clearAndSeedWorkspace(
        window,
        [
          {
            id: 'terminal-long-title',
            title: 'terminal',
            position: { x: 320, y: 120 },
            width: 460,
            height: 300,
            kind: 'terminal',
          },
          {
            id: 'task-long-title',
            title: 'task',
            position: { x: 840, y: 120 },
            width: 460,
            height: 280,
            kind: 'task',
            task: {
              requirement: 'Edit a long title, then blur into the requirement field.',
              status: 'doing',
              priority: 'medium',
              tags: ['rename'],
              linkedAgentNodeId: null,
              lastRunAt: null,
              autoGeneratedTitle: false,
            },
          },
          {
            id: 'note-long-title',
            title: 'note',
            position: { x: 320, y: 480 },
            width: 240,
            height: 280,
            kind: 'note',
            task: {
              text: 'Edit a long title, then blur into the note body.',
            },
          },
        ],
        {
          settings: { uiTheme: 'light' },
        },
      )

      const longTitle =
        '超长便签标题超长便签标题超长便签标题超长便签标题超长便签标题超长便签标题超长便签标题超长便签标题超长便签标题超长便签标题'
      const pane = window.locator('.workspace-canvas .react-flow__pane')
      await expect(pane).toBeVisible()

      const sidebarToggle = window.locator('[data-testid="app-header-sidebar-toggle"]')
      await expect(sidebarToggle).toBeVisible()
      await sidebarToggle.click()
      await expect(window.locator('.app-shell--sidebar-collapsed')).toHaveCount(1)
      await window.waitForTimeout(200)

      const terminalTitleDisplay = window
        .locator('[data-testid="terminal-node-title-display"]')
        .first()
      const taskTitleDisplay = window.locator('[data-testid="task-node-title-display"]').first()
      const noteTitleDisplay = window.locator('[data-testid="note-node-title-display"]').first()

      const terminalTitleInput = window
        .locator('[data-testid="terminal-node-inline-title-input"]')
        .first()
      const taskTitleInput = window.locator('[data-testid="task-node-inline-title-input"]').first()
      const noteTitleInput = window.locator('[data-testid="note-node-title-input"]').first()

      await clickInlineTitleDisplay(terminalTitleDisplay)
      await expect(terminalTitleInput).toBeVisible({ timeout: 30_000 })
      await terminalTitleInput.fill(longTitle)
      await clickPaneAtFlowPoint(window, pane, { x: 1180, y: 120 })
      await expect(terminalTitleInput).toHaveCount(0)

      await clickInlineTitleDisplay(taskTitleDisplay)
      await expect(taskTitleInput).toBeVisible({ timeout: 30_000 })
      await taskTitleInput.fill(longTitle)
      await clickPaneAtFlowPoint(window, pane, { x: 1180, y: 420 })
      await expect(taskTitleInput).toHaveCount(0)

      await clickInlineTitleDisplay(noteTitleDisplay)
      await expect(noteTitleInput).toBeVisible({ timeout: 30_000 })
      await noteTitleInput.fill(longTitle)
      await clickPaneAtFlowPoint(window, pane, { x: 1180, y: 680 })
      await expect(noteTitleInput).toHaveCount(0)

      const [terminalMetrics, taskMetrics, noteMetrics] = await Promise.all([
        readInlineTitleMetrics(terminalTitleDisplay),
        readInlineTitleMetrics(taskTitleDisplay),
        readInlineTitleMetrics(noteTitleDisplay),
      ])

      expect(terminalMetrics).toEqual(
        expect.objectContaining({
          text: longTitle,
        }),
      )
      expect(taskMetrics).toEqual(
        expect.objectContaining({
          text: longTitle,
        }),
      )
      expect(noteMetrics).toEqual(
        expect.objectContaining({
          text: longTitle,
        }),
      )

      for (const metrics of [terminalMetrics, taskMetrics, noteMetrics]) {
        expect(metrics.width).toBeGreaterThan(24)
        expect(metrics.textWidth).toBeGreaterThan(24)
        expect(metrics.textClientWidth).toBeGreaterThan(24)
        expect(metrics.textScrollWidth).toBeGreaterThan(metrics.textClientWidth)
      }
    } finally {
      await electronApp.close()
    }
  })
})
