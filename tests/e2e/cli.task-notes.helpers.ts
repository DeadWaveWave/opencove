export const projectId = 'task-notes-project'
export const taskId = 'task-notes-review'
export const noteId = 'task-notes-results'
export async function taskNotesApp(root: string) {
  const workspace = join(root, 'project')
  await mkdir(workspace)
  const stub = await writeLineageAgentStub(root)
  const options = {
    userDataDir: join(root, 'profile'),
    cleanupUserDataDir: false,
    env: {
      OPENCOVE_TEST_WORKSPACE: workspace,
      OPENCOVE_WORKER_CLIENT: '0',
      OPENCOVE_TEST_USE_REAL_AGENTS: '0',
      OPENCOVE_TEST_ENABLE_SESSION_STATE_WATCHER: '1',
      OPENCOVE_TEST_AGENT_STUB_SCRIPT: stub,
      OPENCOVE_TEST_AGENT_SESSION_SCENARIO: 'claude-prompt-strict',
      OPENCOVE_TEST_CLAUDE_HOOK_INSTALL_FAILURE: '0',
      OPENCOVE_E2E_DISABLE_CRASH_FALLBACK: '1',
      CLAUDE_CONFIG_DIR: join(root, 'claude'),
      CODEX_HOME: join(root, 'codex'),
    },
  }
  const launched = await launchApp(options)
  await seedWorkspaceState(launched.window, {
    activeWorkspaceId: projectId,
    settings: { agentFullAccess: false, language: 'en' },
    workspaces: [
      {
        id: projectId,
        name: 'Task notes',
        path: workspace,
        activeSpaceId: null,
        spaces: [],
        nodes: [
          {
            id: taskId,
            kind: 'task',
            title: 'Review',
            position: { x: 50, y: 50 },
            width: 460,
            height: 280,
            task: {
              requirement: 'Review and record a result',
              status: 'todo',
              linkedAgentNodeId: null,
              agentSessions: [
                {
                  id: 'previous-review',
                  provider: 'claude-code',
                  resumeSessionId: null,
                  prompt: 'Earlier review',
                  model: null,
                  effectiveModel: null,
                  boundDirectory: workspace,
                  lastDirectory: workspace,
                  createdAt: '2026-01-01T00:00:00.000Z',
                  lastRunAt: '2026-01-01T00:00:00.000Z',
                  endedAt: '2026-01-01T01:00:00.000Z',
                  exitCode: 0,
                  status: 'exited',
                },
              ],
              lastRunAt: null,
              autoGeneratedTitle: false,
            },
          },
          {
            id: noteId,
            kind: 'note',
            title: 'Results',
            position: { x: 600, y: 50 },
            width: 360,
            height: 260,
            task: { text: '' },
          },
        ],
      },
    ],
  })
  return { ...launched, options }
}
export function getNode(page: Page, nodeId: string) {
  return page.evaluate(
    async id =>
      window.opencoveApi.controlSurface.invoke<GetNodeResult>({
        kind: 'query',
        id: 'node.get',
        payload: { nodeId: id },
      }),
    nodeId,
  )
}
export function persistedNodes(page: Page) {
  return page.evaluate(async () => {
    const { state } = await window.opencoveApi.persistence.readAppState()
    return (
      state as {
        workspaces: {
          nodes: { id: string; agent?: { taskId: string | null }; task?: Record<string, unknown> }[]
        }[]
      }
    ).workspaces.flatMap(w => w.nodes)
  })
}
export async function focusNode(page: Page, nodeId: string) {
  await page.evaluate(
    async id =>
      window.opencoveApi.controlSurface.invoke({
        kind: 'command',
        id: 'canvas.focus',
        payload: { target: { kind: 'node', nodeId: id } },
      }),
    nodeId,
  )
}
export function successfulJson(result: { code: number; stdout: string; stderr: string }) {
  expect(result.code, result.stderr).toBe(0)
  expect(result.stdout).toMatch(/\n$/)
  return JSON.parse(result.stdout)
}
