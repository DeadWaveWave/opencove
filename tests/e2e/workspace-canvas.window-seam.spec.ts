/* eslint-disable no-await-in-loop -- Both themes and each window share one Electron window and are read in turn. */
import { expect, test, type Locator, type Page } from '@playwright/test'
import { clearAndSeedWorkspace, launchApp } from './workspace-canvas.helpers'
import { PIXEL_EFFECTS_DISABLED } from './workspace-canvas.pixel-effects.helpers'

/**
 * The largest channel step (0-255) between neighbouring screen rows within 4px of a window
 * header's bottom edge, across the frame's width. The header's dithered fades move up to 3 levels
 * from row to row; a rule, a plate edge, or a header layer that stops near the header's bottom (in
 * its clear 1px rule or at its edge) is a step of 9 or more.
 */
async function readHeaderSeamStep(window: Page, node: Locator): Promise<number> {
  const box = await node.locator('[data-cove-part="window-header"]').evaluate(header => {
    const frame = header.closest('[data-cove-part="window"]')!.getBoundingClientRect()
    return {
      x: Math.ceil(frame.left) + 2,
      width: Math.floor(frame.width) - 4,
      bottom: Math.round(header.getBoundingClientRect().bottom),
    }
  })
  const png = await window.screenshot({
    clip: { x: box.x, y: box.bottom - 4, width: box.width, height: 8 },
    animations: 'disabled',
  })
  return await window.evaluate(async base64 => {
    const bytes = Uint8Array.from(atob(base64), char => char.charCodeAt(0))
    const bitmap = await createImageBitmap(new Blob([bytes], { type: 'image/png' }))
    const canvas = new OffscreenCanvas(bitmap.width, bitmap.height)
    const context = canvas.getContext('2d')!
    context.drawImage(bitmap, 0, 0)
    const { data, width, height } = context.getImageData(0, 0, bitmap.width, bitmap.height)
    let step = 0
    for (let row = 1; row < height; row += 1) {
      const above = (row - 1) * width * 4
      const below = row * width * 4
      for (let offset = 0; offset < width * 4; offset += 1) {
        if (offset % 4 !== 3) {
          step = Math.max(step, Math.abs(data[above + offset]! - data[below + offset]!))
        }
      }
    }
    return step
  }, png.toString('base64'))
}

/**
 * A terminal draws on the reading plate only when its xterm is transparent (macOS by default).
 * Opaque terminals (Windows and Linux by default) and solid windows fill the plate with the
 * terminal colour, and the header must fade into that colour instead.
 */
const TERMINAL_CASES = [
  { terminalBackground: 'transparent' },
  { terminalBackground: 'opaque' },
  { terminalBackground: 'transparent', windowMaterial: 'solid' },
] as const
const SEAM_CASES = (['dark', 'light'] as const).flatMap(uiTheme =>
  TERMINAL_CASES.map(terminal => ({ uiTheme, terminal })),
)

test.describe('Workspace Canvas - Seamless window header', () => {
  test('header and reading plate meet without a visible line in dark and light', async () => {
    const { electronApp, window } = await launchApp()

    try {
      for (const { uiTheme, terminal } of SEAM_CASES) {
        await clearAndSeedWorkspace(
          window,
          [
            {
              id: 'seam-terminal',
              title: 'seam terminal',
              position: { x: 360, y: 120 },
              width: 460,
              height: 300,
            },
            {
              id: 'seam-task',
              title: 'seam task',
              position: { x: 900, y: 120 },
              width: 460,
              height: 280,
              kind: 'task',
              task: {
                requirement: 'Keep the header and the plate one surface.',
                status: 'doing',
                priority: 'medium',
                tags: [],
                linkedAgentNodeId: null,
                lastRunAt: null,
                autoGeneratedTitle: false,
              },
            },
            {
              id: 'seam-note',
              title: 'seam note',
              position: { x: 360, y: 480 },
              width: 320,
              height: 220,
              kind: 'note',
              task: { text: 'Release notes' },
            },
          ],
          { settings: { uiTheme, ...terminal, ...PIXEL_EFFECTS_DISABLED } },
        )
        await expect
          .poll(() => window.evaluate(() => document.documentElement.dataset.coveTheme ?? null))
          .toBe(uiTheme)
        // Texture is not a seam: the canvas grid shows through the glass and the glass has grain,
        // and either can differ from one screen row to the next. Both are switched off so only a
        // line where the header ends can register.
        await window.addStyleTag({
          content: `.react-flow__background { display: none; }
            :root { --cove-glass-grain-dark: none !important; --cove-glass-grain-light: none !important; }`,
        })

        const terminalNode = window.locator('.terminal-node').first()
        await expect(terminalNode.locator('[data-cove-part="window-body"]')).toHaveAttribute(
          'data-cove-terminal-background',
          terminal.terminalBackground,
        )
        const nodes = [terminalNode]
        if (terminal === TERMINAL_CASES[0]) {
          nodes.push(window.locator('.task-node').first(), window.locator('.note-node').first())
        }
        for (const node of nodes) {
          await expect(node).toBeVisible()
          const body = node.locator('[data-cove-part="window-body"]')
          // The plate is as far from the frame's right edge as from its left (a note's plate is
          // its textarea, which once ran 12px wide and touched the right edge).
          const gaps = await body.evaluate(element => {
            const frame = element.closest('[data-cove-part="window"]')!.getBoundingClientRect()
            const plate = element.getBoundingClientRect()
            return { left: plate.left - frame.left, right: frame.right - plate.right }
          })
          expect(Math.abs(gaps.left - gaps.right)).toBeLessThanOrEqual(0.5)
          // No rule under the header, no top edge or corners on the plate, and nothing in the
          // header (its kind wash included) that stops at the header's bottom edge.
          await expect(body).toHaveCSS('border-top-left-radius', '0px')
          expect(
            await readHeaderSeamStep(window, node),
            `${uiTheme} ${JSON.stringify(terminal)} ${await node.getAttribute('class')}`,
          ).toBeLessThanOrEqual(4)
        }
      }
    } finally {
      await electronApp.close()
    }
  })
})
