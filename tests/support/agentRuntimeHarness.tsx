export interface RuntimeCanvasContext {
  workspaceId: string
  canvasState: ReturnType<typeof useWorkspaceCanvasState>
  nodeStore: ReturnType<typeof useWorkspaceCanvasNodesStore>
  /**
   * A writer whose identity never changes and that writes through the node store of the latest
   * render. A case that pins a reader's place in a dependency list uses it, so that the writer
   * changing with the workspace cannot rebuild the callback and hide a missing reader.
   */
  stableSetNodes: ReturnType<typeof useWorkspaceCanvasNodesStore>['setNodes']
  /** The same for `updateCanvasDocument`. */
  stableUpdateCanvasDocument: ReturnType<
    typeof useWorkspaceCanvasNodesStore
  >['updateCanvasDocument']
}

export interface FlushRecord {
  /** The workspace's document when the flush ran. */
  document: WorkspaceDocument
  /** Writes to the app store before the flush ran. */
  notificationsBefore: number
}

export interface TwoWorkspaces<Result> {
  harness: CanvasDocumentHarness
  view: RenderHookResult<Result, undefined>
  /** The flushes, each with the document it saw and how many store writes came before it. */
  flushes: FlushRecord[]
  /** Shows workspace B: the provider and the app store's active workspace move together. */
  showB: () => void
}

/**
 * Seeds workspaces A and B and renders `useHook` under the canvas store provider of the shown
 * workspace, with the canvas state and the node store of that workspace wired as the canvas wires
 * them. A flush spy records the store's document when it is called.
 */
export function renderInTwoWorkspaces<Result>(
  useHook: (context: RuntimeCanvasContext) => Result,
  documents: { a?: WorkspaceContent; b?: WorkspaceContent } = {},
): TwoWorkspaces<Result> {
  const harness = createCanvasDocumentHarness({ workspaceId: WORKSPACE_A, ...documents.a })
  useAppStore.setState(state => ({
    workspaces: [
      ...state.workspaces,
      { ...state.workspaces[0], id: WORKSPACE_B, nodes: [], spaces: [], ...documents.b },
    ],
  }))
  const flushes: FlushRecord[] = []
  let shown = WORKSPACE_A
  // The harness's own registration is replaced for the test; its teardown leaves this one alone.
  registerWorkspaceDocumentPersistFlush(() => {
    harness.flush()
    flushes.push({
      document: readWorkspaceDocument(shown) as WorkspaceDocument,
      notificationsBefore: harness.notifications.mock.calls.length,
    })
  })
  const view = renderInCanvasDocument(
    () => {
      const workspaceId = shown
      const nodes = useWorkspaceCanvasStoreNodes(workspaceId)
      const spaces = useAppStore(
        state =>
          state.workspaces.find(workspace => workspace.id === workspaceId)?.spaces ?? EMPTY_SPACES,
      )
      const canvasState = useWorkspaceCanvasState({
        workspaceId,
        nodes,
        spaces,
        viewport: { x: 0, y: 0, zoom: 1 },
      })
      const publishers = useWorkspaceCanvasNodePublishers({ ...canvasState, workspaceId })
      const nodeStore = useWorkspaceCanvasNodesStore({
        workspaceId,
        workspacePath: `/tmp/${workspaceId}`,
        nodes: canvasState.flowNodes,
        spacesRef: canvasState.spacesRef,
        onRequestPersistFlush: requestWorkspaceDocumentPersistFlush,
        onNodesCommitted: publishers.publishCommittedNodes,
        isLiveGestureActive: publishers.isLiveGestureActive,
        standardWindowSizeBucket: 'regular',
        browserDefaultMode: 'iframe',
      })
      const latestSetNodes = useRef(nodeStore.setNodes)
      latestSetNodes.current = nodeStore.setNodes
      const stableSetNodes = useCallback<typeof nodeStore.setNodes>(
        (updater, options) => latestSetNodes.current(updater, options),
        [],
      )
      const latestUpdateCanvasDocument = useRef(nodeStore.updateCanvasDocument)
      latestUpdateCanvasDocument.current = nodeStore.updateCanvasDocument
      const stableUpdateCanvasDocument = useCallback<typeof nodeStore.updateCanvasDocument>(
        (recipe, options) => latestUpdateCanvasDocument.current(recipe, options),
        [],
      )
      return useHook({
        workspaceId,
        canvasState,
        nodeStore,
        stableSetNodes,
        stableUpdateCanvasDocument,
      })
    },
    { workspaceId: () => shown },
  )
  return {
    harness,
    view,
    flushes,
    showB: () => {
      act(() => {
        shown = WORKSPACE_B
        useAppStore.setState({ activeWorkspaceId: WORKSPACE_B })
        view.rerender()
      })
    },
  }
}

export function documentOf(workspaceId: string): WorkspaceDocument {
  const document = readWorkspaceDocument(workspaceId)
  if (!document) {
    throw new Error(`workspace ${workspaceId} is not in the store`)
  }
  return document
}

export function nodeOf(workspaceId: string, nodeId: string): Node<TerminalNodeData> {
  const node = documentOf(workspaceId).nodes.find(candidate => candidate.id === nodeId)
  if (!node) {
    throw new Error(`node ${nodeId} is not in workspace ${workspaceId}`)
  }
  return node
}

