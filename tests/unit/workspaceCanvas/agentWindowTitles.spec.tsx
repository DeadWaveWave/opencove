import React, { type ComponentProps } from 'react'
import { fireEvent, render, screen } from '@testing-library/react'
import { describe, expect, it, vi } from 'vitest'
import type { Node } from '@xyflow/react'
import type { TerminalNodeData } from '@contexts/workspace/presentation/renderer/types'
import type { TerminalNodeProps } from '@contexts/workspace/presentation/renderer/components/TerminalNode.types'
import { WorkspaceCanvasTerminalNodeType } from '@contexts/workspace/presentation/renderer/components/workspaceCanvas/nodeTypes.terminal'
import { CollapsedWindow } from '@contexts/workspace/presentation/renderer/components/workspaceCanvas/collapse/CollapsedWindow'
import { WorkspaceCollapseContext } from '@contexts/workspace/presentation/renderer/components/workspaceCanvas/collapse/WorkspaceCollapseContext'
import { TerminalNodeHeader } from '@contexts/workspace/presentation/renderer/components/terminalNode/TerminalNodeHeader'

const flow = vi.hoisted(() => ({ nodes: [] as Node<TerminalNodeData>[] }))

vi.mock('@xyflow/react', () => ({
  useStore: (selector: (state: { nodes: Node<TerminalNodeData>[] }) => unknown) => selector(flow),
  useStoreApi: () => ({ getState: () => flow }),
}))

vi.mock('@contexts/workspace/presentation/renderer/components/TerminalNode', () => ({
  TerminalNode: (props: TerminalNodeProps) => (
    <TerminalNodeHeader
      title={props.title}
      fixedTitlePrefix={props.fixedTitlePrefix}
      kind={props.isAgentPresentation ? 'agent' : props.kind}
      agentProvider={props.terminalProvider}
      status={props.status}
      onTitleCommit={props.onTitleCommit}
      onClose={() => undefined}
    />
  ),
}))

function nodeData(overrides: Partial<TerminalNodeData> = {}): TerminalNodeData {
  return {
    kind: 'agent',
    sessionId: '',
    title: 'Codex · Review API',
    width: 640,
    height: 520,
    status: 'standby',
    startedAt: null,
    endedAt: null,
    exitCode: null,
    lastError: null,
    scrollback: null,
    task: null,
    note: null,
    image: null,
    document: null,
    website: null,
    agent: {
      provider: 'codex',
      prompt: 'Review API',
      model: null,
      effectiveModel: null,
      launchMode: 'new',
      resumeSessionId: null,
      executionDirectory: '/project',
      expectedDirectory: null,
      directoryMode: 'workspace',
      customDirectory: null,
      shouldCreateDirectory: false,
      taskId: 'task',
    },
    ...overrides,
  }
}

function createCollapseContext(nodes: Node<TerminalNodeData>[]) {
  return {
    nodes,
    workspaceId: 'project',
    spaces: [],
    collapsedNodeIds: {},
    collapsedSpaceIds: {},
    toggleNode: vi.fn(),
    revealNode: vi.fn(),
    collapseAndArrange: vi.fn(),
    undoArrange: vi.fn(),
    canUndoArrange: () => false,
  }
}

function renderTitles(data: TerminalNodeData, linkedTaskTitle?: string) {
  flow.nodes = linkedTaskTitle
    ? [
        {
          id: 'task',
          position: { x: 0, y: 0 },
          data: nodeData({
            kind: 'task',
            title: linkedTaskTitle,
            agent: null,
            task: {
              requirement: '',
              status: 'doing',
              priority: 'medium',
              tags: [],
              linkedAgentNodeId: 'agent',
              agentSessions: [],
              lastRunAt: null,
              autoGeneratedTitle: false,
              createdAt: null,
              updatedAt: null,
            },
          }),
        },
      ]
    : []
  const props: ComponentProps<typeof WorkspaceCanvasTerminalNodeType> = {
    id: 'agent',
    data,
    terminalFontSize: 14,
    terminalFontFamily: null,
    terminalDisplayCalibration: null,
    selectNode: vi.fn(),
    closeNodeRef: { current: vi.fn(async () => undefined) },
    resizeNodeRef: { current: vi.fn() },
    copyAgentLastMessageRef: { current: vi.fn(async () => undefined) },
    reloadAgentSessionRef: { current: vi.fn(async () => undefined) },
    listAgentSessionsRef: { current: vi.fn(async () => []) },
    switchAgentSessionRef: { current: vi.fn(async () => undefined) },
    updateNodeScrollbackRef: { current: vi.fn() },
    normalizeViewportForTerminalInteractionRef: { current: vi.fn() },
    updateTerminalTitleRef: { current: vi.fn() },
    clearTerminalAgentOverlayRef: { current: vi.fn() },
    renameTerminalTitleRef: { current: vi.fn() },
  }
  const collapse = createCollapseContext(flow.nodes)
  const view = render(
    <WorkspaceCollapseContext.Provider value={collapse}>
      <WorkspaceCanvasTerminalNodeType {...props} />
      <CollapsedWindow id="agent" data={data} onExpand={vi.fn()} />
    </WorkspaceCollapseContext.Provider>,
  )
  return { ...view, rename: props.renameTerminalTitleRef.current }
}

describe('Agent window title presentation', () => {
  it.each([
    { title: 'Codex · Review API', pinned: false, linked: undefined, expected: 'Review API' },
    { title: 'codex · Old model', pinned: false, linked: 'Current task', expected: 'Current task' },
    { title: 'codex · My name', pinned: true, linked: 'Current task', expected: 'My name' },
    { title: 'codex · Codex · 示例会话', pinned: true, linked: undefined, expected: '示例会话' },
    {
      title: 'Review Codex · API',
      pinned: true,
      linked: undefined,
      expected: 'Review Codex · API',
    },
  ])('uses the same label in both states: $title', ({ title, pinned, linked, expected }) => {
    const data = nodeData({ title, titlePinnedByUser: pinned })
    const { container, rename } = renderTitles(data, linked)
    expect(screen.getByTestId('terminal-node-title-display').textContent).toBe(expected)
    expect(container.querySelector('.cove-collapsed-window__title')?.textContent).toBe(expected)
    expect(container.querySelector('.terminal-node__title-prefix')).toBeNull()
    expect(data.title).toBe(title)
    expect(container.querySelectorAll('[data-agent-provider="codex"]')).toHaveLength(2)
    fireEvent.click(screen.getByTestId('terminal-node-title-display'))
    const input = screen.getByTestId('terminal-node-inline-title-input')
    expect(input).toHaveValue(expected)
    fireEvent.change(input, { target: { value: 'My edited name' } })
    fireEvent.keyDown(input, { key: 'Enter' })
    expect(rename).toHaveBeenCalledWith('agent', 'My edited name')
  })

  it.each([true, false])(
    'projects terminal Agent labels only while its overlay is active: %s',
    active => {
      const data = nodeData({
        kind: 'terminal',
        title: 'Claude Code · Review API',
        titlePinnedByUser: true,
        agent: null,
        agentOverlay: active
          ? { provider: 'claude-code', status: 'standby', startedAtMs: 1 }
          : null,
        terminalAgentBinding: { provider: 'claude-code', resumeSessionId: 'old-session' },
      })
      const { container } = renderTitles(data)
      const expected = active ? 'Review API' : 'Claude Code · Review API'
      expect(screen.getByTestId('terminal-node-title-display').textContent).toBe(expected)
      expect(container.querySelector('.cove-collapsed-window__title')?.textContent).toBe(expected)
      expect(data.title).toBe('Claude Code · Review API')
    },
  )
})
