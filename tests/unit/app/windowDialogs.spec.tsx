import React, { useState } from 'react'
import { act, fireEvent, render, screen } from '@testing-library/react'
import { afterEach, describe, expect, it, vi } from 'vitest'
import { DeleteProjectDialog } from '../../../src/app/renderer/shell/components/DeleteProjectDialog'
import { TaskEditorWindow } from '../../../src/contexts/workspace/presentation/renderer/components/workspaceCanvas/windows/TaskEditorWindow'
import type { TaskEditorState } from '../../../src/contexts/workspace/presentation/renderer/components/workspaceCanvas/types'

function TaskEditorHarness() {
  const [taskEditor, setTaskEditor] = useState<TaskEditorState | null>({
    nodeId: 'task-node',
    initialTitle: 'Task',
    initialAutoGeneratedTitle: false,
    titleGeneratedInEditor: false,
    title: 'Task',
    requirement: 'Keep this draft',
    priority: 'medium',
    selectedTags: [],
    autoGenerateTitle: false,
    isGeneratingTitle: false,
    isSaving: false,
    error: null,
  })

  return (
    <TaskEditorWindow
      taskEditor={taskEditor}
      taskTitleProviderLabel="Codex"
      taskTitleModelLabel="default"
      taskTagOptions={[]}
      update={recipe => setTaskEditor(prev => (prev ? recipe(prev) : prev))}
      closeTaskEditor={() => setTaskEditor(null)}
      generateTaskEditorTitle={async () => undefined}
      saveTaskEdits={async () => undefined}
    />
  )
}

describe('Window dialogs', () => {
  afterEach(() => vi.useRealTimers())

  it('focuses cancel for deletion and restores the trigger after Escape', () => {
    vi.useFakeTimers()
    const onConfirm = vi.fn()
    function Harness() {
      const [open, setOpen] = useState(false)
      return (
        <>
          <button onClick={() => setOpen(true)}>Remove project</button>
          {open ? (
            <DeleteProjectDialog
              workspaceName="OpenCove"
              isRemoving={false}
              onCancel={() => setOpen(false)}
              onConfirm={onConfirm}
            />
          ) : null}
        </>
      )
    }

    render(<Harness />)
    const trigger = screen.getByRole('button', { name: 'Remove project' })
    trigger.focus()
    fireEvent.click(trigger)
    act(() => vi.runOnlyPendingTimers())
    expect(screen.getByRole('alertdialog')).toHaveAttribute('aria-modal', 'true')
    expect(screen.getByTestId('workspace-project-delete-cancel')).toHaveFocus()
    fireEvent.keyDown(document.activeElement!, { key: 'Tab', shiftKey: true })
    expect(screen.getByTestId('workspace-project-delete-confirm')).toHaveFocus()
    fireEvent.keyDown(document, { key: 'Escape' })
    act(() => vi.runOnlyPendingTimers())
    expect(screen.queryByRole('alertdialog')).not.toBeInTheDocument()
    expect(trigger).toHaveFocus()
    expect(onConfirm).not.toHaveBeenCalled()
  })

  it('does not dismiss a deletion while its existing owner is removing', () => {
    const onCancel = vi.fn()
    render(
      <DeleteProjectDialog
        workspaceName="OpenCove"
        isRemoving
        onCancel={onCancel}
        onConfirm={vi.fn()}
      />,
    )
    fireEvent.keyDown(document, { key: 'Escape' })
    fireEvent.pointerDown(screen.getByRole('alertdialog').parentElement!)
    expect(onCancel).not.toHaveBeenCalled()
    expect(screen.getByTestId('workspace-project-delete-confirm')).toBeDisabled()
  })

  it('closes only the top nested template dialog and preserves the task draft', () => {
    vi.useFakeTimers()
    render(<TaskEditorHarness />)
    act(() => vi.runOnlyPendingTimers())
    expect(screen.getByTestId('workspace-task-editor-title')).toHaveFocus()
    const requirement = screen.getByTestId('workspace-task-editor-requirement')

    fireEvent.click(screen.getByTestId('workspace-task-editor-open-prompt-templates'))
    act(() => vi.runOnlyPendingTimers())
    const addTemplate = screen.getByTestId('task-editor-prompt-templates-add-global')
    addTemplate.focus()
    expect(addTemplate).toHaveFocus()
    fireEvent.click(addTemplate)
    act(() => vi.runOnlyPendingTimers())
    expect(screen.getAllByRole('dialog')).toHaveLength(2)
    fireEvent.keyDown(document, { key: 'Escape' })
    act(() => vi.runOnlyPendingTimers())

    expect(screen.getAllByRole('dialog')).toHaveLength(1)
    expect(requirement).toHaveValue('Keep this draft')
    fireEvent.keyDown(document, { key: 'Escape' })
    expect(screen.queryByRole('dialog')).not.toBeInTheDocument()
  })
})
