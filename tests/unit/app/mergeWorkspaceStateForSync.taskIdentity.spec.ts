import { describe, expect, it } from 'vitest'
import { toShellWorkspaceStateForSync } from '../../../src/app/renderer/shell/hooks/workerSync/mergeWorkspaceStateForSync'
import type {
  PersistedWorkspaceState,
  TaskAgentSessionRecord,
  TaskNodeData,
} from '../../../src/contexts/workspace/presentation/renderer/types'

const session: TaskAgentSessionRecord = {
  id: 'run-1',
  provider: 'codex',
  resumeSessionId: 'thread-1',
  resumeSessionIdVerified: true,
  prompt: 'Build it',
  model: null,
  effectiveModel: null,
  boundDirectory: '/repo',
  lastDirectory: '/repo',
  createdAt: '2026-11-06T00:00:00Z',
  lastRunAt: '2026-11-06T00:00:00Z',
  endedAt: null,
  exitCode: null,
  status: 'standby',
}

function fixture(taskOverrides: Partial<TaskNodeData> = {}) {
  const task: TaskNodeData = {
    requirement: 'Task',
    status: 'todo',
    priority: 'medium',
    tags: [],
    agentSessions: [],
    linkedAgentNodeId: null,
    lastRunAt: null,
    autoGeneratedTitle: false,
    createdAt: null,
    updatedAt: null,
    ...taskOverrides,
  }
  const persisted: PersistedWorkspaceState = {
    id: 'workspace-1',
    name: 'Workspace',
    path: '/repo',
    worktreesRoot: '',
    viewport: { x: 0, y: 0, zoom: 1 },
    isMinimapVisible: true,
    spaces: [],
    activeSpaceId: null,
    spaceArchiveRecords: [],
    nodes: [
      {
        id: 'task-1',
        kind: 'task',
        title: 'Task',
        position: { x: 0, y: 0 },
        width: 360,
        height: 300,
        status: null,
        startedAt: null,
        endedAt: null,
        exitCode: null,
        lastError: null,
        scrollback: null,
        agent: null,
        task,
      },
    ],
  }
  const existing = toShellWorkspaceStateForSync(persisted, undefined)
  const incoming = structuredClone(persisted)
  incoming.name = 'Renamed by another client'
  return { existing, incoming }
}

describe('task identity across Worker refreshes', () => {
  it('preserves an idle task when an unrelated workspace field changes', () => {
    const { existing, incoming } = fixture()
    const merged = toShellWorkspaceStateForSync(incoming, existing)
    expect(merged.name).toBe(incoming.name)
    expect(merged.nodes).toBe(existing.nodes)
  })

  it('preserves deserialized tags and session history when their contents are unchanged', () => {
    const { existing, incoming } = fixture({ tags: ['release'], agentSessions: [session] })
    expect(toShellWorkspaceStateForSync(incoming, existing).nodes).toBe(existing.nodes)
  })

  it.each<[string, (task: TaskNodeData) => void]>([
    [
      'tags',
      task => {
        task.tags[0] = 'review'
      },
    ],
    [
      'session fields',
      task => {
        task.agentSessions[0].resumeSessionIdVerified = false
      },
    ],
    [
      'task status',
      task => {
        task.status = 'done'
      },
    ],
  ])('still applies edits to %s', (_field, edit) => {
    const { existing, incoming } = fixture({ tags: ['release'], agentSessions: [session] })
    const task = incoming.nodes[0].task as TaskNodeData
    edit(task)
    const merged = toShellWorkspaceStateForSync(incoming, existing)
    expect(merged.nodes[0]).not.toBe(existing.nodes[0])
    expect(merged.nodes[0].data.task).toEqual(task)
    expect(existing.nodes[0].data.task?.tags).toEqual(['release'])
  })
})
