import React from 'react'
import { render } from '@testing-library/react'
import { describe, expect, it, vi } from 'vitest'
import type { CanvasTaskCommands } from '../../../src/contexts/workspace/presentation/renderer/components/workspaceCanvas/nodeCommands'
import { WorkspaceCanvasTaskNodeType } from '../../../src/contexts/workspace/presentation/renderer/components/workspaceCanvas/nodeTypes.task'
import type { TerminalNodeData } from '../../../src/contexts/workspace/presentation/renderer/types'
import { CanvasStoreTestProvider } from '../../support/canvasStoreTestHarness'
import { createStoreBackedChannels } from '../../support/workspaceCanvasStoreHarness'
import {
  NodeCommandsProvider,
  noopNodeCommands,
  withTaskCommands,
} from '../../support/nodeCommandsFixture'

// S7 of #647, PR 7: every callback the task body hands TaskNode reaches the command it is named
// for, with its id and arguments, and no other: the seven task commands, and the window commands
// of the body's frame (delete, resize, select, focus). The seven refs they replace did the same.

vi.mock('@xyflow/react', () => ({
  useStore: (selector: (state: unknown) => unknown) => selector({ nodes: [] }),
  useStoreApi: () => ({ getState: () => ({ nodes: [] }) }),
}))
type TaskNodeProps = {
  onClose: () => void
  onOpenEditor: () => void
  onQuickTitleSave: (title: string) => void
  onQuickRequirementSave: (requirement: string) => void
  onRunAgent: () => void
  onResize: (frame: unknown) => void
  onStatusChange: (status: string) => void
  onResumeAgentSession: (recordId: string) => void
  onRemoveAgentSessionRecord: (recordId: string) => void
  onInteractionStart?: (options?: {
    normalizeViewport?: boolean
    selectNode?: boolean
    shiftKey?: boolean
  }) => void
}
const captured = vi.hoisted(() => ({ props: null as null | Record<string, unknown> }))
vi.mock('../../../src/contexts/workspace/presentation/renderer/components/TaskNode', () => ({
  TaskNode: (props: Record<string, unknown>) => {
    captured.props = props
    return null
  },
}))

const data = {
  sessionId: '',
  title: 'Task',
  width: 460,
  height: 280,
  kind: 'task',
  status: null,
  startedAt: null,
  endedAt: null,
  exitCode: null,
  lastError: null,
  scrollback: null,
  agent: null,
  note: null,
  image: null,
  document: null,
  website: null,
  task: {
    requirement: 'do it',
    status: 'todo',
    priority: 'medium',
    tags: [],
    linkedAgentNodeId: null,
    agentSessions: [],
    lastRunAt: null,
    autoGeneratedTitle: false,
    createdAt: null,
    updatedAt: null,
  },
} as TerminalNodeData

function renderBody() {
  // The body reads the Spaces of the document of its workspace when it renders.
  createStoreBackedChannels({ workspaceId: 'workspace', nodes: [] })
  const taskSpies = {
    runAgent: vi.fn(async () => undefined),
    resumeAgentSession: vi.fn(async () => undefined),
    removeAgentSessionRecord: vi.fn(),
    openEditor: vi.fn(),
    updateTitle: vi.fn(),
    updateRequirement: vi.fn(),
    updateStatus: vi.fn(),
  } satisfies CanvasTaskCommands
  const windowSpies = {
    select: vi.fn(),
    clearSelection: vi.fn(),
    close: vi.fn(async () => undefined),
    requestDelete: vi.fn(),
    resize: vi.fn(),
    focusForInteraction: vi.fn(),
    setLabelColorOverride: vi.fn(),
  }
  render(
    <CanvasStoreTestProvider workspaceId="workspace">
      <NodeCommandsProvider commands={{ ...withTaskCommands(taskSpies), window: windowSpies }}>
        <WorkspaceCanvasTaskNodeType
          id="t-1"
          data={data}
          nodePosition={{ x: 0, y: 0 }}
          workspacePath="/repo"
        />
      </NodeCommandsProvider>
    </CanvasStoreTestProvider>,
  )
  return { taskSpies, windowSpies, props: captured.props as unknown as TaskNodeProps }
}

function expectOnly(
  called: keyof CanvasTaskCommands,
  spies: ReturnType<typeof renderBody>['taskSpies'],
  windowSpies: ReturnType<typeof renderBody>['windowSpies'],
) {
  for (const [name, spy] of Object.entries(spies)) {
    if (name === called) {
      expect(spy, name).toHaveBeenCalledTimes(1)
    } else {
      expect(spy, name).not.toHaveBeenCalled()
    }
  }
  for (const [name, spy] of Object.entries(windowSpies)) {
    expect(spy, `window.${name}`).not.toHaveBeenCalled()
  }
}

describe('the task body hands each TaskNode callback to the command it is named for', () => {
  it('onOpenEditor reaches task.openEditor with the id, and nothing else', () => {
    const { taskSpies, windowSpies, props } = renderBody()

    props.onOpenEditor()

    expect(taskSpies.openEditor).toHaveBeenCalledWith('t-1')
    expectOnly('openEditor', taskSpies, windowSpies)
  })

  it('onQuickTitleSave reaches task.updateTitle with the id and the title, and nothing else', () => {
    const { taskSpies, windowSpies, props } = renderBody()

    props.onQuickTitleSave('new title')

    expect(taskSpies.updateTitle).toHaveBeenCalledWith('t-1', 'new title')
    expectOnly('updateTitle', taskSpies, windowSpies)
  })

  it('onQuickRequirementSave reaches task.updateRequirement with the id and the text, and nothing else', () => {
    const { taskSpies, windowSpies, props } = renderBody()

    props.onQuickRequirementSave('new requirement')

    expect(taskSpies.updateRequirement).toHaveBeenCalledWith('t-1', 'new requirement')
    expectOnly('updateRequirement', taskSpies, windowSpies)
  })

  it('onRunAgent reaches task.runAgent with the id, and does not wait for it', () => {
    const { taskSpies, windowSpies, props } = renderBody()

    const result = props.onRunAgent() as unknown

    expect(taskSpies.runAgent).toHaveBeenCalledWith('t-1')
    expectOnly('runAgent', taskSpies, windowSpies)
    // The callback is fire and forget, as `void runTaskAgentRef.current(id)` was.
    expect(result).toBeUndefined()
  })

  it('onStatusChange reaches task.updateStatus with the id and the status, and nothing else', () => {
    const { taskSpies, windowSpies, props } = renderBody()

    props.onStatusChange('done')

    expect(taskSpies.updateStatus).toHaveBeenCalledWith('t-1', 'done')
    expectOnly('updateStatus', taskSpies, windowSpies)
  })

  it('onResumeAgentSession reaches task.resumeAgentSession with the id and the record, and does not wait for it', () => {
    const { taskSpies, windowSpies, props } = renderBody()

    const result = props.onResumeAgentSession('record-1') as unknown

    expect(taskSpies.resumeAgentSession).toHaveBeenCalledWith('t-1', 'record-1')
    expectOnly('resumeAgentSession', taskSpies, windowSpies)
    expect(result).toBeUndefined()
  })

  it('onRemoveAgentSessionRecord reaches task.removeAgentSessionRecord with the id and the record, and nothing else', () => {
    const { taskSpies, windowSpies, props } = renderBody()

    props.onRemoveAgentSessionRecord('record-1')

    expect(taskSpies.removeAgentSessionRecord).toHaveBeenCalledWith('t-1', 'record-1')
    expectOnly('removeAgentSessionRecord', taskSpies, windowSpies)
  })

  it('onClose asks to delete the task window, and onResize resizes it', () => {
    const { windowSpies, taskSpies, props } = renderBody()
    const frame = { position: { x: 1, y: 2 }, size: { width: 500, height: 400 } }

    props.onClose()
    props.onResize(frame)

    expect(windowSpies.requestDelete).toHaveBeenCalledWith(['t-1'])
    expect(windowSpies.close).not.toHaveBeenCalled()
    expect(windowSpies.resize).toHaveBeenCalledWith('t-1', frame)
    for (const spy of Object.values(taskSpies)) {
      expect(spy).not.toHaveBeenCalled()
    }
  })

  it.each([
    ['a plain click', undefined, ['select', ['t-1']], ['focusForInteraction', ['t-1']]],
    ['a shift click', { shiftKey: true }, ['select', ['t-1', { toggle: true }]], null],
    ['a press that does not select', { selectNode: false }, null, ['focusForInteraction', ['t-1']]],
    [
      'a press that does not move the viewport',
      { normalizeViewport: false },
      ['select', ['t-1']],
      null,
    ],
  ] as const)(
    'onInteractionStart on %s selects and focuses as the window commands say',
    (_name, options, select, focus) => {
      const { windowSpies, props } = renderBody()

      props.onInteractionStart!(options as never)

      if (select) {
        expect(windowSpies.select).toHaveBeenCalledTimes(1)
        expect(windowSpies.select).toHaveBeenCalledWith(...select[1])
      } else {
        expect(windowSpies.select).not.toHaveBeenCalled()
      }
      if (focus) {
        expect(windowSpies.focusForInteraction).toHaveBeenCalledWith(...focus[1])
      } else {
        expect(windowSpies.focusForInteraction).not.toHaveBeenCalled()
      }
    },
  )

  it('renders nothing for a window that has no task data', () => {
    captured.props = null
    createStoreBackedChannels({ workspaceId: 'workspace', nodes: [] })
    render(
      <CanvasStoreTestProvider workspaceId="workspace">
        <NodeCommandsProvider commands={noopNodeCommands}>
          <WorkspaceCanvasTaskNodeType
            id="t-1"
            data={{ ...data, task: null } as TerminalNodeData}
            nodePosition={{ x: 0, y: 0 }}
            workspacePath="/repo"
          />
        </NodeCommandsProvider>
      </CanvasStoreTestProvider>,
    )

    expect(captured.props).toBeNull()
  })
})
