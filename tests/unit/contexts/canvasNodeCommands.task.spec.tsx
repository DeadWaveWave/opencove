// S7 of #647, PR 7: the task family, called through the real canvas on the faithful React Flow mock
// (the harness is `tests/support/canvasNodeCommandsHarness.tsx`). What this spec pins:
//   - `task.runAgent` and `task.resumeAgentSession` read the app's settings and the terminal
//     display calibration when an action starts, once, and a settings change keeps the command
//     object and the whole params value (Decision 2);
//   - an action that started in A and finishes after the switch to B writes A: the task, the agent
//     it created and its error (Decision 4);
//   - a task window that is closed while its action waits for the launch is not written;
//   - each command does what the function it is named for does.
// The closed-node rows for the seven commands are in `canvasNodeCommands.closedNode.spec.tsx`.

installCanvasHarnessHooks()

function record(id: string): TaskAgentSessionRecord {
  return {
    id,
    provider: 'codex',
    resumeSessionId: `${id}-resume`,
    resumeSessionIdVerified: true,
    prompt: 'resume me',
    model: 'gpt-5.2-codex',
    effectiveModel: 'gpt-5.2-codex',
    boundDirectory: '/tmp/bound',
    lastDirectory: '/tmp/bound',
    createdAt: '2026-03-15T00:00:00.000Z',
    lastRunAt: '2026-03-15T00:00:00.000Z',
    endedAt: null,
    exitCode: null,
    status: 'standby',
  }
}

function taskWindow(
  id: string,
  x: number,
  {
    title = id,
    requirement = 'do the thing',
    agentSessions = [],
  }: { title?: string; requirement?: string; agentSessions?: TaskAgentSessionRecord[] } = {},
): Node<TerminalNodeData> {
  return {
    ...pixelNode({
      kind: 'task',
      sessionId: '',
      title,
      task: {
        requirement,
        status: 'todo',
        priority: 'medium',
        tags: [],
        linkedAgentNodeId: null,
        agentSessions,
        lastRunAt: null,
        autoGeneratedTitle: false,
        isEnriching: false,
        createdAt: null,
        updatedAt: null,
      },
    }),
    id,
    position: { x, y: 0 },
    initialWidth: 460,
    initialHeight: 280,
  }
}

const nodeOf = (workspaceId: string, nodeId: string) =>
  readWorkspaceDocument(workspaceId)?.nodes.find(node => node.id === nodeId)
const taskOf = (workspaceId: string, nodeId = 't') => nodeOf(workspaceId, nodeId)?.data.task
const agentsOf = (workspaceId: string) =>
  readWorkspaceDocument(workspaceId)?.nodes.filter(node => node.data.kind === 'agent') ?? []

const stubLaunch = (options: { hold?: boolean; fail?: boolean } = {}) =>
  stubAgentLaunch({ ...options, sessionId: 'runtime-task' })

const settingsWith = (patch: Partial<AgentSettings>) =>
  act(() => {
    useAppStore.setState(state => ({ agentSettings: { ...state.agentSettings, ...patch } }))
  })

// `t` in A has the title 'in A' and the record `rec`, and the same id in B has other fields, so a
// write that reached B shows.
const documentNodesOfA = () => [
  ...documentOfA(),
  taskWindow('t', 2400, { title: 'in A', requirement: 'req A', agentSessions: [record('rec')] }),
]

/**
 * A run links the task to the agent it launched, and a second run of that task reuses the agent
 * instead of launching, so a case that launches twice starts the task over between its calls.
 */
const resetTask = () => act(() => void setDocumentNodes(A, documentNodesOfA()))

beforeEach(() => {
  ipc.invoke.mockReset()
  useAppStore.setState({ agentSettings: { ...DEFAULT_AGENT_SETTINGS } })
  setDocumentNodes(A, documentNodesOfA())
  setDocumentNodes(B, [
    taskWindow('t', 0, { title: 'in B', requirement: 'req B', agentSessions: [record('rec')] }),
  ])
})

type Call = (commands: ReturnType<typeof commandsOf>) => Promise<void>
const run: Call = commands => commands.task.runAgent('t')
const resume: Call = commands => commands.task.resumeAgentSession('t', 'rec')
const ACTIONS: Array<[string, Call]> = [
  ['runAgent', run],
  ['resumeAgentSession', resume],
]

describe('the task launch reads the settings when the action starts', () => {
  const rows: Array<
    [string, Partial<AgentSettings>, (payload: Record<string, unknown>) => unknown, unknown]
  > = [
    ['agentFullAccess', { agentFullAccess: true }, payload => payload.agentFullAccess, true],
    [
      'codexReuseRunningAppServer',
      { codexReuseRunningAppServer: true },
      payload => payload.codexReuseRunningAppServer,
      true,
    ],
    [
      'agentEnvByProvider',
      {
        agentEnvByProvider: {
          ...DEFAULT_AGENT_SETTINGS.agentEnvByProvider,
          codex: [{ id: 'row', key: 'FROM_SETTINGS', value: 'yes', enabled: true }],
        },
      },
      payload => payload.env,
      { FROM_SETTINGS: 'yes' },
    ],
    [
      'agentExecutablePathOverrideByProvider',
      {
        agentExecutablePathOverrideByProvider: {
          ...DEFAULT_AGENT_SETTINGS.agentExecutablePathOverrideByProvider,
          codex: '/opt/codex',
        },
      },
      payload => payload.executablePathOverride,
      '/opt/codex',
    ],
  ]
  const cases = ACTIONS.flatMap(([action, call]) =>
    rows.map(
      ([name, patch, read, expected]) => [action, call, name, patch, read, expected] as const,
    ),
  )

  it.each(cases)(
    '%s launches with the %s of the settings at the call, on the command made before they changed',
    async (_action, call, _name, patch, read, expected) => {
      const launch = stubLaunch()
      await mount()
      const before = latest()
      const commands = commandsOf()

      await settingsWith(patch)
      // The change keeps the command object and the whole params value (guard).
      expect(latest().params).toBe(before.params)
      expect(commandsOf()).toBe(commands)
      expect(commandsOf().task).toBe(commands.task)

      await act(async () => call(commands))

      expect(launch.payloads()).toHaveLength(1)
      expect(read(launch.payloads()[0]!)).toEqual(expected)
    },
  )

  it('runAgent launches with the default provider of the settings at the call', async () => {
    const launch = stubLaunch()
    await mount()
    const commands = commandsOf()

    await settingsWith({ defaultProvider: 'opencode' })
    expect(commandsOf()).toBe(commands)
    await act(async () => commands.task.runAgent('t'))

    expect(launch.payloads()[0]!.provider).toBe('opencode')
  })

  it.each(ACTIONS)(
    '%s launches with the font size of the settings at the call: another size, another geometry',
    async (_action, call) => {
      const launch = stubLaunch()
      useAppStore.setState(state => ({
        agentSettings: { ...state.agentSettings, terminalFontSize: 13 },
      }))
      await mount()
      const commands = commandsOf()
      await act(async () => call(commands))
      resetTask()

      await settingsWith({ terminalFontSize: 28 })
      expect(commandsOf()).toBe(commands)
      await act(async () => call(commands))

      const [first, second] = launch.payloads().map(payload => payload.cols as number)
      expect(second).toBeLessThan(first!)
    },
  )

  // The calibration changes while a workspace is open (a display change, a font load). The command
  // object does not change with it (the identity spec pins that); the launch uses the one of the call.
  it.each(ACTIONS)(
    '%s launches with the display calibration at the call: another cell, another geometry',
    async (_action, call) => {
      const launch = stubLaunch()
      await mount()
      const commands = commandsOf()
      await act(async () => call(commands))
      resetTask()

      await observe(() => controls.setCalibration(terminalCalibration(24)))
      expect(commandsOf()).toBe(commands)
      await act(async () => call(commands))

      const [first, second] = launch.payloads().map(payload => payload.cols as number)
      expect(second).toBeLessThan(first!)
    },
  )

  it.each(ACTIONS)(
    '%s sizes the agent window it creates from the window size of the settings at the call',
    async (_action, call) => {
      stubLaunch()
      await mount()
      const commands = commandsOf()
      await act(async () => call(commands))
      const widthOfFirst = agentsOf(A)[0]!.data.width
      resetTask()

      await settingsWith({ standardWindowSizeBucket: 'large' })
      expect(commandsOf()).toBe(commands)
      await act(async () => call(commands))

      const widthOfSecond = agentsOf(A)[0]!.data.width
      expect(widthOfSecond).toBeGreaterThan(widthOfFirst)
    },
  )
})

describe('a task action reads the settings once, when it starts', () => {
  it.each(ACTIONS)(
    '%s sizes the agent window from the bucket its launch geometry used, not one changed during the launch',
    async (_action, call) => {
      const launch = stubLaunch({ hold: true })
      await mount()
      let running!: Promise<void>
      act(() => {
        running = call(commandsOf())
      })
      await vi.waitFor(() => expect(launch.payloads()).toHaveLength(1))
      await settingsWith({ standardWindowSizeBucket: 'large' })

      await act(async () => {
        launch.release()
        await running
      })

      const regular = resolveDefaultAgentWindowSize('regular', 'codex')
      expect(agentsOf(A)).toHaveLength(1)
      expect({ width: agentsOf(A)[0]!.data.width, height: agentsOf(A)[0]!.data.height }).toEqual(
        regular,
      )
    },
  )
})

describe('a task action that is waiting for the launch when the user switches workspace', () => {
  it.each(ACTIONS)(
    '%s links the agent it created to the task of A, and writes nothing in B',
    async (_action, call) => {
      const launch = stubLaunch({ hold: true })
      await mount()
      const commandsOfA = commandsOf()
      let running!: Promise<void>
      act(() => {
        running = call(commandsOfA)
      })
      await vi.waitFor(() => expect(launch.payloads()).toHaveLength(1))
      await observe(() => controls.showWorkspace(B))
      const documentOfBBefore = readWorkspaceDocument(B)!

      await act(async () => {
        launch.release()
        await running
      })

      const agents = agentsOf(A)
      expect(agents).toHaveLength(1)
      expect(agents[0]!.data.sessionId).toBe('runtime-task')
      expect(agents[0]!.data.agent?.taskId).toBe('t')
      expect(taskOf(A)).toMatchObject({ status: 'doing', linkedAgentNodeId: agents[0]!.id })
      expect(taskOf(A)!.lastRunAt).toEqual(expect.any(String))
      expect(nodeOf(A, 't')!.data.lastError).toBeNull()
      // B: the same object, and its own `t` as it was.
      expect(readWorkspaceDocument(B)!.nodes).toBe(documentOfBBefore.nodes)
      expect(taskOf(B)).toMatchObject({ status: 'todo', linkedAgentNodeId: null })
      expect(agentsOf(B)).toEqual([])
    },
  )

  it.each(ACTIONS)(
    '%s writes the error of a refused launch to the task of A, shows it, and writes nothing in B',
    async (_action, call) => {
      const launch = stubLaunch({ hold: true, fail: true })
      onShowMessage.mockClear()
      await mount()
      const commandsOfA = commandsOf()
      let running!: Promise<void>
      act(() => {
        running = call(commandsOfA)
      })
      await vi.waitFor(() => expect(launch.payloads()).toHaveLength(1))
      await observe(() => controls.showWorkspace(B))
      const documentOfBBefore = readWorkspaceDocument(B)!

      await act(async () => {
        launch.release()
        await running
      })

      expect(nodeOf(A, 't')!.data.lastError).toEqual(expect.stringContaining('launch refused'))
      expect(taskOf(A)).toMatchObject({ status: 'todo', linkedAgentNodeId: null })
      expect(agentsOf(A)).toEqual([])
      expect(readWorkspaceDocument(B)!.nodes).toBe(documentOfBBefore.nodes)
      expect(nodeOf(B, 't')!.data.lastError).toBeNull()
    },
  )
})

describe('a task window that is closed while its action waits for the launch', () => {
  // The launch that completes still creates its agent window (as before): one write, flushed by
  // the creator. Nothing else is written, notified or flushed for the window that is gone.
  const cases = ACTIONS.flatMap(([action, call]) => [
    [action, call, 'succeeds', false, 1, 1] as const,
    [action, call, 'is refused', true, 0, 0] as const,
  ])
  it.each(cases)(
    '%s writes nothing about the window when the launch %s',
    async (_action, call, _name, fail, writes, flushCount) => {
      const launch = stubLaunch({ hold: true, fail })
      await mount()
      let running!: Promise<void>
      act(() => {
        running = call(commandsOf())
      })
      await vi.waitFor(() => expect(launch.payloads()).toHaveLength(1))
      act(() => {
        commitCanvasDocument(A, document => ({
          ...document,
          nodes: document.nodes.filter(node => node.id !== 't'),
        }))
      })
      const notifications = vi.fn()
      const flushes = vi.fn()
      const unsubscribe = useAppStore.subscribe(notifications)
      const unregister = registerWorkspaceDocumentPersistFlush(flushes)

      await act(async () => {
        launch.release()
        await running
      })
      unsubscribe()
      unregister()

      expect(notifications).toHaveBeenCalledTimes(writes)
      expect(flushes).toHaveBeenCalledTimes(flushCount)
      expect(nodeOf(A, 't')).toBeUndefined()
      expect(agentsOf(A)).toHaveLength(fail ? 0 : 1)
    },
  )
})

describe('a task command of workspace A that runs after the switch to B writes A (Decision 4)', () => {
  it('updateStatus, updateTitle, updateRequirement and removeAgentSessionRecord write the task of the workspace that made them', async () => {
    await mount()
    const commandsOfA = commandsOf()
    await observe(() => controls.showWorkspace(B))

    act(() => {
      commandsOfA.task.updateStatus('t', 'done')
      commandsOfA.task.updateTitle('t', ' late title ')
      commandsOfA.task.updateRequirement('t', ' late requirement ')
      commandsOfA.task.removeAgentSessionRecord('t', 'rec')
    })

    expect(nodeOf(A, 't')!.data.title).toBe('late title')
    expect(taskOf(A)).toMatchObject({
      status: 'done',
      requirement: 'late requirement',
      agentSessions: [],
    })
    expect(nodeOf(B, 't')!.data.title).toBe('in B')
    expect(taskOf(B)).toMatchObject({ status: 'todo', requirement: 'req B' })
    expect(taskOf(B)!.agentSessions).toHaveLength(1)
  })

  it('openEditor reads the task of the workspace that made it', async () => {
    await mount()
    const commandsOfA = commandsOf()
    // The dialog belongs to the canvas store of the render that made the command.
    const readUiOfA = latest().readUi
    await observe(() => controls.showWorkspace(B))

    act(() => commandsOfA.task.openEditor('t'))

    expect(readUiOfA().taskEditor).toMatchObject({ nodeId: 't', title: 'in A' })
  })

  it('a command of B writes B after the switch, not A', async () => {
    await mount()
    await observe(() => controls.showWorkspace(B))

    act(() => commandsOf().task.updateStatus('t', 'done'))

    expect(taskOf(B)!.status).toBe('done')
    expect(taskOf(A)!.status).toBe('todo')
  })
})

describe('each task command has the effect of the function it is named for', () => {
  it('updateStatus sets the status of the task window, and flushes once per change', async () => {
    const flushes = vi.fn()
    const unregister = registerWorkspaceDocumentPersistFlush(flushes)
    await mount()
    flushes.mockClear()

    act(() => commandsOf().task.updateStatus('t', 'doing'))
    unregister()

    expect(taskOf(A)!.status).toBe('doing')
    expect(flushes).toHaveBeenCalledTimes(1)
  })

  it('updateTitle trims the title, clears the error and the generated flag, and flushes once', async () => {
    const flushes = vi.fn()
    const unregister = registerWorkspaceDocumentPersistFlush(flushes)
    setDocumentNodes(A, [
      ...documentOfA(),
      {
        ...taskWindow('t', 2400),
        data: { ...taskWindow('t', 2400).data, lastError: 'old error' },
      },
    ])
    await mount()
    flushes.mockClear()

    act(() => commandsOf().task.updateTitle('t', '  new title  '))
    unregister()

    expect(nodeOf(A, 't')!.data.title).toBe('new title')
    expect(nodeOf(A, 't')!.data.lastError).toBeNull()
    expect(taskOf(A)!.autoGeneratedTitle).toBe(false)
    expect(flushes).toHaveBeenCalledTimes(1)
  })

  it('updateRequirement trims the text and flushes once, and an empty text changes nothing', async () => {
    const flushes = vi.fn()
    const unregister = registerWorkspaceDocumentPersistFlush(flushes)
    await mount()
    flushes.mockClear()

    act(() => commandsOf().task.updateRequirement('t', '   '))
    expect(flushes).not.toHaveBeenCalled()
    expect(taskOf(A)!.requirement).toBe('req A')
    act(() => commandsOf().task.updateRequirement('t', '  fresh  '))
    unregister()

    expect(taskOf(A)!.requirement).toBe('fresh')
    expect(flushes).toHaveBeenCalledTimes(1)
  })

  it('removeAgentSessionRecord drops that record only, and flushes once', async () => {
    const flushes = vi.fn()
    const unregister = registerWorkspaceDocumentPersistFlush(flushes)
    setDocumentNodes(A, [
      ...documentOfA(),
      taskWindow('t', 2400, { agentSessions: [record('rec'), record('keep')] }),
    ])
    await mount()
    flushes.mockClear()

    act(() => commandsOf().task.removeAgentSessionRecord('t', 'rec'))
    unregister()

    expect(taskOf(A)!.agentSessions?.map(item => item.id)).toEqual(['keep'])
    expect(flushes).toHaveBeenCalledTimes(1)
  })

  it('openEditor opens the editor dialog with the task of the window', async () => {
    await mount()

    act(() => commandsOf().task.openEditor('t'))

    expect(latest().readUi().taskEditor).toMatchObject({
      nodeId: 't',
      title: 'in A',
      requirement: 'req A',
    })
  })

  it('runAgent of a task without a requirement writes the error and launches nothing', async () => {
    const launch = stubLaunch()
    setDocumentNodes(A, [...documentOfA(), taskWindow('t', 2400, { requirement: '   ' })])
    await mount()

    await act(async () => commandsOf().task.runAgent('t'))

    expect(launch.payloads()).toEqual([])
    expect(nodeOf(A, 't')!.data.lastError).toEqual(expect.any(String))
    expect(nodeOf(A, 't')!.data.lastError).not.toBe('')
    expect(agentsOf(A)).toEqual([])
  })

  it('resumeAgentSession of a record the task does not hold launches nothing', async () => {
    const launch = stubLaunch()
    await mount()

    await act(async () => commandsOf().task.resumeAgentSession('t', 'missing'))

    expect(launch.payloads()).toEqual([])
    expect(agentsOf(A)).toEqual([])
  })
})
