import { act } from '@testing-library/react'
import { describe, expect, it, vi } from 'vitest'
import type { Node } from '@xyflow/react'
import { useWorkspaceCanvasSpaceDirectoryOps } from '../../../src/contexts/workspace/presentation/renderer/components/workspaceCanvas/hooks/useSpaceDirectoryOps'
import type {
  TerminalNodeData,
  WorkspaceSpaceState,
} from '../../../src/contexts/workspace/presentation/renderer/types'
import {
  createCanvasDocumentHarness,
  renderCanvasNodeStore,
} from '../../support/canvasDocumentHarness'

function createNoteNode(id: string, title: string): Node<TerminalNodeData> {
  return {
    id,
    type: 'noteNode',
    position: { x: 0, y: 0 },
    data: {
      sessionId: '',
      title,
      width: 320,
      height: 220,
      kind: 'note',
      status: null,
      startedAt: null,
      endedAt: null,
      exitCode: null,
      lastError: null,
      scrollback: null,
      agent: null,
      task: null,
      note: { text: `${title} body` },
    },
    draggable: true,
    selectable: true,
  }
}

function createTaskNode(id: string, title: string): Node<TerminalNodeData> {
  return {
    id,
    type: 'taskNode',
    position: { x: 40, y: 40 },
    data: {
      sessionId: '',
      title,
      width: 360,
      height: 240,
      kind: 'task',
      status: null,
      startedAt: null,
      endedAt: null,
      exitCode: null,
      lastError: null,
      scrollback: null,
      executionDirectory: null,
      expectedDirectory: null,
      agent: null,
      task: {
        requirement: 'Do the thing',
        status: 'todo',
        priority: 'medium',
        tags: [],
        linkedAgentNodeId: null,
        agentSessions: [],
        lastRunAt: null,
        autoGeneratedTitle: false,
        createdAt: null,
        updatedAt: null,
      },
      note: null,
    },
    draggable: true,
    selectable: true,
  }
}

describe('useWorkspaceCanvasSpaceDirectoryOps archiveSpace', () => {
  it('removes the archived space and all nodes inside it', () => {
    const closeNode = vi.fn(async () => undefined)

    const initialNodes: Node<TerminalNodeData>[] = [
      createTaskNode('task-1', 'Task 1'),
      createNoteNode('note-1', 'Note 1'),
      createNoteNode('outside-note', 'Outside Note'),
    ]

    const initialSpaces: WorkspaceSpaceState[] = [
      {
        id: 'space-1',
        name: 'Space 1',
        directoryPath: '/repo/.opencove/worktrees/space-1',
        targetMountId: null,
        labelColor: null,
        nodeIds: ['task-1', 'note-1'],
        rect: null,
      },
    ]

    const harness = createCanvasDocumentHarness({ nodes: initialNodes, spaces: initialSpaces })
    const view = renderCanvasNodeStore(harness, {
      workspacePath: '/repo',
      extend: function useDirectoryOpsUnderTest() {
        return useWorkspaceCanvasSpaceDirectoryOps({
          workspacePath: '/repo',
          closeNode,
        })
      },
    })

    act(() => {
      view.result.current.updateSpaceDirectory('space-1', '/repo', { archiveSpace: true })
    })

    const document = harness.readStoreDocument()
    expect(document.spaces).toHaveLength(0)
    expect(document.nodes).toHaveLength(1)
    expect(document.nodes.map(node => node.data.title).join(', ')).toBe('Outside Note')
    expect(closeNode).not.toHaveBeenCalled()
    expect(harness.flush).toHaveBeenCalledTimes(1)
  })
})
