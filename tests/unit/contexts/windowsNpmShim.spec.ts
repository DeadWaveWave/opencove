// @vitest-environment node
import { readFileSync } from 'node:fs'
import { expect, it } from 'vitest'
import { npmNodeCmdPattern, npmNodePs1Pattern } from '../../../src/platform/terminal/windowsNpmShim'
const source = readFileSync('tests/fixtures/windows-argv/npm-node.cmd', 'utf8').replaceAll(
  '\r\n',
  '\n',
)
// JS equivalent of the .NET absolute-start/end anchors, no multiline matching.
const pattern = new RegExp(npmNodeCmdPattern.replace('\\A', '^').replace('\\z', '(?![\\s\\S])'))
it('recognizes the whole cmd-shim 8.0.0 Node template generated by the actual package', () => {
  expect(pattern.exec(source)?.groups?.target).toBe('node_modules\\provider\\cli.js')
})
it.each([
  text => `echo dangerous\n${text}`,
  text => `${text}echo dangerous\n`,
  text => text.replace('  SET "_prog=node"', '  SET "_prog=other"'),
  text => text.replace('"%_prog%"  ', '"%_prog%" --flag '),
  text => text.replace('SETLOCAL', 'SETLOCAL\nSET NODE_PATH=other'),
])('refuses an unverified script without executing it', mutate => {
  expect(pattern.test(mutate(source))).toBe(false)
})

it('verifies all four npm PowerShell forwarding branches against the same target', () => {
  const psSource = readFileSync('tests/fixtures/windows-argv/npm-node.ps1', 'utf8').replaceAll(
    '\r\n',
    '\n',
  )
  const psPattern = new RegExp(npmNodePs1Pattern.replace('\\A', '^').replace('\\z', '(?![\\s\\S])'))
  expect(psPattern.exec(psSource)?.groups?.target).toBe('node_modules/provider/cli.js')
  expect(
    psPattern.test(
      psSource.replace('"$basedir/node_modules/provider/cli.js"', '"$basedir/other.js"'),
    ),
  ).toBe(false)
  expect(psPattern.test(psSource + 'Write-Output unsafe\n')).toBe(false)
})
