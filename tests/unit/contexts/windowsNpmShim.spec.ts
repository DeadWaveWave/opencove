// @vitest-environment node
import { readFileSync } from 'node:fs'
import { expect, it } from 'vitest'
import { npmCmdPattern, npmPs1Pattern } from '../../../src/platform/terminal/windowsNpmShim'
const source = readFileSync('tests/fixtures/windows-argv/npm-node.cmd', 'utf8').replaceAll(
  '\r\n',
  '\n',
)
// JS equivalent of the .NET absolute-start/end anchors, no multiline matching.
const pattern = new RegExp(npmCmdPattern.replace('\\A', '^').replace('\\z', '(?![\\s\\S])'))
it('recognizes the whole cmd-shim 8.0.0 Node template generated by the actual package', () => {
  expect(pattern.exec(source)?.groups?.target).toBe('node_modules\\provider\\cli.js')
})
it.each([
  text => `echo dangerous\n${text}`,
  text => `${text}echo dangerous\n`,
  text => text.replace('  SET "_prog=node"', '  SET "_prog=other"'),
  text => text.replace('"%_prog%"  ', '"%_prog%" --flag '),
  text => text.replace('SETLOCAL', 'SETLOCAL\nSET NODE_PATH=other'),
])('refuses an unverified script without executing it', mutate => {
  expect(pattern.test(mutate(source))).toBe(false)
})

it('verifies all four npm PowerShell forwarding branches against the same target', () => {
  const psSource = readFileSync('tests/fixtures/windows-argv/npm-node.ps1', 'utf8').replaceAll(
    '\r\n',
    '\n',
  )
  const psPattern = new RegExp(npmPs1Pattern.replace('\\A', '^').replace('\\z', '(?![\\s\\S])'))
  expect(psPattern.exec(psSource)?.groups?.target).toBe('node_modules/provider/cli.js')
  expect(
    psPattern.test(
      psSource.replace('"$basedir/node_modules/provider/cli.js"', '"$basedir/other.js"'),
    ),
  ).toBe(false)
  expect(psPattern.test(psSource + 'Write-Output unsafe\n')).toBe(false)
})

it.each([
  ['cmd', npmCmdPattern, 'node_modules\\@anthropic-ai\\claude-code\\bin\\claude.exe'],
  ['ps1', npmPs1Pattern, 'node_modules/@anthropic-ai/claude-code/bin/claude.exe'],
])(
  'recognizes a standard direct native npm %s without treating it as a Node entrypoint',
  (ext, sourcePattern, target) => {
    const fixture = readFileSync(
      `tests/fixtures/windows-argv/npm-native.${ext}`,
      'utf8',
    ).replaceAll('\r\n', '\n')
    const nativePattern = new RegExp(
      sourcePattern.replace('\\A', '^').replace('\\z', '(?![\\s\\S])'),
    )
    const match = nativePattern.exec(fixture)
    expect(match?.groups?.nativeTarget).toBe(target)
    expect(match?.groups?.target).toBeUndefined()
    expect(nativePattern.test(fixture + '\n')).toBe(false)
    if (ext === 'ps1') {
      expect(nativePattern.test(fixture.replace('claude.exe', 'other.exe'))).toBe(false)
    }
    expect(nativePattern.test(fixture.replaceAll('claude.exe', 'script.cmd'))).toBe(false)
    expect(nativePattern.test(fixture.replaceAll('claude.exe', '%EXPAND%.exe'))).toBe(false)
    expect(nativePattern.test(fixture.replaceAll('claude.exe', '$EXPAND.exe'))).toBe(false)
    expect(nativePattern.test(fixture.replaceAll(target, 'C:/unrelated.exe'))).toBe(false)
  },
)
