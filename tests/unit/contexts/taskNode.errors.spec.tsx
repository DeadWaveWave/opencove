it('shows a refused Pi config run in the actual canvas task card while preserving the live session', async () => {
  const launchAgentInNode = vi.fn()
  const onSpacesChange = vi.fn()
  const kill = vi.fn()
  vi.stubGlobal('opencoveApi', { pty: { kill } })
  const observed = { current: [] as Node<TerminalNodeData>[] }
  function Harness() {
    const nodesRef = useRef(initialNodes())
    const [nodes, setNodes] = useState(nodesRef.current)
    flow.nodes = nodes
    observed.current = nodes
    const spacesRef = useRef([])
    const context = {
      nodesRef,
      spacesRef,
      workspaceId: 'workspace',
      workspacePath: '/repo',
      agentSettings: { ...DEFAULT_AGENT_SETTINGS, defaultProvider: 'codex' },
      launchAgentInNode,
      onSpacesChange,
      t: (key: string) => key,
      setNodes: (update: (previous: Node<TerminalNodeData>[]) => Node<TerminalNodeData>[]) => {
        nodesRef.current = update(nodesRef.current)
        setNodes(nodesRef.current)
      },
    } as TaskActionContext
    return (
      <WorkspaceCanvasTaskNodeType
        id="task"
        data={nodes[0].data}
        nodePosition={nodes[0].position}
        spacesRef={spacesRef}
        workspacePath="/repo"
        selectNode={() => {}}
        resizeNodeRef={{ current: () => {} }}
        normalizeViewportForTerminalInteractionRef={{ current: () => {} }}
        requestNodeDeleteRef={{ current: () => {} }}
        openTaskEditorRef={{ current: () => {} }}
        quickUpdateTaskTitleRef={{ current: () => {} }}
        quickUpdateTaskRequirementRef={{ current: () => {} }}
        runTaskAgentRef={{ current: async () => runTaskAgentAction('task', context) }}
        resumeTaskAgentSessionRef={{ current: async () => {} }}
        removeTaskAgentSessionRecordRef={{ current: () => {} }}
        updateTaskStatusRef={{ current: () => {} }}
      />
    )
  }
  render(<Harness />)
  expect(screen.queryByRole('alert')).toBeNull()
  await act(async () => {
    fireEvent.click(screen.getByTestId('task-node-run-agent'))
  })
  expect(observed.current[0].data.lastError).toContain('Rephrase the task')
  expect(screen.getByRole('alert')).toBeVisible()
  expect(screen.getByRole('alert')).toHaveTextContent('Rephrase the task')
  expect(screen.getByTestId('task-node-inline-requirement-input')).toHaveValue('config')
  expect(screen.getByTestId('task-node-inline-requirement-input')).not.toBeDisabled()
  expect(screen.getByTestId('task-node-status-select')).toHaveValue('todo')
  expect(screen.getByTestId('task-node-agent-sessions')).toHaveTextContent('1 session · 1 running')
  expect(observed.current[1].data).toMatchObject({
    status: 'running',
    sessionId: 'original-session',
  })
  expect(launchAgentInNode).not.toHaveBeenCalled()
  expect(onSpacesChange).not.toHaveBeenCalled()
  expect(kill).not.toHaveBeenCalled()
})
