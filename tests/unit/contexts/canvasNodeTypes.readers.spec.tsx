import React, { useState } from 'react'
import { act, cleanup, render } from '@testing-library/react'
import { ReactFlowProvider } from '@xyflow/react'
import { afterEach, beforeEach, expect, it, vi } from 'vitest'
import { useAppStore } from '../../../src/app/renderer/shell/store/useAppStore'
import { DEFAULT_AGENT_SETTINGS } from '../../../src/contexts/settings/domain/agentSettings'
import { useWorkspaceCanvasActionRefs } from '../../../src/contexts/workspace/presentation/renderer/components/workspaceCanvas/hooks/useActionRefs'
import { useWorkspaceCanvasNodeTypes } from '../../../src/contexts/workspace/presentation/renderer/components/workspaceCanvas/nodeTypes'
import { WorkspaceCanvasNodeTypesProvider } from '../../../src/contexts/workspace/presentation/renderer/components/workspaceCanvas/nodeTypes.context'
import type { WorkspaceSpaceState } from '../../../src/contexts/workspace/presentation/renderer/types'
import { CanvasStoreTestProvider } from '../../support/canvasStoreTestHarness'
import { createCanvasDocumentHarness } from '../../support/canvasDocumentHarness'
import { replaceSpacesInStore } from '../../support/workspaceCanvasStoreHarness'
import { noopNodeCommands } from '../../support/nodeCommandsFixture'
import { pixelNode } from './workspacePixelLayer.fixtures'

// The node types read the Spaces of the document when they render (#702, PR 14): the mount of a
// document or folder window and the directory of a task card. They read through the reader of the
// canvas store provider, so the workspace of the render is the one that is read, and they do not
// subscribe: a store write alone renders nothing.

const probe = vi.hoisted(() => ({
  documentMounts: [] as Array<string | null | undefined>,
  taskDirectories: [] as string[],
}))

vi.mock(
  '@contexts/workspace/presentation/renderer/components/workspaceCanvas/nodePosition',
  () => ({ useNodePosition: () => ({ x: 0, y: 0 }) }),
)
vi.mock(
  '@contexts/workspace/presentation/renderer/components/workspaceCanvas/collapse/WindowCollapsePresentation',
  () => ({
    WindowCollapsePresentation: ({ children }: { children: React.ReactNode }) => <>{children}</>,
  }),
)
vi.mock('@contexts/workspace/presentation/renderer/components/shared/windowCommitProbe', () => ({
  useWindowNodeCommitProbe: () => {},
}))
vi.mock(
  '@contexts/workspace/presentation/renderer/components/workspaceCanvas/nodeTypes.document',
  () => ({
    WorkspaceCanvasDocumentNodeType: ({ mountId }: { mountId?: string | null }) => {
      probe.documentMounts.push(mountId)
      return null
    },
  }),
)
vi.mock('@contexts/workspace/presentation/renderer/components/TaskNode', () => ({
  TaskNode: ({ currentDirectory }: { currentDirectory: string }) => {
    probe.taskDirectories.push(currentDirectory)
    return null
  },
}))

const A = 'workspace-a'
const B = 'workspace-b'

const documentNode = () => ({
  ...pixelNode({
    kind: 'document',
    sessionId: '',
    title: 'doc',
    document: { uri: 'file:///repo/readme.md' },
  }),
  id: 'doc',
  type: 'documentNode',
})
const taskNode = () => ({
  ...pixelNode({
    kind: 'task',
    sessionId: '',
    title: 'task',
    task: {
      requirement: 'r',
      status: 'todo',
      priority: 'medium',
      tags: [],
      linkedAgentNodeId: null,
      agentSessions: [],
      lastRunAt: null,
      autoGeneratedTitle: false,
      createdAt: null,
      updatedAt: null,
    },
  }),
  id: 'task',
  type: 'taskNode',
})

const spaceOf = (id: string, mount: string | null, directoryPath: string): WorkspaceSpaceState => ({
  id,
  name: id,
  directoryPath,
  targetMountId: mount,
  labelColor: null,
  nodeIds: ['doc', 'task'],
  rect: null,
})

let shown = A
let tick: () => void = () => {}
let renders = 0

function Canvas() {
  renders += 1
  const [, setTick] = useState(0)
  tick = () => setTick(value => value + 1)
  const actions = useWorkspaceCanvasActionRefs()
  const composed = useWorkspaceCanvasNodeTypes({
    ...actions,
    workspacePath: '/repo',
    agentProviderOrder: DEFAULT_AGENT_SETTINGS.agentProviderOrder,
    defaultProvider: DEFAULT_AGENT_SETTINGS.defaultProvider,
    browserDefaultMode: DEFAULT_AGENT_SETTINGS.browserDefaultMode,
    browserSearchEngine: DEFAULT_AGENT_SETTINGS.browserSearchEngine,
    commands: noopNodeCommands,
  })
  const Document = composed.nodeTypes.documentNode
  const Task = composed.nodeTypes.taskNode
  const documentItem = documentNode()
  const task = taskNode()
  return (
    <WorkspaceCanvasNodeTypesProvider value={composed.nodeTypesParameters}>
      <Document id={documentItem.id} data={documentItem.data} />
      <Task id={task.id} data={task.data} />
    </WorkspaceCanvasNodeTypesProvider>
  )
}

function renderCanvas() {
  const view = render(
    <CanvasStoreTestProvider workspaceId={shown}>
      <ReactFlowProvider>
        <Canvas />
      </ReactFlowProvider>
    </CanvasStoreTestProvider>,
  )
  return {
    ...view,
    showWorkspace: (id: string) => {
      shown = id
      act(() => {
        useAppStore.setState({ activeWorkspaceId: id })
      })
      view.rerender(
        <CanvasStoreTestProvider workspaceId={shown}>
          <ReactFlowProvider>
            <Canvas />
          </ReactFlowProvider>
        </CanvasStoreTestProvider>,
      )
    },
  }
}

const latest = <T,>(values: T[]): T | undefined => values[values.length - 1]

beforeEach(() => {
  shown = A
  renders = 0
  probe.documentMounts = []
  probe.taskDirectories = []
  createCanvasDocumentHarness({
    workspaceId: A,
    nodes: [documentNode(), taskNode()],
    spaces: [spaceOf('space-a', 'mount-a', '/repo/a')],
  })
  useAppStore.setState(state => ({
    workspaces: [
      ...state.workspaces,
      {
        ...state.workspaces[0],
        id: B,
        nodes: [documentNode(), taskNode()],
        spaces: [spaceOf('space-b', 'mount-b', '/repo/b')],
      },
    ],
  }))
})

afterEach(cleanup)

it('shows the mount and the directory of the Spaces the store holds when it renders', () => {
  renderCanvas()

  expect(latest(probe.documentMounts)).toBe('mount-a')
  expect(latest(probe.taskDirectories)).toBe('/repo/a')
})

it('renders nothing for a Spaces write alone, and shows the written Spaces when it renders again', () => {
  renderCanvas()
  const rendersBefore = {
    document: probe.documentMounts.length,
    task: probe.taskDirectories.length,
  }

  act(() => {
    replaceSpacesInStore(A, [spaceOf('space-a', 'mount-new', '/repo/new')])
  })

  expect(probe.documentMounts).toHaveLength(rendersBefore.document)
  expect(probe.taskDirectories).toHaveLength(rendersBefore.task)
  expect(renders).toBe(1)

  act(() => {
    replaceSpacesInStore(A, [spaceOf('space-a', 'mount-newer', '/repo/newer')])
    tick()
  })

  expect(latest(probe.documentMounts)).toBe('mount-newer')
  expect(latest(probe.taskDirectories)).toBe('/repo/newer')
})

it('reads the workspace of the render that shows B, not the first one', () => {
  const view = renderCanvas()

  view.showWorkspace(B)

  expect(latest(probe.documentMounts)).toBe('mount-b')
  expect(latest(probe.taskDirectories)).toBe('/repo/b')
})

it('reads the workspace of the provider while another one is the active workspace', () => {
  useAppStore.setState({ activeWorkspaceId: B })
  renderCanvas()

  expect(latest(probe.documentMounts)).toBe('mount-a')
  expect(latest(probe.taskDirectories)).toBe('/repo/a')
})
