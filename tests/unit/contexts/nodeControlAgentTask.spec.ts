function createStateStore(initial: NodeControlAppState) {
  let state = initial
  let revision = 1
  const store: NodeControlAppStateStore = {
    readAppState: async () => state,
    readAppStateRevision: async () => revision,
    writeAppState: async next => {
      state = next
      revision += 1
      return { ok: true, level: 'full', bytes: 1, revision }
    },
  }
  return { store, getState: () => state }
}

async function createAgent(
  initial: NodeControlAppState,
  data: Record<string, unknown>,
  options: { launchFails?: boolean } = {},
) {
  const controlSurface = createControlSurface()
  const { store, getState } = createStateStore(initial)
  const launchAgent = vi.fn(async () => {
    if (options.launchFails) {
      throw new Error('launch exploded')
    }
    return {
      sessionId: 'agent-session-1',
      provider: 'codex' as const,
      startedAt: '2026-04-25T00:00:00.000Z',
      executionContext: { workingDirectory: '/repo' },
      profileId: null,
      runtimeKind: 'posix' as const,
      resumeSessionId: null,
      effectiveModel: null,
    }
  })
  controlSurface.register('session.launchAgent', {
    kind: 'command',
    validate: payload => payload,
    handle: launchAgent,
    defaultErrorCode: 'agent.launch_failed',
  })
  registerNodeControlHandlers(controlSurface, {
    topology: {
      listEndpoints: async () => ({ endpoints: [localEndpoint] }),
      listMounts: async () => ({ mounts: [] }),
    } as WorkerTopologyStore,
    getPersistenceStore: async () => store as never,
  })
  const result = await controlSurface.invoke(ctx, {
    kind: 'command',
    id: 'node.create',
    payload: {
      kind: 'agent',
      space: { kind: 'spaceId', spaceId: 'space-1' },
      data: { prompt: '', provider: 'codex', model: null, ...data },
    },
  })
  return { result, launchAgent, getState }
}

function findTask(state: NodeControlAppState, id: string) {
  return state.workspaces[0].nodes.find(node => node.id === id)
}

describe('node.create agent task link (taskNodeId)', () => {
  it('links the agent and the task in one write and sets the task to doing', async () => {
    const initial = createState([taskNode('task-1')])
    const { result, getState } = await createAgent(initial, { taskNodeId: 'task-1' })

    expect(result.ok).toBe(true)
    if (!result.ok) {
      return
    }
    const agentId = result.value.node.id
    const state = getState()
    const agent = state.workspaces[0].nodes.find(node => node.id === agentId)
    const task = findTask(state, 'task-1')
    expect(agent?.agent).toMatchObject({ taskId: 'task-1' })
    expect(task?.task).toMatchObject({ status: 'doing', linkedAgentNodeId: agentId })
  })

  it('leaves the task untouched when taskNodeId is omitted', async () => {
    const { result, getState } = await createAgent(createState([taskNode('task-1')]), {})

    expect(result.ok).toBe(true)
    expect(findTask(getState(), 'task-1')?.task).toMatchObject({
      status: 'todo',
      linkedAgentNodeId: null,
    })
  })

  it('returns node.not_found and does not launch when the task does not exist', async () => {
    const { result, launchAgent } = await createAgent(createState([taskNode('task-1')]), {
      taskNodeId: 'missing',
    })

    expect(result.ok).toBe(false)
    if (!result.ok) {
      expect(result.error.code).toBe('node.not_found')
    }
    expect(launchAgent).not.toHaveBeenCalled()
  })

  it('rejects a node that is not a task before launching', async () => {
    const note = createNode({ id: 'note-1', kind: 'note' })
    const { result, launchAgent } = await createAgent(createState([taskNode('task-1'), note]), {
      taskNodeId: 'note-1',
    })

    expect(result.ok).toBe(false)
    if (!result.ok) {
      expect(result.error.code).toBe('common.invalid_input')
    }
    expect(launchAgent).not.toHaveBeenCalled()
  })

  it('rejects a task outside the target Space before launching', async () => {
    const initial = createState([taskNode('task-1')], [])
    const { result, launchAgent } = await createAgent(initial, { taskNodeId: 'task-1' })

    expect(result.ok).toBe(false)
    if (!result.ok) {
      expect(result.error.code).toBe('common.invalid_input')
    }
    expect(launchAgent).not.toHaveBeenCalled()
  })

  it('rejects a task that already has a live linked agent before launching', async () => {
    const liveAgent = createNode({
      id: 'agent-live',
      kind: 'agent',
      agent: { provider: 'codex', taskId: 'task-1' },
    })
    const initial = createState([taskNode('task-1', 'agent-live'), liveAgent])
    const { result, launchAgent } = await createAgent(initial, { taskNodeId: 'task-1' })

    expect(result.ok).toBe(false)
    if (!result.ok) {
      expect(result.error.code).toBe('common.invalid_input')
    }
    expect(launchAgent).not.toHaveBeenCalled()
  })

  it('treats a stale linkedAgentNodeId whose agent is gone as unlinked', async () => {
    const initial = createState([taskNode('task-1', 'agent-gone')])
    const { result, getState } = await createAgent(initial, { taskNodeId: 'task-1' })

    expect(result.ok).toBe(true)
    if (!result.ok) {
      return
    }
    expect(findTask(getState(), 'task-1')?.task).toMatchObject({
      status: 'doing',
      linkedAgentNodeId: result.value.node.id,
    })
  })

  it('leaves no link and keeps the task status when the launch fails', async () => {
    const initial = createState([taskNode('task-1')])
    const { result, getState } = await createAgent(
      initial,
      { taskNodeId: 'task-1' },
      { launchFails: true },
    )

    expect(result.ok).toBe(false)
    const state = getState()
    expect(state.workspaces[0].nodes.map(node => node.id)).toEqual(['task-1'])
    expect(findTask(state, 'task-1')?.task).toMatchObject({
      status: 'todo',
      linkedAgentNodeId: null,
    })
  })

  it.each([42, '', '   ', null, true])(
    'rejects invalid taskNodeId=%j before launching',
    async value => {
      const { result, launchAgent } = await createAgent(createState([taskNode('task-1')]), {
        taskNodeId: value,
      })

      expect(result.ok).toBe(false)
      if (!result.ok) {
        expect(result.error.code).toBe('common.invalid_input')
      }
      expect(launchAgent).not.toHaveBeenCalled()
    },
  )
})
