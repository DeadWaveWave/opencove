export type PixelGlyphName = keyof typeof PIXEL_GLYPHS

/** The filled runs of a glyph, row by row, as SVG rects (one per horizontal run). */
export function pixelGlyphRuns(
  name: PixelGlyphName,
): Array<{ x: number; y: number; width: number }> {
  const runs: Array<{ x: number; y: number; width: number }> = []
  PIXEL_GLYPHS[name].forEach((row, y) => {
    let x = 0
    while (x < row.length) {
      if (row[x] !== '#') {
        x++
        continue
      }
      let width = 1
      while (row[x + width] === '#') {
        width++
      }
      runs.push({ x, y, width })
      x += width
    }
  })
  return runs
}
