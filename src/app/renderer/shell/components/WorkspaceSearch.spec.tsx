function Harness({
  onSelectNode = vi.fn(),
  onSelectSpace = vi.fn(),
  onPanelWidthChange = vi.fn(),
  handoff = false,
}: {
  onSelectNode?: (id: string) => void
  onSelectSpace?: (id: string) => void
  onPanelWidthChange?: (width: number) => void
  handoff?: boolean
}) {
  const [open, setOpen] = useState(false)
  const [commandOpen, setCommandOpen] = useState(false)
  const commandCloseRef = useRef<HTMLButtonElement | null>(null)
  return (
    <>
      <div className="app-shell">
        <button
          data-testid="app-header-command-center"
          onClick={() => (handoff ? setCommandOpen(true) : setOpen(true))}
        >
          Open
        </button>
        <div className="workspace-canvas" tabIndex={0}>
          <input data-testid="node-input" />
        </div>
      </div>
      <Dialog
        open={commandOpen}
        onDismiss={() => setCommandOpen(false)}
        aria-label="Commands"
        className="command-center"
        initialFocusRef={commandCloseRef}
      >
        <button ref={commandCloseRef} onClick={() => setCommandOpen(false)}>
          Close commands
        </button>
        <button
          onClick={() => {
            setCommandOpen(false)
            setOpen(true)
          }}
        >
          Search project
        </button>
      </Dialog>
      <WorkspaceSearch
        isOpen={open}
        onClose={() => setOpen(false)}
        activeWorkspace={workspace}
        panelWidth={560}
        onPanelWidthChange={onPanelWidthChange}
        onSelectNode={onSelectNode}
        onSelectSpace={onSelectSpace}
        worktreeInfoByPath={null}
        pullRequestsByBranch={null}
      />
    </>
  )
}

function openSearch() {
  const trigger = screen.getByTestId('app-header-command-center')
  trigger.focus()
  fireEvent.click(trigger)
  act(() => vi.runOnlyPendingTimers())
  return trigger
}

describe('WorkspaceSearch surface', () => {
  beforeEach(() => {
    vi.useFakeTimers()
    vi.stubGlobal('innerWidth', 1200)
  })
  afterEach(() => {
    vi.useRealTimers()
    vi.unstubAllGlobals()
  })

  it('keeps desktop search open after selection and restores the trigger on close', () => {
    const onSelectNode = vi.fn()
    render(<Harness onSelectNode={onSelectNode} />)
    const trigger = openSearch()
    const input = screen.getByRole('combobox')
    expect(document.activeElement).toBe(input)
    fireEvent.change(input, { target: { value: 'token' } })
    fireEvent.keyDown(input, { key: 'Enter' })
    expect(onSelectNode).toHaveBeenCalledExactlyOnceWith('task')
    expect(screen.getByTestId('workspace-search').getAttribute('aria-modal')).toBe('false')
    expect(document.activeElement).toBe(input)
    fireEvent.keyDown(input, { key: 'Escape' })
    expect(screen.queryByTestId('workspace-search')).toBeNull()
    expect(document.activeElement).toBe(trigger)
  })

  it('retains independent category toggles and never disables every category', () => {
    render(<Harness />)
    openSearch()
    fireEvent.click(screen.getByTestId('workspace-search-filter-spaces'))
    fireEvent.click(screen.getByTestId('workspace-search-filter-tasks'))
    fireEvent.click(screen.getByTestId('workspace-search-filter-notes'))
    expect(screen.queryByTestId('workspace-search-item-space:space')).toBeNull()
    expect(screen.queryByTestId('workspace-search-item-task:task')).toBeNull()
    expect(screen.getByTestId('workspace-search-item-note:note')).toBeTruthy()
    fireEvent.click(screen.getByTestId('workspace-search-filter-all'))
    expect(screen.getAllByRole('option')).toHaveLength(3)
  })

  it('leaves composing navigation, confirmation, and Escape to the input method', () => {
    const onSelectNode = vi.fn()
    const onSelectSpace = vi.fn()
    render(<Harness onSelectNode={onSelectNode} onSelectSpace={onSelectSpace} />)
    openSearch()
    const input = screen.getByRole('combobox')
    const activeOption = input.getAttribute('aria-activedescendant')
    for (const composing of [{ isComposing: true }, { keyCode: 229 }]) {
      for (const key of ['ArrowDown', 'ArrowUp', 'Enter', 'Escape']) {
        fireEvent.keyDown(input, { key, ...composing })
      }
      expect(input.getAttribute('aria-activedescendant')).toBe(activeOption)
      expect(screen.getByTestId('workspace-search')).toBeTruthy()
    }
    expect(onSelectNode).not.toHaveBeenCalled()
    expect(onSelectSpace).not.toHaveBeenCalled()
  })

  it('keeps node labels independent from their Space and removes redundant Space metadata', () => {
    render(<Harness />)
    openSearch()
    expect(
      screen.getByTestId('workspace-search-item-task:task').getAttribute('data-cove-label-color'),
    ).toBe('blue')
    expect(
      screen.getByTestId('workspace-search-item-note:note').hasAttribute('data-cove-label-color'),
    ).toBe(false)
    const space = screen.getByTestId('workspace-search-item-space:space')
    expect(space.querySelector('.lucide-scan')).not.toBeNull()
    expect(space.textContent).toBe('ui/chrome')
    expect(space.textContent).not.toContain('/repo')
  })

  it('uses mobile modal focus without opening input and closes after locating a result', () => {
    vi.stubGlobal('innerWidth', 390)
    const onSelectNode = vi.fn()
    const onPanelWidthChange = vi.fn()
    render(<Harness onSelectNode={onSelectNode} onPanelWidthChange={onPanelWidthChange} />)
    const trigger = openSearch()
    expect(screen.getByTestId('workspace-search').getAttribute('aria-modal')).toBe('true')
    expect(document.activeElement).toBe(screen.getByTestId('workspace-search-close'))
    expect(screen.queryByTestId('workspace-search-resize-handle')).toBeNull()
    expect(document.querySelector('.app-shell')?.hasAttribute('inert')).toBe(true)
    fireEvent.click(screen.getByTestId('workspace-search-item-task:task'))
    act(() => vi.runOnlyPendingTimers())
    expect(onSelectNode).toHaveBeenCalledExactlyOnceWith('task')
    expect(screen.queryByTestId('workspace-search')).toBeNull()
    expect(document.activeElement).toBe(trigger)
    expect(document.querySelector('.app-shell')?.hasAttribute('inert')).toBe(false)
    expect(onPanelWidthChange).not.toHaveBeenCalled()
  })

  it('keeps mobile focus inside and restores non-input focus after keyboard search', () => {
    vi.stubGlobal('innerWidth', 390)
    render(<Harness />)
    const trigger = openSearch()
    const close = screen.getByTestId('workspace-search-close')
    fireEvent.keyDown(close, { key: 'Tab', shiftKey: true })
    expect(document.activeElement).toBe(screen.getByTestId('workspace-search-filter-notes'))
    const input = screen.getByRole('combobox')
    input.focus()
    fireEvent.change(input, { target: { value: 'token' } })
    fireEvent.keyDown(input, { key: 'Enter' })
    act(() => vi.runOnlyPendingTimers())
    expect(document.activeElement).toBe(trigger)
  })

  it.each([1200, 390])('hands a closing command dialog to search at %s px', width => {
    vi.stubGlobal('innerWidth', width)
    render(<Harness handoff />)
    const trigger = openSearch()
    fireEvent.click(screen.getByRole('button', { name: 'Search project' }))
    act(() => vi.runOnlyPendingTimers())
    expect(document.activeElement).toBe(
      width > 720 ? screen.getByRole('combobox') : screen.getByTestId('workspace-search-close'),
    )
    fireEvent.click(screen.getByTestId('workspace-search-close'))
    act(() => vi.runOnlyPendingTimers())
    expect(document.activeElement).toBe(trigger)
  })

  it('switches responsive containers without saving a new panel width', () => {
    const onPanelWidthChange = vi.fn()
    render(<Harness onPanelWidthChange={onPanelWidthChange} />)
    const trigger = openSearch()
    act(() => {
      vi.stubGlobal('innerWidth', 320)
      window.dispatchEvent(new Event('resize'))
    })
    act(() => vi.runOnlyPendingTimers())
    expect(screen.getByTestId('workspace-search').style.width).toBe('')
    act(() => {
      vi.stubGlobal('innerWidth', 1200)
      window.dispatchEvent(new Event('resize'))
    })
    act(() => vi.runOnlyPendingTimers())
    expect(screen.getByTestId('workspace-search').style.width).toBe('560px')
    expect(document.activeElement).toBe(screen.getByRole('combobox'))
    fireEvent.click(screen.getByTestId('workspace-search-close'))
    expect(document.activeElement).toBe(trigger)
    expect(onPanelWidthChange).not.toHaveBeenCalled()
  })

  it('commits desktop resize once and restores the page interaction styles', () => {
    const onPanelWidthChange = vi.fn()
    render(<Harness onPanelWidthChange={onPanelWidthChange} />)
    openSearch()
    const handle = screen.getByTestId('workspace-search-resize-handle')
    fireEvent(handle, new MouseEvent('pointerdown', { bubbles: true, button: 0, clientX: 600 }))
    fireEvent(window, new MouseEvent('pointermove', { clientX: 520 }))
    expect(screen.getByTestId('workspace-search').style.width).toBe('640px')
    expect(document.body.style.cursor).toBe('ew-resize')
    fireEvent(window, new MouseEvent('pointerup'))
    fireEvent(window, new MouseEvent('pointerup'))
    expect(onPanelWidthChange).toHaveBeenCalledExactlyOnceWith(640)
    expect(document.body.style.cursor).toBe('')
    expect(document.body.style.userSelect).toBe('')
  })

  it('cancels an unfinished resize when switching to compact layout', () => {
    const onPanelWidthChange = vi.fn()
    render(<Harness onPanelWidthChange={onPanelWidthChange} />)
    openSearch()
    const handle = screen.getByTestId('workspace-search-resize-handle')
    fireEvent(handle, new MouseEvent('pointerdown', { bubbles: true, button: 0, clientX: 600 }))
    fireEvent(window, new MouseEvent('pointermove', { clientX: 520 }))
    act(() => {
      vi.stubGlobal('innerWidth', 390)
      window.dispatchEvent(new Event('resize'))
    })
    fireEvent(window, new MouseEvent('pointerup'))
    expect(onPanelWidthChange).not.toHaveBeenCalled()
    expect(document.body.style.cursor).toBe('')
    expect(document.body.style.userSelect).toBe('')
    act(() => {
      vi.stubGlobal('innerWidth', 1200)
      window.dispatchEvent(new Event('resize'))
    })
    expect(screen.getByTestId('workspace-search').style.width).toBe('560px')
  })
})
