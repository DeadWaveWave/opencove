import { describe, expect, it, vi } from 'vitest'
import type {
  ContextMenuState,
  NodeDeleteConfirmationState,
  RoleCreatorState,
  SpaceActionMenuState,
  SpaceTargetMountPickerState,
  TaskEditorState,
} from '../components/workspaceCanvas/types'
import { createCanvasStore } from './canvasStore'

const paneMenu: ContextMenuState = { kind: 'pane', x: 10, y: 20, flowX: 1, flowY: 2 }
const selectionMenu: ContextMenuState = { kind: 'selection', x: 30, y: 40, nodeId: 'node-1' }
const spaceMenu: SpaceActionMenuState = { spaceId: 'space-1', x: 50, y: 60 }

const mountPicker: SpaceTargetMountPickerState = {
  nodeIds: ['node-1'],
  rect: null,
  mounts: [],
  selectedMountId: 'mount-1',
  anchor: { x: 1, y: 2 },
}
const taskEditor: TaskEditorState = {
  nodeId: 'task-1',
  initialTitle: 'Title',
  initialAutoGeneratedTitle: false,
  titleGeneratedInEditor: false,
  title: 'Title',
  requirement: 'Requirement',
  priority: 'medium',
  selectedTags: [],
  autoGenerateTitle: false,
  isGeneratingTitle: false,
  isSaving: false,
  error: null,
}
const roleCreator: RoleCreatorState = {
  anchor: { x: 0, y: 0 },
  mode: 'create',
  roleId: null,
  name: '',
  description: '',
  promptTemplate: '',
  inputHint: '',
  outputFormat: '',
  isCreating: false,
  error: null,
}
const deleteConfirmation: NodeDeleteConfirmationState = {
  nodeIds: ['node-1'],
  primaryNodeKind: 'note',
  primaryNodeTitle: 'Note',
  emptyingSpaces: [],
}

describe('canvas store', () => {
  it('starts with every menu, dialog and rename closed', () => {
    const closed = {
      contextMenu: null,
      spaceActionMenu: null,
      spaceRename: null,
      spaceTargetMountPicker: null,
      taskEditor: null,
      roleCreator: null,
      nodeDeleteConfirmation: null,
    }
    const { api } = createCanvasStore()

    expect(api.getState().ui).toEqual(closed)
    expect(api.getInitialState().ui).toEqual(closed)
  })

  it('notifies once per changing command', () => {
    const { api, commands } = createCanvasStore()
    const listener = vi.fn()
    api.subscribe(listener)

    commands.ui.openContextMenu(paneMenu)
    expect(listener).toHaveBeenCalledTimes(1)
    expect(api.getState().ui.contextMenu).toBe(paneMenu)

    commands.ui.openContextMenu(selectionMenu)
    expect(listener).toHaveBeenCalledTimes(2)
    expect(api.getState().ui.contextMenu).toBe(selectionMenu)

    commands.ui.closeContextMenu()
    expect(listener).toHaveBeenCalledTimes(3)
    expect(api.getState().ui.contextMenu).toBeNull()

    commands.ui.openSpaceActionMenu(spaceMenu)
    expect(listener).toHaveBeenCalledTimes(4)
    expect(api.getState().ui.spaceActionMenu).toBe(spaceMenu)

    commands.ui.closeSpaceActionMenu()
    expect(listener).toHaveBeenCalledTimes(5)
    expect(api.getState().ui.spaceActionMenu).toBeNull()
  })

  it('notifies nobody when a command changes nothing', () => {
    const { api, commands } = createCanvasStore()
    const listener = vi.fn()
    api.subscribe(listener)

    commands.ui.closeContextMenu()
    commands.ui.closeSpaceActionMenu()
    commands.ui.closeMenus()

    expect(listener).not.toHaveBeenCalled()
  })

  it('never has both menus open: each opener clears the other in the same update', () => {
    const { api, commands } = createCanvasStore()
    const seen: Array<{ contextMenu: unknown; spaceActionMenu: unknown }> = []
    api.subscribe(state => {
      seen.push({
        contextMenu: state.ui.contextMenu,
        spaceActionMenu: state.ui.spaceActionMenu,
      })
    })

    commands.ui.openSpaceActionMenu(spaceMenu)
    commands.ui.openContextMenu(paneMenu)
    commands.ui.openSpaceActionMenu(spaceMenu)

    expect(seen).toEqual([
      { contextMenu: null, spaceActionMenu: spaceMenu },
      { contextMenu: paneMenu, spaceActionMenu: null },
      { contextMenu: null, spaceActionMenu: spaceMenu },
    ])
  })

  it('closeMenus closes both menus in one notification', () => {
    const { api, commands } = createCanvasStore()
    commands.ui.openContextMenu(paneMenu)
    const listener = vi.fn()
    api.subscribe(listener)

    commands.ui.closeMenus()
    expect(listener).toHaveBeenCalledTimes(1)
    expect(api.getState().ui).toMatchObject({ contextMenu: null, spaceActionMenu: null })

    commands.ui.openSpaceActionMenu(spaceMenu)
    commands.ui.closeMenus()
    expect(api.getState().ui).toMatchObject({ contextMenu: null, spaceActionMenu: null })
  })

  it('keeps command and api identity stable across state changes', () => {
    const store = createCanvasStore()
    const { api, commands } = store
    const openContextMenu = commands.ui.openContextMenu
    const closeMenus = commands.ui.closeMenus
    const stateBefore = api.getState()

    commands.ui.openContextMenu(paneMenu)
    commands.ui.openSpaceActionMenu(spaceMenu)
    commands.ui.closeMenus()

    expect(api.getState()).not.toBe(stateBefore)
    expect(store.api).toBe(api)
    expect(store.commands).toBe(commands)
    expect(store.commands.ui.openContextMenu).toBe(openContextMenu)
    expect(store.commands.ui.closeMenus).toBe(closeMenus)
    expect(api.getInitialState()).toBe(stateBefore)
  })

  it('gives each store its own state', () => {
    const first = createCanvasStore()
    const second = createCanvasStore()

    first.commands.ui.openContextMenu(paneMenu)

    expect(second.api.getState().ui.contextMenu).toBeNull()
  })

  it('exposes no raw setState, in its type or at runtime', () => {
    const store = createCanvasStore()

    expect('setState' in store.api).toBe(false)
    // @ts-expect-error -- the canvas store exposes no raw setState; write through its commands (#647 S3)
    expect(() => store.api.setState({})).toThrow(TypeError)
  })

  describe('dialogs', () => {
    const dialogs = [
      ['spaceTargetMountPicker', mountPicker, { ...mountPicker, selectedMountId: 'mount-2' }],
      ['taskEditor', taskEditor, { ...taskEditor, title: 'Edited' }],
      ['roleCreator', roleCreator, { ...roleCreator, name: 'Reviewer' }],
      ['nodeDeleteConfirmation', deleteConfirmation, { ...deleteConfirmation, nodeIds: [] }],
    ] as const

    it.each(dialogs)('%s opens, updates and closes through the commands', (key, open, edited) => {
      const { api, commands } = createCanvasStore()
      const listener = vi.fn()
      api.subscribe(listener)

      commands.ui.openDialog(key, open as never)
      expect(api.getState().ui[key]).toBe(open)
      expect(listener).toHaveBeenCalledTimes(1)

      commands.ui.updateDialog(key, (() => edited) as never)
      expect(api.getState().ui[key]).toBe(edited)
      expect(listener).toHaveBeenCalledTimes(2)

      commands.ui.closeDialog(key)
      expect(api.getState().ui[key]).toBeNull()
      expect(listener).toHaveBeenCalledTimes(3)
    })

    it.each(dialogs)('%s: update and close on a closed dialog notify nobody', key => {
      const { api, commands } = createCanvasStore()
      const listener = vi.fn()
      api.subscribe(listener)
      const recipe = vi.fn()

      commands.ui.updateDialog(key, recipe as never)
      commands.ui.closeDialog(key)

      expect(recipe).not.toHaveBeenCalled()
      expect(api.getState().ui[key]).toBeNull()
      expect(listener).not.toHaveBeenCalled()
    })

    it('updating a dialog with an unchanged value notifies nobody and touches no other field', () => {
      const { api, commands } = createCanvasStore()
      commands.ui.openDialog('taskEditor', taskEditor)
      commands.ui.openContextMenu(paneMenu)
      const listener = vi.fn()
      api.subscribe(listener)

      commands.ui.updateDialog('taskEditor', current => current)
      expect(listener).not.toHaveBeenCalled()

      commands.ui.updateDialog('taskEditor', current => ({ ...current, requirement: 'More' }))
      expect(api.getState().ui.contextMenu).toBe(paneMenu)
      expect(api.getState().ui.taskEditor).toEqual({ ...taskEditor, requirement: 'More' })
    })

    it('keeps the dialogs independent of each other', () => {
      const { api, commands } = createCanvasStore()
      commands.ui.openDialog('taskEditor', taskEditor)
      commands.ui.openDialog('roleCreator', roleCreator)
      commands.ui.closeDialog('taskEditor')

      expect(api.getState().ui.taskEditor).toBeNull()
      expect(api.getState().ui.roleCreator).toBe(roleCreator)
    })
  })

  describe('space rename', () => {
    it('starts with the draft, clears the context menu and keeps the Space menu', () => {
      const { api, commands } = createCanvasStore()
      commands.ui.openContextMenu(paneMenu)
      const listener = vi.fn()
      api.subscribe(listener)

      commands.ui.startSpaceRename('space-1', 'Space 1')

      expect(listener).toHaveBeenCalledTimes(1)
      expect(api.getState().ui.spaceRename).toEqual({ spaceId: 'space-1', draft: 'Space 1' })
      expect(api.getState().ui.contextMenu).toBeNull()
    })

    it('changes the draft only while a rename is open', () => {
      const { api, commands } = createCanvasStore()
      const listener = vi.fn()
      api.subscribe(listener)

      commands.ui.setSpaceRenameDraft('ignored')
      expect(api.getState().ui.spaceRename).toBeNull()
      expect(listener).not.toHaveBeenCalled()

      commands.ui.startSpaceRename('space-1', 'Space 1')
      commands.ui.setSpaceRenameDraft('Renamed')
      expect(api.getState().ui.spaceRename).toEqual({ spaceId: 'space-1', draft: 'Renamed' })
      expect(listener).toHaveBeenCalledTimes(2)
    })

    it('cancels once and notifies nobody when nothing is being renamed', () => {
      const { api, commands } = createCanvasStore()
      const listener = vi.fn()
      api.subscribe(listener)

      commands.ui.cancelSpaceRename()
      expect(listener).not.toHaveBeenCalled()

      commands.ui.startSpaceRename('space-1', 'Space 1')
      commands.ui.cancelSpaceRename()
      expect(api.getState().ui.spaceRename).toBeNull()
      expect(listener).toHaveBeenCalledTimes(2)

      commands.ui.cancelSpaceRename()
      expect(listener).toHaveBeenCalledTimes(2)
    })
  })
})
