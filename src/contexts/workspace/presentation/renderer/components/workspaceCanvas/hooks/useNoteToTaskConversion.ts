import { useCallback, useMemo } from 'react'
import type { Node } from '@xyflow/react'
import { useTranslation } from '@app/renderer/i18n'
import type { StandardWindowSizeBucket } from '@contexts/settings/domain/agentSettings'
import type { TerminalNodeData } from '../../../types'
import { resolveDefaultTaskWindowSize } from '../constants'
import type { ShowWorkspaceCanvasMessage } from '../types'
import { resolveWorkspaceLayoutAfterNodeResize } from './useNodesStore.resolveResizeLayout'
import type { UseWorkspaceCanvasNodesStoreResult } from './useNodesStore.types'
import {
  useCanvasDocumentCommands,
  useCanvasUiCommands,
  useReadCanvasDocument,
  useReadCanvasSelection,
} from '../../../store/canvasStoreContext'

function toTaskNode(
  node: Node<TerminalNodeData>,
  requirement: string,
  title: string,
  now: string,
): Node<TerminalNodeData> {
  return {
    ...node,
    type: 'taskNode',
    selectable: true,
    data: {
      ...node.data,
      title,
      kind: 'task',
      task: {
        requirement,
        status: 'todo',
        priority: 'medium',
        tags: [],
        linkedAgentNodeId: null,
        agentSessions: [],
        lastRunAt: null,
        autoGeneratedTitle: false,
        createdAt: now,
        updatedAt: now,
      },
      note: null,
    },
  }
}

function resolveFallbackTaskTitle(requirement: string, fallbackTitle: string): string {
  const cleanedRequirement = requirement.replace(/\s+/g, ' ').trim()
  if (cleanedRequirement.length === 0) {
    return fallbackTitle
  }

  if (cleanedRequirement.length <= 24) {
    return cleanedRequirement
  }

  return `${cleanedRequirement.slice(0, 24)}...`
}

export function useWorkspaceCanvasNoteToTaskConversion({
  selectedNodeIds,
  flowNodes,
  updateCanvasDocument,
  onShowMessage,
  standardWindowSizeBucket,
}: {
  selectedNodeIds: readonly string[]
  flowNodes: Node<TerminalNodeData>[]
  updateCanvasDocument: UseWorkspaceCanvasNodesStoreResult['updateCanvasDocument']
  onShowMessage?: ShowWorkspaceCanvasMessage
  standardWindowSizeBucket: StandardWindowSizeBucket
}): {
  canConvertSelectedNoteToTask: boolean
  isConvertSelectedNoteToTaskDisabled: boolean
  convertSelectedNoteToTask: () => void
  convertNoteToTask: (nodeId: string) => boolean
} {
  const ui = useCanvasUiCommands()
  const readSelection = useReadCanvasSelection()
  const readDocument = useReadCanvasDocument()
  const { requestPersistFlush } = useCanvasDocumentCommands()

  const { t } = useTranslation()
  const selectedNoteMeta = useMemo(() => {
    if (selectedNodeIds.length !== 1) {
      return { canConvert: false, isDisabled: false }
    }

    const selectedId = selectedNodeIds[0]
    const selected = flowNodes.find(node => node.id === selectedId) ?? null

    if (!selected || selected.data.kind !== 'note') {
      return { canConvert: false, isDisabled: false }
    }

    const text = selected.data.note?.text ?? ''
    return { canConvert: true, isDisabled: text.trim().length === 0 }
  }, [flowNodes, selectedNodeIds])

  // Validates against the committed document, then converts and lays out in one store write that
  // is computed from the nodes and the Spaces of the document when it runs.
  const convertNoteToTask = useCallback(
    (nodeId: string): boolean => {
      const normalizedNodeId = nodeId.trim()
      if (normalizedNodeId.length === 0) {
        return false
      }

      const selected = readDocument().nodes.find(node => node.id === normalizedNodeId) ?? null
      if (!selected || selected.data.kind !== 'note' || !selected.data.note) {
        return false
      }

      if (selected.data.note.text.trim().length === 0) {
        onShowMessage?.(t('messages.noteToTaskRequiresContent'), 'warning')
        return false
      }

      const fallbackTitle = t('taskWindow.defaultTaskTitle')
      const defaultTaskSize = resolveDefaultTaskWindowSize(standardWindowSizeBucket)
      const now = new Date().toISOString()
      let didConvert = false

      updateCanvasDocument(({ nodes, spaces }) => {
        const target = nodes.find(node => node.id === normalizedNodeId)
        if (!target || target.data.kind !== 'note' || !target.data.note) {
          return { nodes, spaces }
        }

        const requirement = target.data.note.text.trim()
        if (requirement.length === 0) {
          return { nodes, spaces }
        }

        const title = resolveFallbackTaskTitle(requirement, fallbackTitle)
        const convertedNodes = nodes.map(node =>
          node === target ? toTaskNode(node, requirement, title, now) : node,
        )
        didConvert = true

        const resolvedLayout = resolveWorkspaceLayoutAfterNodeResize({
          nodeId: normalizedNodeId,
          desiredFrame: {
            position: target.position,
            size: defaultTaskSize,
          },
          nodes: convertedNodes,
          spaces,
          gap: 0,
        })

        return resolvedLayout
          ? { nodes: resolvedLayout.nodes, spaces: resolvedLayout.spaces }
          : { nodes: convertedNodes, spaces }
      })

      if (didConvert) {
        requestPersistFlush()
      }

      return didConvert
    },
    [
      onShowMessage,
      readDocument,
      requestPersistFlush,
      standardWindowSizeBucket,
      t,
      updateCanvasDocument,
    ],
  )

  const convertSelectedNoteToTask = useCallback(() => {
    const selectedIds = readSelection().nodeIds
    if (selectedIds.length !== 1) {
      ui.closeContextMenu()
      return
    }

    convertNoteToTask(selectedIds[0])
    ui.closeContextMenu()
  }, [convertNoteToTask, readSelection, ui])

  return {
    canConvertSelectedNoteToTask: selectedNoteMeta.canConvert,
    isConvertSelectedNoteToTaskDisabled: selectedNoteMeta.isDisabled,
    convertSelectedNoteToTask,
    convertNoteToTask,
  }
}
