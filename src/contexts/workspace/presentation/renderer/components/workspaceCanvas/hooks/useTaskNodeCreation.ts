import { useCallback } from 'react'
import { resolvePaneNodeCreationAnchor } from './useInteractions.creationAnchor'
import type { Node } from '@xyflow/react'
import { useTranslation } from '@app/renderer/i18n'
import type { StandardWindowSizeBucket } from '@contexts/settings/domain/agentSettings'
import type { Point, TaskPriority, TerminalNodeData } from '../../../types'
import { resolveDefaultTaskWindowSize } from '../constants'
import { resolveNodePlacementAnchorFromViewportCenter } from '../helpers'
import type { NodePlacementOptions } from '../types'
import {
  assignNodeToSpaceAndExpand,
  findContainingSpaceByAnchor,
} from './useInteractions.spaceAssignment'
import { useCanvasNodeWriter } from './useCanvasNodeWriter'
import {
  useCanvasDocumentCommands,
  useCanvasUiCommands,
  useReadCanvasDocument,
  useReadCanvasUi,
} from '../../../store/canvasStoreContext'

interface UseTaskNodeCreationParams {
  workspaceId?: string
  standardWindowSizeBucket: StandardWindowSizeBucket
  createTaskNode: (
    anchor: Point,
    title: string,
    requirement: string,
    autoGeneratedTitle: boolean,
    priority: TaskPriority,
    tags: string[],
    placement?: NodePlacementOptions,
  ) => Node<TerminalNodeData> | null
}

export function useWorkspaceCanvasTaskNodeCreation({
  workspaceId,
  standardWindowSizeBucket,
  createTaskNode,
}: UseTaskNodeCreationParams): {
  createTaskAtPoint: (anchor: Point) => void
  createTaskFromContextMenu: () => void
} {
  const ui = useCanvasUiCommands()
  const readUi = useReadCanvasUi()
  const readDocument = useReadCanvasDocument()
  const documentCommands = useCanvasDocumentCommands()
  const { updateCanvasDocument } = useCanvasNodeWriter()

  const { t } = useTranslation()
  const createTaskAtAnchor = useCallback(
    (anchor: Point): void => {
      const placementAnchor = resolveNodePlacementAnchorFromViewportCenter(
        anchor,
        resolveDefaultTaskWindowSize(standardWindowSizeBucket),
      )
      const targetSpace = findContainingSpaceByAnchor(readDocument().spaces, anchor) ?? null
      const created = createTaskNode(
        placementAnchor,
        t('taskWindow.defaultTaskTitle'),
        '',
        false,
        'medium',
        [],
        { targetSpaceRect: targetSpace?.rect ?? null },
      )

      if (!created) {
        return
      }

      if (targetSpace) {
        assignNodeToSpaceAndExpand({
          workspaceId,
          createdNodeId: created.id,
          targetSpaceId: targetSpace.id,
          updateCanvasDocument,
        })
      }

      // The creator wrote the node, and the assignment above the Space; the flush follows them.
      documentCommands.requestPersistFlush()
    },
    [
      workspaceId,
      createTaskNode,
      documentCommands,
      readDocument,
      standardWindowSizeBucket,
      t,
      updateCanvasDocument,
    ],
  )

  const createTaskFromContextMenu = useCallback(() => {
    const contextMenu = readUi().contextMenu
    if (!contextMenu || contextMenu.kind !== 'pane') {
      return
    }

    createTaskAtAnchor(resolvePaneNodeCreationAnchor(contextMenu))
    ui.closeContextMenu()
  }, [createTaskAtAnchor, readUi, ui])

  return {
    createTaskAtPoint: createTaskAtAnchor,
    createTaskFromContextMenu,
  }
}
